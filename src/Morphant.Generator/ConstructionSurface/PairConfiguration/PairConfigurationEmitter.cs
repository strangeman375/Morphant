using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.ConstructionSurface.ConstructionPlan;

namespace Morphant.Generator.ConstructionSurface.PairConfiguration;

internal static class PairConfigurationEmitter
{
    public static string Emit(PairConfigurationModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        writer.OpenBlock("namespace Morphant");
        writer.OpenBlock(
            "internal static partial class " +
            model.ExtensionContainerTypeName);

        var hasPreviousMethod = false;

        void Separate()
        {
            if (hasPreviousMethod)
            {
                writer.Line();
            }

            hasPreviousMethod = true;
        }

        if (model.HasStructuredConstruction)
        {
            Separate();
            WriteMethod(
                writer,
                model,
                "Construct",
                "construct",
                "Supplies constructor arguments when no destination exists.",
                "Inline lambda returning a construction expression.",
                "global::Morphant.Delegates.Construct<" +
                model.DeclarativeSourceTypeName + ", " +
                model.ConstructionResultTypeName + ">");
            Separate();
            WriteMethod(
                writer,
                model,
                "Construct",
                "construct",
                "Supplies constructor arguments when no destination exists.",
                "Inline lambda returning a construction expression.",
                "global::Morphant.Delegates.Construct<" +
                model.DeclarativeSourceTypeName + ", " +
                "global::Morphant.Context.MappingContextMarker, " +
                model.ConstructionResultTypeName + ">");
            Separate();
            WriteMethod(
                writer,
                model,
                "Resolve",
                "resolve",
                "Chooses reuse or construction on Create and Update.",
                "Inline lambda returning the existing destination value or a construction expression.",
                "global::Morphant.Delegates.Resolve<" +
                model.DeclarativeSourceTypeName + ", " +
                model.PreviousDestinationTypeName + ", " +
                model.ConstructionResultTypeName + ">");
            Separate();
            WriteMethod(
                writer,
                model,
                "Resolve",
                "resolve",
                "Chooses reuse or construction on Create and Update.",
                "Inline lambda returning the existing destination value or a construction expression.",
                "global::Morphant.Delegates.Resolve<" +
                model.DeclarativeSourceTypeName + ", " +
                model.PreviousDestinationTypeName + ", " +
                "global::Morphant.Context.MappingContextMarker, " +
                model.ConstructionResultTypeName + ">");
        }

        Separate();
        WriteMethod(
            writer,
            model,
            "ConstructUsing",
            "construct",
            "Creates a destination through a callback only when none exists.",
            "Callback returning the destination; null ends the mapping.",
            "global::Morphant.Delegates.ConstructUsing<" +
            model.DeclarativeSourceTypeName + ", " +
            model.DestinationTypeName + ">");
        Separate();
        WriteMethod(
            writer,
            model,
            "ConstructUsing",
            "construct",
            "Creates a destination through a callback only when none exists.",
            "Callback returning the destination; null ends the mapping.",
            "global::Morphant.Delegates.ConstructUsing<" +
            model.DeclarativeSourceTypeName + ", " +
            "global::Morphant.Context.MappingContext, " +
            model.DestinationTypeName + ">");
        Separate();
        WriteMethod(
            writer,
            model,
            "ResolveUsing",
            "resolve",
            "Chooses the destination through a callback on Create and Update.",
            "Callback returning the destination; null ends the mapping.",
            "global::Morphant.Delegates.ResolveUsing<" +
            model.DeclarativeSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            model.DestinationTypeName + ">");
        Separate();
        WriteMethod(
            writer,
            model,
            "ResolveUsing",
            "resolve",
            "Chooses the destination through a callback on Create and Update.",
            "Callback returning the destination; null ends the mapping.",
            "global::Morphant.Delegates.ResolveUsing<" +
            model.DeclarativeSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            "global::Morphant.Context.MappingContext, " +
            model.DestinationTypeName + ">");
        Separate();
        WriteMethod(
            writer,
            model,
            "Convert",
            "mapping",
            "Maps with ordinary C#, bypassing null policies and member rules.",
            "Lambda, method group, or delegate returning the final result.",
            "global::Morphant.Delegates.Convert<" +
            model.ManualSourceTypeName + ", " +
            model.DestinationTypeName + ">");
        Separate();
        WriteMethod(
            writer,
            model,
            "Convert",
            "mapping",
            "Maps with ordinary C#, bypassing null policies and member rules.",
            "Lambda, method group, or delegate returning the final result.",
            "global::Morphant.Delegates.Convert<" +
            model.ManualSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            model.DestinationTypeName + ">");
        Separate();
        WriteMethod(
            writer,
            model,
            "Convert",
            "mapping",
            "Maps with ordinary C#, bypassing null policies and member rules.",
            "Lambda, method group, or delegate returning the final result.",
            "global::Morphant.Delegates.Convert<" +
            model.ManualSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            "global::Morphant.Context.MappingContext, " +
            model.DestinationTypeName + ">");

        writer.CloseBlock();
        writer.CloseBlock();

        return writer.ToString();
    }

    private static void WriteMethod(
        CodeWriter writer,
        PairConfigurationModel model,
        string methodName,
        string callbackName,
        string summary,
        string callbackDescription,
        string delegateTypeName)
    {
        WriteSummary(writer, summary);
        WriteTypeParameterDocumentation(writer, model.TypeParameters);
        WriteParameterDocumentation(
            writer,
            "builder",
            "The mapping to configure.");
        WriteParameterDocumentation(
            writer,
            callbackName,
            callbackDescription);
        var documentationPage = methodName switch
        {
            "ConstructUsing" => "construct-using",
            "ResolveUsing" => "resolve-using",
            _ => methodName.ToLowerInvariant()
        };
        writer.Line(
            "/// <seealso href=\"https://github.com/strangeman375/Morphant/blob/main/docs/api/" +
            documentationPage + ".md\"/>");

        writer.Line(
            "public static " +
            model.BuilderTypeName +
            " " +
            methodName +
            BuildTypeParameterList(model.TypeParameters) +
            "(");
        writer.Line($"    this {model.ReceiverTypeName} builder,");
        writer.Line($"    {delegateTypeName} {callbackName})");
        WriteMethodEnd(writer, model.TypeParameters);
    }

    private static void WriteMethodEnd(
        CodeWriter writer,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        writer.Indent();
        var annotationsAreDisabled = false;

        foreach (var typeParameter in typeParameters)
        {
            if (typeParameter.Constraints.IsEmpty)
            {
                continue;
            }

            if (typeParameter.RequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    typeParameter.RequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");
                annotationsAreDisabled =
                    typeParameter.RequiresNullableAnnotationsDisabled;
            }

            writer.Line(
                "where " +
                Identifier(typeParameter.Name) +
                " : " +
                string.Join(", ", typeParameter.Constraints));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Line(
            "=> throw new global::Morphant.Exceptions." +
            "RuntimeInvocationNotSupportedException();");
        writer.Unindent();
    }

    private static string BuildTypeParameterList(
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        return typeParameters.Count == 0
            ? string.Empty
            : "<" +
              string.Join(
                  ", ",
                  typeParameters.Select(static parameter =>
                      Identifier(parameter.Name))) +
              ">";
    }

    private static void WriteTypeParameterDocumentation(
        CodeWriter writer,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        foreach (var typeParameter in typeParameters)
        {
            writer.Line(
                "/// <typeparam name=\"" +
                XmlAttribute(typeParameter.Name) +
                "\">A type parameter from the mapping declaration.</typeparam>");
        }
    }

    private static void WriteSummary(CodeWriter writer, string summary)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {summary}");
        writer.Line("/// </summary>");
    }

    private static void WriteParameterDocumentation(
        CodeWriter writer,
        string parameterName,
        string description)
    {
        writer.Line(
            "/// <param name=\"" +
            XmlAttribute(parameterName) +
            "\">" +
            XmlText(description) +
            "</param>");
    }

    private static string XmlAttribute(string value)
    {
        return XmlText(value)
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
}
