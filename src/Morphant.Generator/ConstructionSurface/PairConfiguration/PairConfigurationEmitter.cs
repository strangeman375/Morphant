using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.ConstructionSurface.ConstructionPlan;

namespace Morphant.Generator.ConstructionSurface.PairConfiguration;

internal static class PairConfigurationEmitter
{
    public static string Emit(PairConfigurationModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        writer.OpenBlock("namespace Morphant");
        writer.OpenBlock(
            "internal static partial class " +
            "MorphantGeneratedMappingExtensions");

        WriteSourceOnlyConstruct(writer, model);
        writer.Line();
        WritePreviousAwareConstruct(writer, model);
        writer.Line();
        WriteConvert(writer, model);

        writer.CloseBlock();
        writer.CloseBlock();

        return writer.ToString();
    }

    private static void WriteSourceOnlyConstruct(
        CodeWriter writer,
        PairConfigurationModel model)
    {
        WriteSummary(
            writer,
            "Configures how to construct a destination when no existing " +
            "destination is used.");
        WriteTypeParameterDocumentation(writer, model.TypeParameters);
        WriteParameterDocumentation(
            writer,
            "builder",
            "The mapping builder to configure.");
        WriteParameterDocumentation(
            writer,
            "construct",
            "A lambda expression that receives the non-null source and " +
            "describes destination construction.");
        WriteReturnsDocumentation(writer);

        WriteMethodStart(writer, model, "Construct");
        writer.Line($"    this {model.BuilderTypeName} builder,");
        writer.Line(
            "    global::Morphant.Delegates.Construct<" +
            model.DeclarativeSourceTypeName +
            ", " +
            model.ConstructionResultTypeName +
            "> construct)");
        WriteMethodEnd(writer, model.TypeParameters);
    }

    private static void WritePreviousAwareConstruct(
        CodeWriter writer,
        PairConfigurationModel model)
    {
        WriteSummary(
            writer,
            "Configures how to select or construct the destination from " +
            "the source and an optional existing destination.");
        WriteTypeParameterDocumentation(writer, model.TypeParameters);
        WriteParameterDocumentation(
            writer,
            "builder",
            "The mapping builder to configure.");
        WriteParameterDocumentation(
            writer,
            "construct",
            "A lambda expression that receives the non-null source and " +
            "the optional existing destination and describes destination " +
            "construction.");
        WriteReturnsDocumentation(writer);

        WriteMethodStart(writer, model, "Construct");
        writer.Line($"    this {model.BuilderTypeName} builder,");
        writer.Line(
            "    global::Morphant.Delegates.Construct<" +
            model.DeclarativeSourceTypeName +
            ", " +
            model.PreviousDestinationTypeName +
            ", " +
            model.ConstructionResultTypeName +
            "> construct)");
        WriteMethodEnd(writer, model.TypeParameters);
    }

    private static void WriteConvert(
        CodeWriter writer,
        PairConfigurationModel model)
    {
        WriteSummary(
            writer,
            "Configures a fully manual mapping algorithm.");
        WriteTypeParameterDocumentation(writer, model.TypeParameters);
        WriteParameterDocumentation(
            writer,
            "builder",
            "The mapping builder to configure.");
        WriteParameterDocumentation(
            writer,
            "mapping",
            "A lambda expression that receives the original source, the " +
            "optional existing destination, and the current mapping context.");
        WriteReturnsDocumentation(writer);

        WriteMethodStart(writer, model, "Convert");
        writer.Line($"    this {model.BuilderTypeName} builder,");
        writer.Line(
            "    global::Morphant.Delegates.Convert<" +
            model.ManualSourceTypeName +
            ", " +
            model.PreviousDestinationTypeName +
            ", " +
            model.DestinationTypeName +
            "> mapping)");
        WriteMethodEnd(writer, model.TypeParameters);
    }

    private static void WriteMethodStart(
        CodeWriter writer,
        PairConfigurationModel model,
        string methodName)
    {
        writer.Line(
            "public static " +
            model.BuilderTypeName +
            " " +
            methodName +
            BuildTypeParameterList(model.TypeParameters) +
            "(");
    }

    private static void WriteMethodEnd(
        CodeWriter writer,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        writer.Indent();
        var annotationsAreDisabled = false;

        foreach (var typeParameter in typeParameters)
        {
            if (typeParameter.Constraints.IsEmpty)
            {
                continue;
            }

            if (typeParameter.RequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    typeParameter.RequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");
                annotationsAreDisabled =
                    typeParameter.RequiresNullableAnnotationsDisabled;
            }

            writer.Line(
                "where " +
                Identifier(typeParameter.Name) +
                " : " +
                string.Join(", ", typeParameter.Constraints));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Line(
            "=> throw new global::Morphant.Exceptions." +
            "RuntimeInvocationNotSupportedException();");
        writer.Unindent();
    }

    private static string BuildTypeParameterList(
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        return typeParameters.Count == 0
            ? string.Empty
            : "<" +
              string.Join(
                  ", ",
                  typeParameters.Select(static parameter =>
                      Identifier(parameter.Name))) +
              ">";
    }

    private static void WriteTypeParameterDocumentation(
        CodeWriter writer,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        foreach (var typeParameter in typeParameters)
        {
            writer.Line(
                "/// <typeparam name=\"" +
                XmlAttribute(typeParameter.Name) +
                "\">A type used by the mapping pair.</typeparam>");
        }
    }

    private static void WriteReturnsDocumentation(CodeWriter writer)
    {
        writer.Line(
            "/// <returns>The <paramref name=\"builder\"/> instance.</returns>");
    }

    private static void WriteSummary(CodeWriter writer, string summary)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {summary}");
        writer.Line("/// </summary>");
    }

    private static void WriteParameterDocumentation(
        CodeWriter writer,
        string parameterName,
        string description)
    {
        writer.Line(
            "/// <param name=\"" +
            XmlAttribute(parameterName) +
            "\">" +
            XmlText(description) +
            "</param>");
    }

    private static string XmlAttribute(string value)
    {
        return XmlText(value)
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
}
