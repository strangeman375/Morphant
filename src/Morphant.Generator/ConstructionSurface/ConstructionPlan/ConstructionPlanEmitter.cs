using Microsoft.CodeAnalysis.CSharp;

namespace Morphant.Generator.ConstructionSurface.ConstructionPlan;

internal static class ConstructionPlanEmitter
{
    public static string Emit(ConstructionPlanModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        writer.OpenBlock($"namespace {model.Namespace}");

        if (!model.ConstructorParameterFields.IsEmpty)
        {
            WriteConstructorParametersType(writer, model);
            writer.Line();
        }

        WriteConstructionType(writer, model);
        writer.CloseBlock();

        return writer.ToString();
    }

    private static void WriteConstructorParametersType(
        CodeWriter writer,
        ConstructionPlanModel model)
    {
        var typeReference = BuildTypeReference(
            Identifier(model.ConstructorParametersTypeName),
            model.TypeParameters);
        var destinationCref = XmlAttribute(
            model.DestinationDocumentation.Cref);

        WriteSummary(
            writer,
            "Contains mappings for constructor arguments of " +
            $"<see cref=\"{destinationCref}\"/>.");
        WriteTypeDeclaration(
            writer,
            $"internal sealed class {typeReference}",
            model.TypeParameters);

        for (var index = 0;
             index < model.ConstructorParameterFields.Length;
             index++)
        {
            var field = model.ConstructorParameterFields[index];

            ToggleNullableAnnotations(
                writer,
                field.RequiresNullableAnnotationsDisabled,
                index > 0 &&
                model.ConstructorParameterFields[index - 1]
                    .RequiresNullableAnnotationsDisabled);

            WriteSummary(
                writer,
                "Configures the " +
                $"<c>{XmlText(field.ParameterName)}</c> " +
                "constructor argument.");
            writer.Line(
                "public global::Morphant.Members.ConstructorParameter<" +
                field.TypeName +
                ">" +
                (field.AcceptsNull ? "?" : string.Empty) +
                " " +
                Identifier(field.Name) +
                " = null!;");

            var nextRequiresDisabled =
                index + 1 < model.ConstructorParameterFields.Length &&
                model.ConstructorParameterFields[index + 1]
                    .RequiresNullableAnnotationsDisabled;

            if (field.RequiresNullableAnnotationsDisabled &&
                !nextRequiresDisabled)
            {
                writer.Line("#nullable enable annotations");
            }

            if (index < model.ConstructorParameterFields.Length - 1)
            {
                writer.Line();
            }
        }

        writer.CloseBlock();
    }

    private static void WriteConstructionType(
        CodeWriter writer,
        ConstructionPlanModel model)
    {
        var typeName = Identifier(model.TypeName);
        var typeReference = BuildTypeReference(
            typeName,
            model.TypeParameters);

        WriteTypeDocumentation(writer, model);

        if (model.ObsoleteAttributeSource is { } obsoleteAttribute)
        {
            writer.Line($"[{obsoleteAttribute}]");
        }

        WriteTypeDeclaration(
            writer,
            $"internal sealed class {typeReference}",
            model.TypeParameters);

        WriteByConventionConstructor(writer, model, typeName);
        writer.Line();
        WriteByFactoryConstructor(writer, model, typeName);
        writer.Line();

        foreach (var constructor in model.Constructors)
        {
            WriteDestinationConstructorDocumentation(writer, constructor);

            if (constructor.ObsoleteAttributeSource is { } constructorObsolete)
            {
                writer.Line($"[{constructorObsolete}]");
            }

            var parameters = constructor.Parameters
                .Select(FormatParameter)
                .ToArray();
            var nullableAnnotationsDisabled = constructor.Parameters
                .Select(static parameter =>
                    parameter.RequiresNullableAnnotationsDisabled)
                .ToArray();

            WriteConstructor(
                writer,
                typeName,
                parameters,
                nullableAnnotationsDisabled);
            writer.Line();
        }

        WritePreviousConversion(writer, model, typeReference);
        writer.CloseBlock();
    }

    private static void WriteByConventionConstructor(
        CodeWriter writer,
        ConstructionPlanModel model,
        string typeName)
    {
        WriteSummary(
            writer,
            "Creates a destination instance using convention-based mapping.");
        WriteParameterDocumentation(
            writer,
            "marker",
            "Selects convention-based construction.");

        if (model.ConstructorParameterFields.IsEmpty)
        {
            WriteConstructor(
                writer,
                typeName,
                new[]
                {
                    "global::Morphant.Markers.ByConventionMarker marker"
                });
            return;
        }

        WriteParameterDocumentation(
            writer,
            "parameters",
            "Specifies optional mappings for constructor arguments.");
        WriteConstructor(
            writer,
            typeName,
            new[]
            {
                "global::Morphant.Markers.ByConventionMarker marker",
                BuildTypeReference(
                    Identifier(model.ConstructorParametersTypeName),
                    model.TypeParameters) +
                "? parameters = null"
            });
    }

    private static void WriteByFactoryConstructor(
        CodeWriter writer,
        ConstructionPlanModel model,
        string typeName)
    {
        WriteSummary(
            writer,
            "Creates a destination instance using factory-based construction.");
        WriteParameterDocumentation(
            writer,
            "marker",
            "Selects factory-based construction.");
        WriteConstructor(
            writer,
            typeName,
            new[]
            {
                "global::Morphant.Markers.IByFactoryMarker<" +
                model.DestinationTypeName +
                "> marker"
            });
    }

    private static void WritePreviousConversion(
        CodeWriter writer,
        ConstructionPlanModel model,
        string typeReference)
    {
        WriteSummary(
            writer,
            "Selects an existing destination as the mapping result.");
        WriteParameterDocumentation(
            writer,
            "previous",
            "The existing destination to select.");
        writer.Line(
            $"public static implicit operator {typeReference}(");
        writer.Line(
            "    global::Morphant.Option<" +
            model.DestinationTypeName +
            "> previous) =>");
        writer.Line(
            "    throw new global::Morphant.Exceptions." +
            "RuntimeInvocationNotSupportedException();");
    }

    private static void WriteTypeDocumentation(
        CodeWriter writer,
        ConstructionPlanModel model)
    {
        var documentation = model.DestinationDocumentation;
        var cref = XmlAttribute(documentation.Cref);

        if (documentation.HasDocumentation)
        {
            writer.Line($"/// <inheritdoc cref=\"{cref}\"/>");
            return;
        }

        WriteSummary(
            writer,
            "Describes construction of " +
            $"<see cref=\"{cref}\"/>.");
    }

    private static void WriteDestinationConstructorDocumentation(
        CodeWriter writer,
        ConstructionConstructorModel constructor)
    {
        if (constructor.Documentation.HasDocumentation)
        {
            writer.Line(
                "/// <inheritdoc cref=\"" +
                XmlAttribute(constructor.Documentation.Cref) +
                "\"/>");
            return;
        }

        WriteSummary(
            writer,
            "Creates a destination instance using a corresponding constructor.");

        foreach (var parameter in constructor.Parameters)
        {
            WriteParameterDocumentation(
                writer,
                parameter.Name,
                BuildConstructorParameterDescription(parameter));
        }
    }

    private static string BuildConstructorParameterDescription(
        ConstructionConstructorParameterModel parameter)
    {
        var description =
            "Configures the " +
            $"<c>{XmlText(parameter.Name)}</c> " +
            "constructor argument.";

        return parameter.DefaultValueDisplay is not { } defaultValue
            ? description
            : description +
              " If omitted, the destination constructor default value " +
              $"<c>{XmlText(defaultValue)}</c> is used.";
    }

    private static string FormatParameter(
        ConstructionConstructorParameterModel parameter)
    {
        var wrapperType =
            "global::Morphant.Members.ConstructorParameter<" +
            parameter.TypeName +
            ">";

        if (parameter.AcceptsNull)
        {
            wrapperType += "?";
        }

        return parameter.IsOptional
            ? wrapperType +
              " " +
              Identifier(parameter.Name) +
              " = " +
              (parameter.AcceptsNull ? "null" : "null!")
            : wrapperType +
              " " +
              Identifier(parameter.Name);
    }

    private static void WriteConstructor(
        CodeWriter writer,
        string typeName,
        IReadOnlyList<string> parameters,
        IReadOnlyList<bool>? nullableAnnotationsDisabled = null)
    {
        if (parameters.Count <= 1)
        {
            var parameter = parameters.Count == 0
                ? string.Empty
                : parameters[0];
            var annotationsDisabled =
                nullableAnnotationsDisabled is not null &&
                nullableAnnotationsDisabled.Count == 1 &&
                nullableAnnotationsDisabled[0];

            if (annotationsDisabled)
            {
                writer.Line("#nullable disable annotations");
            }

            writer.Line($"public {typeName}({parameter})");
            writer.EmptyBlock();

            if (annotationsDisabled)
            {
                writer.Line("#nullable enable annotations");
            }

            return;
        }

        writer.Line($"public {typeName}(");
        writer.Indent();
        var annotationsAreDisabled = false;

        for (var index = 0; index < parameters.Count; index++)
        {
            var parameterRequiresDisabled =
                nullableAnnotationsDisabled is not null &&
                nullableAnnotationsDisabled[index];

            if (parameterRequiresDisabled != annotationsAreDisabled)
            {
                writer.Line(
                    parameterRequiresDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");
                annotationsAreDisabled = parameterRequiresDisabled;
            }

            writer.Line(
                parameters[index] +
                (index == parameters.Count - 1 ? ")" : ","));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Unindent();
        writer.EmptyBlock();
    }

    private static void WriteTypeDeclaration(
        CodeWriter writer,
        string declaration,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        if (typeParameters.All(static parameter =>
                parameter.Constraints.IsEmpty))
        {
            writer.OpenBlock(declaration);
            return;
        }

        writer.Line(declaration);
        writer.Indent();
        var annotationsAreDisabled = false;

        foreach (var typeParameter in typeParameters)
        {
            if (typeParameter.Constraints.IsEmpty)
            {
                continue;
            }

            if (typeParameter.RequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    typeParameter.RequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");
                annotationsAreDisabled =
                    typeParameter.RequiresNullableAnnotationsDisabled;
            }

            writer.Line(
                "where " +
                Identifier(typeParameter.Name) +
                " : " +
                string.Join(", ", typeParameter.Constraints));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Unindent();
        writer.Line("{");
        writer.Indent();
    }

    private static string BuildTypeReference(
        string typeName,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        return typeParameters.Count == 0
            ? typeName
            : typeName +
              "<" +
              string.Join(
                  ", ",
                  typeParameters.Select(static parameter =>
                      Identifier(parameter.Name))) +
              ">";
    }

    private static void ToggleNullableAnnotations(
        CodeWriter writer,
        bool requiresDisabled,
        bool previousRequiresDisabled)
    {
        if (requiresDisabled == previousRequiresDisabled)
        {
            return;
        }

        writer.Line(
            requiresDisabled
                ? "#nullable disable annotations"
                : "#nullable enable annotations");
    }

    private static void WriteSummary(CodeWriter writer, string summary)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {summary}");
        writer.Line("/// </summary>");
    }

    private static void WriteParameterDocumentation(
        CodeWriter writer,
        string parameterName,
        string description)
    {
        writer.Line(
            $"/// <param name=\"{XmlAttribute(parameterName)}\">" +
            $"{description}</param>");
    }

    private static string XmlAttribute(string value)
    {
        return XmlText(value)
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
}
