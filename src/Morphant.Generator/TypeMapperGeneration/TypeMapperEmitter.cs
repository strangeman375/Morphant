    private static void WriteControlFlowUpdateNode(
        CodeWriter writer,
        TypeMapperControlFlowNode node,
        GeneratedLocalNameAllocator localNames)
    {
        WriteLocalValues(
            writer,
            node.Locals);

        if (node.EvaluationExpression is
                { } evaluationExpression)
        {
            WriteEvaluation(
                writer,
                evaluationExpression,
                node.EvaluationCondition,
                node.EvaluationLocals);
            WriteControlFlowUpdateNode(
                writer,
                node.EvaluationContinuation!,
                localNames);
            return;
        }

        if (node.SwitchExpression is
                { } switchExpression)
        {
            writer.Line($"switch ({switchExpression})");
            writer.Line("{");
            writer.Indent();

            foreach (var section in node.SwitchSections)
            {
                foreach (var label in section.Labels)
                {
                    writer.Line(label);
                }

                writer.Line("{");
                writer.Indent();
                WriteControlFlowUpdateNode(
                    writer,
                    section.Branch,
                    localNames);
                writer.Unindent();
                writer.Line("}");
            }

            writer.Unindent();
            writer.Line("}");

            if (node.SwitchContinuation is
                    { } continuation)
            {
                writer.Line();
                WriteControlFlowUpdateNode(
                    writer,
                    continuation,
                    localNames);
            }

            return;
        }

        if (node.Condition is { } condition)
        {
            writer.Line($"if ({condition})");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowUpdateNode(
                writer,
                node.WhenTrue!,
                localNames);
            writer.Unindent();
            writer.Line("}");
            writer.Line("else");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowUpdateNode(
                writer,
                node.WhenFalse!,
                localNames);
            writer.Unindent();
            writer.Line("}");
            return;
        }

        if (node.ThrowExpression is { } throwExpression)
        {
            var resolvedThrowExpression = ResolveThrowExpression(
                throwExpression,
                node.ThrowUsesCurrentMappingOperation,
                MappingOperationExpression(update: true));
            writer.Line($"throw {resolvedThrowExpression};");
            return;
        }

        WriteUpdateLeafStatements(
            writer,
            node.Leaf!.Value,
            allowReplacement: true,
            localNames: localNames);
    }

    private static void WriteUpdateLeafStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        bool allowReplacement,
        GeneratedLocalNameAllocator localNames)
    {
        if (mapping.Failure is
            { } unsupportedMappingMessage)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                unsupportedMappingMessage,
                update: true);
            return;
        }

        if (mapping.UpdateFailure is
            { } unsupportedExceptionMessage)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                unsupportedExceptionMessage,
                update: true);
            return;
        }

        if (mapping.UpdateDirectExpression is
            { } directExpression)
        {
            writer.Line($"return {directExpression};");
            return;
        }

        if (allowReplacement &&
            mapping.CreateFactory is { } factory)
        {
            WriteFactoryCreateStatements(
                writer,
                mapping,
                factory,
                MappingOperationExpression(update: true),
                localNames);
            return;
        }

        if (allowReplacement &&
            mapping.CreateConstructor is { } constructor)
        {
            WriteConstructorCreateStatements(
                writer,
                mapping,
                constructor,
                MappingOperationExpression(update: true),
                localNames);
            return;
        }

        if (mapping.UpdateKind ==
            TypeMapperUpdateKind.Unsupported)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                "Morphant could not generate Update for this mapping.",
                update: true);
            return;
        }

        if (mapping.PostMemberControlFlow is { } postControlFlow)
        {
            WritePostMemberControlFlow(
                writer,
                mapping,
                postControlFlow,
                "destination",
                localNames,
                operationExpression:
                    MappingOperationExpression(update: true));
            return;
        }

        if (mapping.UpdateMemberMappings.IsEmpty)
        {
            writer.Line("return destination;");
            return;
        }

        WriteMemberValueLocals(
            writer,
            mapping.UpdateMemberMappings);

        foreach (var memberMapping in
                 mapping.UpdateMemberMappings)
        {
            WriteInvocationArgumentLocals(writer, memberMapping);
            writer.Line(
                "destination." +
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(
                    mapping,
                    memberMapping,
                    localNames) +
                ";");
        }

        writer.Line();
        writer.Line("return destination;");
    }

    private static void WritePostMemberControlFlow(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        TypeMapperMemberControlFlowNode node,
        string assignmentTarget,
        GeneratedLocalNameAllocator localNames,
        string? returnExpression = null,
        string? operationExpression = null)
    {
        operationExpression ??=
            MappingOperationExpression(update: false);

        WriteLocalValues(writer, node.Locals);

        if (node.EvaluationExpression is { } evaluationExpression)
        {
            WriteEvaluation(
                writer,
                evaluationExpression,
                node.EvaluationCondition,
                node.EvaluationLocals);
            WritePostMemberControlFlow(
                writer,
                mapping,
                node.EvaluationContinuation!,
                assignmentTarget,
                localNames,
                returnExpression,
                operationExpression);
            return;
        }

        if (node.SwitchExpression is { } switchExpression)
        {
            writer.Line($"switch ({switchExpression})");
            writer.Line("{");
            writer.Indent();

            foreach (var section in node.SwitchSections)
            {
                foreach (var label in section.Labels)
                {
                    writer.Line(label);
                }

                writer.Line("{");
                writer.Indent();
                WritePostMemberControlFlow(
                    writer,
                    mapping,
                    section.Branch,
                    assignmentTarget,
                    localNames,
                    returnExpression,
                    operationExpression);
                writer.Unindent();
                writer.Line("}");
            }

            writer.Unindent();
            writer.Line("}");

            if (node.SwitchContinuation is { } continuation)
            {
                writer.Line();
                WritePostMemberControlFlow(
                    writer,
                    mapping,
                    continuation,
                    assignmentTarget,
                    localNames,
                    returnExpression,
                    operationExpression);
            }

            return;
        }

        if (node.Condition is { } condition)
        {
            writer.Line($"if ({condition})");
            writer.Line("{");
            writer.Indent();
            WritePostMemberControlFlow(
                writer,
                mapping,
                node.WhenTrue!,
                assignmentTarget,
                localNames,
                returnExpression,
                operationExpression);
            writer.Unindent();
            writer.Line("}");
            writer.Line("else");
            writer.Line("{");
            writer.Indent();
            WritePostMemberControlFlow(
                writer,
                mapping,
                node.WhenFalse!,
                assignmentTarget,
                localNames,
                returnExpression,
                operationExpression);
            writer.Unindent();
            writer.Line("}");
            return;
        }

        if (node.ThrowExpression is { } throwExpression)
        {
            var resolvedThrowExpression = ResolveThrowExpression(
                throwExpression,
                node.ThrowUsesCurrentMappingOperation,
                operationExpression);
            writer.Line($"throw {resolvedThrowExpression};");
            return;
        }

        if (node.Failure is { } unsupportedMessage)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                unsupportedMessage,
                operationExpression);
            return;
        }

        WriteMemberValueLocals(writer, node.MemberMappings);

        foreach (var memberMapping in node.MemberMappings)
        {
            WriteInvocationArgumentLocals(writer, memberMapping);
            writer.Line(
                assignmentTarget + "." +
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(
                    mapping,
                    memberMapping,
                    localNames) +
                ";");
        }

        if (!node.MemberMappings.IsEmpty)
        {
            writer.Line();
        }

        writer.Line($"return {returnExpression ?? assignmentTarget};");
    }

    private static void WriteMappingConfigurationFailure(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        MappingFailureObservation failure,
        bool update) =>
        WriteMappingConfigurationFailure(
            writer,
            mapping,
            failure.RecoveryMessage,
            update);

    private static void WriteMappingConfigurationFailure(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        string reason,
        bool update) =>
        WriteMappingConfigurationFailure(
            writer,
            mapping,
            reason,
            MappingOperationExpression(update));

    private static void WriteMappingConfigurationFailure(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        MappingFailureObservation failure,
        string operationExpression) =>
        WriteMappingConfigurationFailure(
            writer,
            mapping,
            failure.RecoveryMessage,
            operationExpression);

    private static void WriteMappingConfigurationFailure(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        string reason,
        string operationExpression)
    {
        var reasonLiteral =
            SyntaxFactory.LiteralExpression(
                    SyntaxKind.StringLiteralExpression,
                    SyntaxFactory.Literal(reason))
                .ToString();

        writer.Line(
            "=> throw new global::Morphant.Exceptions." +
            "MappingConfigurationException(");
        writer.Indent();
        writer.Line(operationExpression + ",");
        writer.Line($"typeof({mapping.SourceRuntimeTypeName}),");
        writer.Line($"typeof({mapping.DestinationRuntimeTypeName}),");
        writer.Line($"{reasonLiteral});");
        writer.Unindent();
    }

    private static void WriteMappingConfigurationFailureStatement(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        MappingFailureObservation failure,
        bool update) =>
        WriteMappingConfigurationFailureStatement(
