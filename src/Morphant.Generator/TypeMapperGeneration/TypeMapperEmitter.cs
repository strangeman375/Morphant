    private static void WriteControlFlowUpdateNode(
        CodeWriter writer,
        TypeMapperControlFlowNode node)
    {
        WriteLocalValues(
            writer,
            node.Locals);

        if (node.EvaluationExpression is
                { } evaluationExpression)
        {
            writer.Line($"_ = {evaluationExpression};");
            writer.Line();
            WriteControlFlowUpdateNode(
                writer,
                node.EvaluationContinuation!);
            return;
        }

        if (node.SwitchExpression is
                { } switchExpression)
        {
            writer.Line($"switch ({switchExpression})");
            writer.Line("{");
            writer.Indent();

            foreach (var section in node.SwitchSections)
            {
                foreach (var label in section.Labels)
                {
                    writer.Line(label);
                }

                writer.Line("{");
                writer.Indent();
                WriteControlFlowUpdateNode(
                    writer,
                    section.Branch);
                writer.Unindent();
                writer.Line("}");
            }

            writer.Unindent();
            writer.Line("}");

            if (node.SwitchContinuation is
                    { } continuation)
            {
                writer.Line();
                WriteControlFlowUpdateNode(
                    writer,
                    continuation);
            }

            return;
        }

        if (node.Condition is { } condition)
        {
            writer.Line($"if ({condition})");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowUpdateNode(
                writer,
                node.WhenTrue!);
            writer.Unindent();
            writer.Line("}");
            writer.Line("else");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowUpdateNode(
                writer,
                node.WhenFalse!);
            writer.Unindent();
            writer.Line("}");
            return;
        }

        if (node.ThrowExpression is { } throwExpression)
        {
            var resolvedThrowExpression = ResolveThrowExpression(
                throwExpression,
                node.ThrowUsesCurrentMappingOperation,
                MappingOperationExpression(update: true));
            writer.Line($"throw {resolvedThrowExpression};");
            return;
        }

        WriteUpdateLeafStatements(
            writer,
            node.Leaf!.Value,
            allowReplacement: true);
    }

    private static void WriteUpdateLeafStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        bool allowReplacement)
    {
        if (mapping.Failure is
            { } unsupportedMappingMessage)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                unsupportedMappingMessage,
                update: true);
            return;
        }

        if (mapping.UpdateFailure is
            { } unsupportedExceptionMessage)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                unsupportedExceptionMessage,
                update: true);
            return;
        }

        if (mapping.UpdateDirectExpression is
            { } directExpression)
        {
            writer.Line($"return {directExpression};");
            return;
        }

        if (allowReplacement &&
            mapping.CreateFactory is { } factory)
        {
            WriteFactoryCreateStatements(
                writer,
                mapping,
                factory,
                MappingOperationExpression(update: true));
            return;
        }

        if (allowReplacement &&
            mapping.CreateConstructor is { } constructor)
        {
            WriteConstructorCreateStatements(
                writer,
                mapping,
                constructor,
                MappingOperationExpression(update: true));
            return;
        }

        if (mapping.UpdateKind ==
            TypeMapperUpdateKind.Unsupported)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                "Morphant could not generate Update for this mapping.",
                update: true);
            return;
        }

        if (mapping.PostMemberControlFlow is { } postControlFlow)
        {
            WritePostMemberControlFlow(
                writer,
                mapping,
                postControlFlow,
                "destination",
                operationExpression:
                    MappingOperationExpression(update: true));
            return;
        }

        if (mapping.UpdateMemberMappings.IsEmpty)
        {
            writer.Line("return destination;");
            return;
        }

        WriteMemberValueLocals(
            writer,
            mapping.UpdateMemberMappings);

        foreach (var memberMapping in
                 mapping.UpdateMemberMappings)
        {
            writer.Line(
                "destination." +
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(mapping, memberMapping) +
                ";");
        }

        writer.Line();
        writer.Line("return destination;");
    }

    private static void WritePostMemberControlFlow(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        TypeMapperMemberControlFlowNode node,
        string assignmentTarget,
        string? returnExpression = null,
        string? operationExpression = null)
    {
        operationExpression ??=
            MappingOperationExpression(update: false);

        WriteLocalValues(writer, node.Locals);

        if (node.EvaluationExpression is { } evaluationExpression)
        {
            writer.Line($"_ = {evaluationExpression};");
            writer.Line();
            WritePostMemberControlFlow(
                writer,
                mapping,
                node.EvaluationContinuation!,
                assignmentTarget,
                returnExpression,
                operationExpression);
            return;
        }

        if (node.SwitchExpression is { } switchExpression)
        {
            writer.Line($"switch ({switchExpression})");
            writer.Line("{");
            writer.Indent();

            foreach (var section in node.SwitchSections)
            {
                foreach (var label in section.Labels)
                {
                    writer.Line(label);
                }

                writer.Line("{");
                writer.Indent();
                WritePostMemberControlFlow(
                    writer,
                    mapping,
                    section.Branch,
                    assignmentTarget,
                    returnExpression,
                    operationExpression);
                writer.Unindent();
                writer.Line("}");
            }

            writer.Unindent();
            writer.Line("}");

            if (node.SwitchContinuation is { } continuation)
            {
                writer.Line();
                WritePostMemberControlFlow(
                    writer,
                    mapping,
                    continuation,
                    assignmentTarget,
                    returnExpression,
                    operationExpression);
            }

            return;
        }

        if (node.Condition is { } condition)
        {
            writer.Line($"if ({condition})");
            writer.Line("{");
            writer.Indent();
            WritePostMemberControlFlow(
                writer,
                mapping,
                node.WhenTrue!,
                assignmentTarget,
                returnExpression,
                operationExpression);
            writer.Unindent();
            writer.Line("}");
            writer.Line("else");
            writer.Line("{");
            writer.Indent();
            WritePostMemberControlFlow(
                writer,
                mapping,
                node.WhenFalse!,
                assignmentTarget,
                returnExpression,
                operationExpression);
            writer.Unindent();
            writer.Line("}");
            return;
        }

        if (node.ThrowExpression is { } throwExpression)
        {
            var resolvedThrowExpression = ResolveThrowExpression(
                throwExpression,
                node.ThrowUsesCurrentMappingOperation,
                operationExpression);
            writer.Line($"throw {resolvedThrowExpression};");
            return;
        }

        if (node.Failure is { } unsupportedMessage)
        {
            WriteMappingConfigurationFailureStatement(
                writer,
                mapping,
                unsupportedMessage,
                operationExpression);
            return;
        }

        WriteMemberValueLocals(writer, node.MemberMappings);

        foreach (var memberMapping in node.MemberMappings)
        {
            writer.Line(
                assignmentTarget + "." +
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(mapping, memberMapping) +
                ";");
        }

        if (!node.MemberMappings.IsEmpty)
        {
            writer.Line();
        }

        writer.Line($"return {returnExpression ?? assignmentTarget};");
    }

