using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Morphant.Generator.Settings;

namespace Morphant.Generator.TypeMapperGeneration;

internal static class TypeMapperEmitter
{
    private const string InvalidMappingModeExceptionMessage =
        "The effective MappingMode is invalid.";

    private const string InvalidNullSourceHandlingExceptionMessage =
        "The effective NullSourceHandling is invalid.";

    private const string InvalidNullDestinationHandlingExceptionMessage =
        "The effective NullDestinationHandling is invalid.";

    public static SourceText Emit(TypeMapperModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();

        if (model.Namespace.Length > 0)
        {
            writer.OpenBlock($"namespace {model.Namespace}");
        }

        foreach (var containingType in model.ContainingTypes)
        {
            writer.OpenBlock(
                $"partial {containingType.DeclarationKind} " +
                containingType.TypeName +
                containingType.TypeParameterList);
        }

        WriteType(writer, model);

        for (var index = model.ContainingTypes.Length - 1;
             index >= 0;
             index--)
        {
            writer.CloseBlock();
        }

        if (model.Namespace.Length > 0)
        {
            writer.CloseBlock();
        }

        return SourceText.From(
            writer.ToString(),
            Encoding.UTF8);
    }

    private static void WriteType(
        CodeWriter writer,
        TypeMapperModel model)
    {
        writer.Line(
            $"{model.Accessibility} partial class " +
            model.TypeName +
            model.TypeParameterList +
            " :");
        writer.Indent();

        for (var index = 0; index < model.Mappings.Length; index++)
        {
            var suffix = index < model.Mappings.Length - 1
                ? ","
                : string.Empty;

            writer.Line(
                model.Mappings[index].InterfaceTypeName + suffix);
        }

        writer.Unindent();
        writer.Line("{");
        writer.Indent();

        for (var index = 0; index < model.Mappings.Length; index++)
        {
            if (index > 0)
            {
                writer.Line();
            }

            WriteMapping(writer, model.Mappings[index]);
        }

        writer.Unindent();
        writer.Line("}");
    }

    private static void WriteMapping(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        WriteMapNew(writer, mapping);
        writer.Line();
        WriteMapExisting(writer, mapping);

        if (mapping.MapNewImplMethodName is not null)
        {
            writer.Line();
            WriteMapNewImpl(writer, mapping);
        }

        if (mapping.MapExistingImplMethodName is not null)
        {
            writer.Line();
            WriteMapExistingImpl(writer, mapping);
        }

        if (mapping.EffectiveSettings.IsMappingModeValid &&
            !mapping.HelperMethodDeclarations.IsDefaultOrEmpty)
        {
            foreach (var declaration in
                     mapping.HelperMethodDeclarations)
            {
                writer.Line();
                WriteMultilineDeclaration(
                    writer,
                    declaration);
            }
        }
    }

    private static void WriteMapNew(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        writer.Line("/// <inheritdoc/>");
        writer.Line(
            $"{mapping.DestinationTypeName} " +
            $"{mapping.InterfaceTypeName}.Map(");
        writer.Indent();
        writer.Line(
            $"{mapping.MaybeNullSourceTypeName} source,");
        writer.Line("global::Morphant.Context.MappingContext context)");

        if (!mapping.EffectiveSettings.IsMappingModeValid)
        {
            WriteUnsupportedMapping(
                writer,
                InvalidMappingModeExceptionMessage);
            writer.Unindent();
            return;
        }

        if (!mapping.EffectiveSettings.SupportsMapNew)
        {
            WriteUnsupportedMapping(
                writer,
                "The effective MappingMode does not include Create.");
            writer.Unindent();
            return;
        }

        if (!mapping.EffectiveSettings.IsNullSourceHandlingValid)
        {
            WriteUnsupportedMapping(
                writer,
                InvalidNullSourceHandlingExceptionMessage);
            writer.Unindent();
            return;
        }

        if (mapping.SourceCanBeNull)
        {
            WriteMapNewBody(
                writer,
                mapping);
            return;
        }

        var methodName =
            mapping.MapNewImplMethodName ??
            throw new InvalidOperationException(
                "A Create implementation method name is required.");

        writer.Line(
            $"=> {BuildMapNewImplCall(mapping, methodName)};");
        writer.Unindent();
    }

    private static void WriteMapNewBody(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        writer.Unindent();
        writer.Line("{");
        writer.Indent();

        WriteSourceNullHandling(
            writer,
            mapping,
            mapExisting: false);
        writer.Line();
        WriteNonNullSourceNormalization(writer, mapping);
        WriteMapNewCallOrStatements(
            writer,
            mapping);

        writer.Unindent();
        writer.Line("}");
    }

    private static void WriteMapNewCallOrStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        if (mapping.MapNewImplMethodName is
            { } mapNewImplMethodName)
        {
            writer.Line(
                $"return {BuildMapNewImplCall(mapping, mapNewImplMethodName)};");
            return;
        }

        WriteMapNewStatements(
            writer,
            mapping);
    }

    private static void WriteMapNewStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        if (mapping.UnsupportedExceptionMessage is
            { } unsupportedExceptionMessage)
        {
            WriteUnsupportedMappingStatement(
                writer,
                unsupportedExceptionMessage);
            return;
        }

        if (mapping.ControlFlow is { } controlFlow)
        {
            WriteControlFlowMapNewNode(
                writer,
                controlFlow.MapNewRoot);
            return;
        }

        WriteControlFlowMapNewLeaf(
            writer,
            mapping);
    }

    private static void WriteControlFlowMapNewNode(
        CodeWriter writer,
        TypeMapperControlFlowNode node)
    {
        WriteLocalValues(
            writer,
            node.Locals);

        if (node.SwitchExpression is
                { } switchExpression)
        {
            writer.Line($"switch ({switchExpression})");
            writer.Line("{");
            writer.Indent();

            foreach (var section in node.SwitchSections)
            {
                foreach (var label in section.Labels)
                {
                    writer.Line(label);
                }

                writer.Line("{");
                writer.Indent();
                WriteControlFlowMapNewNode(
                    writer,
                    section.Branch);
                writer.Unindent();
                writer.Line("}");
            }

            writer.Unindent();
            writer.Line("}");

            if (node.SwitchContinuation is
                    { } continuation)
            {
                writer.Line();
                WriteControlFlowMapNewNode(
                    writer,
                    continuation);
            }

            return;
        }

        if (node.Condition is { } condition)
        {
            writer.Line($"if ({condition})");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowMapNewNode(
                writer,
                node.WhenTrue!);
            writer.Unindent();
            writer.Line("}");
            writer.Line("else");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowMapNewNode(
                writer,
                node.WhenFalse!);
            writer.Unindent();
            writer.Line("}");
            return;
        }

        if (node.ThrowExpression is { } throwExpression)
        {
            writer.Line($"throw {throwExpression};");
            return;
        }

        WriteControlFlowMapNewLeaf(
            writer,
            node.Leaf!.Value);
    }

    private static void WriteControlFlowMapNewLeaf(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        if (mapping.MapNewUnsupportedExceptionMessage is
            { } unsupportedExceptionMessage)
        {
            WriteUnsupportedMappingStatement(
                writer,
                unsupportedExceptionMessage);
            return;
        }

        if (mapping.MapNewDirectExpression is
            { } directExpression)
        {
            writer.Line($"return {directExpression};");
            return;
        }

        if (mapping.MapNewFactory is { } factory)
        {
            WriteFactoryMapNewStatements(
                writer,
                mapping,
                factory);
            return;
        }

        if (mapping.MapNewConstructor is
            { } constructor)
        {
            WriteConstructorMapNewStatements(
                writer,
                mapping,
                constructor);
            return;
        }

        writer.Line(
            "throw new global::System.NotImplementedException();");
    }

    private static void WriteConstructorMapNewStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        TypeMapperConstructorMappingModel constructor)
    {
        var hasValueLocals = false;

        foreach (var argument in constructor.Arguments)
        {
            if (argument.ValueLocalName is not
                { } valueLocalName)
            {
                continue;
            }

            hasValueLocals = true;
            writer.Line(
                (argument.ValueLocalTypeName ?? "var") +
                $" {valueLocalName} = " +
                ConstructorArgumentUncachedValueExpression(
                    mapping,
                    argument) +
                ";");
        }

        if (hasValueLocals)
        {
            writer.Line();
        }

        if (constructor.Arguments.IsEmpty)
        {
            writer.Line(
                $"return new {constructor.ConstructedTypeName}()" +
                (mapping.MapNewMemberMappings.IsEmpty
                    ? ";"
                    : string.Empty));
        }
        else
        {
            writer.Line(
                $"return new {constructor.ConstructedTypeName}(");
            writer.Indent();

            for (var index = 0;
                 index < constructor.Arguments.Length;
                 index++)
            {
                var argument = constructor.Arguments[index];
                var isLast =
                    index == constructor.Arguments.Length - 1;
                var suffix = isLast
                    ? mapping.MapNewMemberMappings.IsEmpty
                        ? ");"
                        : ")"
                    : ",";

                writer.Line(
                    $"{Identifier(argument.ParameterName)}: " +
                    ConstructorArgumentValueExpression(
                        mapping,
                        argument) +
                    suffix);
            }

            writer.Unindent();
        }

        if (mapping.MapNewMemberMappings.IsEmpty)
        {
            return;
        }

        writer.Line("{");
        writer.Indent();

        for (var index = 0;
             index < mapping.MapNewMemberMappings.Length;
             index++)
        {
            var memberMapping =
                mapping.MapNewMemberMappings[index];
            var suffix =
                index < mapping.MapNewMemberMappings.Length - 1
                    ? ","
                    : string.Empty;

            writer.Line(
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(mapping, memberMapping) +
                suffix);
        }

        writer.Unindent();
        writer.Line("};");
    }

    private static void WriteFactoryMapNewStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        TypeMapperFactoryMappingModel factory)
    {
        if (factory.LocalFunctionDeclaration is
            { } localFunctionDeclaration)
        {
            WriteLocalFunction(
                writer,
                localFunctionDeclaration);
        }

        if (factory.Delegate is { } factoryDelegate)
        {
            writer.Line(
                $"{factoryDelegate.TypeName} " +
                $"{Identifier(factoryDelegate.LocalName)} = " +
                factoryDelegate.ValueExpression +
                ";");
        }

        var destinationLocalName =
            Identifier(factory.DestinationLocalName);

        writer.Line(
            $"{mapping.DestinationTypeName} {destinationLocalName} = " +
            factory.ValueExpression +
            ";");

        var assignmentTarget = destinationLocalName;
        var returnExpression = destinationLocalName;

        if (!mapping.MapNewMemberMappings.IsEmpty &&
            factory.NullableValueLocalName is
                { } nullableValueLocalName)
        {
            var valueLocalName =
                Identifier(nullableValueLocalName);

            writer.Line(
                $"var {valueLocalName} = " +
                $"{destinationLocalName}.Value;");

            assignmentTarget = valueLocalName;
            returnExpression = valueLocalName;
        }
        else if (factory.DestinationRequiresNullForgivingOperator)
        {
            assignmentTarget += "!";
        }

        foreach (var memberMapping in
                 mapping.MapNewMemberMappings)
        {
            writer.Line(
                $"{assignmentTarget}." +
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(mapping, memberMapping) +
                ";");
        }

        writer.Line();
        writer.Line($"return {returnExpression};");
    }

    private static void WriteMapExisting(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        writer.Line("/// <inheritdoc/>");
        writer.Line(
            $"{mapping.DestinationTypeName} " +
            $"{mapping.InterfaceTypeName}.Map(");
        writer.Indent();
        writer.Line(
            $"{mapping.MaybeNullSourceTypeName} source,");
        writer.Line(
            $"{mapping.MaybeNullDestinationTypeName} destination,");
        writer.Line("global::Morphant.Context.MappingContext context)");

        if (!mapping.EffectiveSettings.IsMappingModeValid)
        {
            WriteUnsupportedMapping(
                writer,
                InvalidMappingModeExceptionMessage);
            writer.Unindent();
            return;
        }

        if (!mapping.EffectiveSettings.SupportsMapExisting)
        {
            WriteUnsupportedMapping(
                writer,
                "The effective MappingMode does not include Update.");
            writer.Unindent();
            return;
        }

        if (!mapping.EffectiveSettings.IsNullSourceHandlingValid)
        {
            WriteUnsupportedMapping(
                writer,
                InvalidNullSourceHandlingExceptionMessage);
            writer.Unindent();
            return;
        }

        if (!mapping.EffectiveSettings.IsNullDestinationHandlingValid)
        {
            WriteUnsupportedMapping(
                writer,
                InvalidNullDestinationHandlingExceptionMessage);
            writer.Unindent();
            return;
        }

        if (mapping.SourceCanBeNull ||
            mapping.DestinationCanBeNull)
        {
            WriteMapExistingBody(
                writer,
                mapping);
            return;
        }

        var methodName =
            mapping.MapExistingImplMethodName ??
            throw new InvalidOperationException(
                "An Update implementation method name is required.");

        writer.Line(
            $"=> {BuildMapExistingImplCall(mapping, methodName)};");
        writer.Unindent();
    }

    private static void WriteMapExistingBody(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        writer.Unindent();
        writer.Line("{");
        writer.Indent();

        if (mapping.SourceCanBeNull)
        {
            WriteSourceNullHandling(
                writer,
                mapping,
                mapExisting: true);
            writer.Line();
            WriteNonNullSourceNormalization(writer, mapping);
        }

        if (mapping.DestinationCanBeNull)
        {
            WriteDestinationNullHandling(
                writer,
                mapping);
            writer.Line();
        }

        var methodName =
            mapping.MapExistingImplMethodName ??
            throw new InvalidOperationException(
                "An Update implementation method name is required.");

        writer.Line(
            $"return {BuildMapExistingImplCall(mapping, methodName)};");

        writer.Unindent();
        writer.Line("}");
    }

    private static void WriteMapExistingStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        if (mapping.UnsupportedExceptionMessage is
            { } unsupportedExceptionMessage)
        {
            WriteUnsupportedMappingStatement(
                writer,
                unsupportedExceptionMessage);
            return;
        }

        if (mapping.ControlFlow is { } controlFlow)
        {
            WriteControlFlowMapExistingNode(
                writer,
                controlFlow.MapExistingRoot);
            return;
        }

        WriteMapExistingLeafStatements(
            writer,
            mapping);
    }

    private static void WriteSourceNullHandling(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        bool mapExisting)
    {
        writer.Line("if (source is null)");
        writer.Line("{");
        writer.Indent();

        switch (mapping.EffectiveSettings.NullSourceHandling)
        {
            case NullSourceHandlingValue.ReturnNull:
                writer.Line("return default!;");
                break;

            case NullSourceHandlingValue.ReturnDestination
                when mapExisting:
                writer.Line("return destination!;");
                break;

            case NullSourceHandlingValue.ReturnDestination:
                writer.Line("return default!;");
                break;

            case NullSourceHandlingValue.Throw:
                WriteArgumentNullException(
                    writer,
                    "source");
                break;

            default:
                throw new InvalidOperationException(
                    "A valid effective NullSourceHandling value is required.");
        }

        writer.Unindent();
        writer.Line("}");
    }

    private static void WriteNonNullSourceNormalization(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        if (!mapping.SourceIsNullableValue)
        {
            return;
        }

        writer.Line(
            $"var {mapping.NonNullSourceName} = source.Value;");
        writer.Line();
    }

    private static void WriteDestinationNullHandling(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        writer.Line("if (destination is null)");
        writer.Line("{");
        writer.Indent();

        switch (mapping.EffectiveSettings.NullDestinationHandling)
        {
            case NullDestinationHandlingValue.Create:
                WriteMapNewCallOrStatements(
                    writer,
                    mapping);
                break;

            case NullDestinationHandlingValue.Throw:
                WriteArgumentNullException(
                    writer,
                    "destination");
                break;

            default:
                throw new InvalidOperationException(
                    "A valid effective NullDestinationHandling value is required.");
        }

        writer.Unindent();
        writer.Line("}");
    }

    private static void WriteMapNewImpl(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        var methodName =
            mapping.MapNewImplMethodName ??
            throw new InvalidOperationException(
                "A Create implementation method name is required.");

        writer.Line(
            $"private {mapping.DestinationTypeName} " +
            $"{methodName}(");
        writer.Indent();
        writer.Line(
            $"{mapping.NonNullSourceTypeName} " +
            mapping.NonNullSourceName + ",");
        writer.Line(
            "global::Morphant.Context.MappingContext context)");
        writer.Unindent();
        writer.Line("{");
        writer.Indent();

        WriteMapNewStatements(
            writer,
            mapping);

        writer.Unindent();
        writer.Line("}");
    }

    private static string BuildMapNewImplCall(
        TypeMapperMappingModel mapping,
        string methodName)
    {
        return $"{methodName}({mapping.NonNullSourceName}, context)";
    }

    private static void WriteMapExistingImpl(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        var methodName =
            mapping.MapExistingImplMethodName ??
            throw new InvalidOperationException(
                "An Update implementation method name is required.");

        writer.Line(
            $"private {mapping.DestinationTypeName} " +
            $"{methodName}(");
        writer.Indent();
        writer.Line(
            $"{mapping.NonNullSourceTypeName} " +
            mapping.NonNullSourceName + ",");
        writer.Line(
            $"{mapping.NonNullDestinationTypeName} destination,");
        writer.Line(
            "global::Morphant.Context.MappingContext context)");
        writer.Unindent();
        writer.Line("{");
        writer.Indent();

        WriteMapExistingStatements(
            writer,
            mapping);

        writer.Unindent();
        writer.Line("}");
    }

    private static string BuildMapExistingImplCall(
        TypeMapperMappingModel mapping,
        string methodName)
    {
        var destination = mapping.MapExistingKind ==
            TypeMapperMapExistingKind.NullableValue
                ? "destination.Value"
                : "destination";
        var arguments =
            $"{mapping.NonNullSourceName}, {destination}";

        return $"{methodName}({arguments}, context)";
    }

    private static void WriteArgumentNullException(
        CodeWriter writer,
        string parameterName)
    {
        writer.Line(
            "throw new global::System.ArgumentNullException(" +
            $"nameof({parameterName}));");
    }

    private static void WriteControlFlowMapExistingNode(
        CodeWriter writer,
        TypeMapperControlFlowNode node)
    {
        WriteLocalValues(
            writer,
            node.Locals);

        if (node.SwitchExpression is
                { } switchExpression)
        {
            writer.Line($"switch ({switchExpression})");
            writer.Line("{");
            writer.Indent();

            foreach (var section in node.SwitchSections)
            {
                foreach (var label in section.Labels)
                {
                    writer.Line(label);
                }

                writer.Line("{");
                writer.Indent();
                WriteControlFlowMapExistingNode(
                    writer,
                    section.Branch);
                writer.Unindent();
                writer.Line("}");
            }

            writer.Unindent();
            writer.Line("}");

            if (node.SwitchContinuation is
                    { } continuation)
            {
                writer.Line();
                WriteControlFlowMapExistingNode(
                    writer,
                    continuation);
            }

            return;
        }

        if (node.Condition is { } condition)
        {
            writer.Line($"if ({condition})");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowMapExistingNode(
                writer,
                node.WhenTrue!);
            writer.Unindent();
            writer.Line("}");
            writer.Line("else");
            writer.Line("{");
            writer.Indent();
            WriteControlFlowMapExistingNode(
                writer,
                node.WhenFalse!);
            writer.Unindent();
            writer.Line("}");
            return;
        }

        if (node.ThrowExpression is { } throwExpression)
        {
            writer.Line($"throw {throwExpression};");
            return;
        }

        WriteMapExistingLeafStatements(
            writer,
            node.Leaf!.Value);
    }

    private static void WriteMapExistingLeafStatements(
        CodeWriter writer,
        TypeMapperMappingModel mapping)
    {
        if (mapping.MapExistingUnsupportedExceptionMessage is
            { } unsupportedExceptionMessage)
        {
            WriteUnsupportedMappingStatement(
                writer,
                unsupportedExceptionMessage);
            return;
        }

        if (mapping.MapExistingDirectExpression is
            { } directExpression)
        {
            writer.Line($"return {directExpression};");
            return;
        }

        if (mapping.MapExistingKind ==
            TypeMapperMapExistingKind.Unsupported)
        {
            writer.Line(
                "throw new global::System.NotImplementedException();");
            return;
        }

        if (mapping.MapExistingMemberMappings.IsEmpty)
        {
            writer.Line("return destination;");
            return;
        }

        WriteMemberValueLocals(
            writer,
            mapping.MapExistingMemberMappings);

        foreach (var memberMapping in
                 mapping.MapExistingMemberMappings)
        {
            writer.Line(
                "destination." +
                $"{Identifier(memberMapping.DestinationMemberName)} = " +
                MemberValueExpression(mapping, memberMapping) +
                ";");
        }

        writer.Line();
        writer.Line("return destination;");
    }

    private static void WriteUnsupportedMapping(
        CodeWriter writer,
        string exceptionMessage)
    {
        var messageLiteral =
            SyntaxFactory.LiteralExpression(
                    SyntaxKind.StringLiteralExpression,
                    SyntaxFactory.Literal(exceptionMessage))
                .ToString();

        writer.Line(
            "=> throw new global::System.NotSupportedException(");
        writer.Indent();
        writer.Line($"{messageLiteral});");
        writer.Unindent();
    }

    private static void WriteUnsupportedMappingStatement(
        CodeWriter writer,
        string exceptionMessage)
    {
        var messageLiteral =
            SyntaxFactory.LiteralExpression(
                    SyntaxKind.StringLiteralExpression,
                    SyntaxFactory.Literal(exceptionMessage))
                .ToString();

        writer.Line(
            "throw new global::System.NotSupportedException(");
        writer.Indent();
        writer.Line($"{messageLiteral});");
        writer.Unindent();
    }

    private static void WriteLocalValues(
        CodeWriter writer,
        ImmutableArray<TypeMapperLocalValueModel> locals)
    {
        foreach (var local in locals)
        {
            writer.Line(
                (local.IsConst
                    ? "const "
                    : string.Empty) +
                $"{local.DeclarationType} {local.Name} = " +
                local.ValueExpression +
                ";");
        }

        if (!locals.IsEmpty)
        {
            writer.Line();
        }
    }

    private static void WriteLocalFunction(
        CodeWriter writer,
        string declaration)
    {
        WriteMultilineDeclaration(
            writer,
            declaration);
        writer.Line();
    }

    private static void WriteMultilineDeclaration(
        CodeWriter writer,
        string declaration)
    {
        foreach (var line in declaration
                     .Replace("\r\n", "\n")
                     .Replace('\r', '\n')
                     .Split('\n'))
        {
            writer.Line(line);
        }
    }

    private static string SourceValueExpression(
        TypeMapperMappingModel mapping,
        string sourceMemberName,
        string? sourceValueLocalName)
    {
        return sourceValueLocalName ??
               $"{mapping.NonNullSourceName}." +
               Identifier(sourceMemberName);
    }

    private static string MemberValueExpression(
        TypeMapperMappingModel owner,
        TypeMapperMemberMappingModel mapping)
    {
        return mapping.ValueLocalName ??
               mapping.ExplicitValueExpression ??
               SourceValueExpression(
                   owner,
                   mapping.SourceMemberName,
                   mapping.SourceValueLocalName);
    }

    private static void WriteMemberValueLocals(
        CodeWriter writer,
        IEnumerable<TypeMapperMemberMappingModel> mappings)
    {
        var wroteLocal = false;

        foreach (var mapping in mappings)
        {
            if (mapping.ValueLocalName is not { } valueLocalName)
            {
                continue;
            }

            var valueTypeName =
                mapping.ExplicitValueTypeName ??
                throw new InvalidOperationException(
                    "A member value local requires a value type.");
            var valueExpression =
                mapping.ExplicitValueExpression ??
                throw new InvalidOperationException(
                    "A member value local requires an explicit expression.");

            writer.Line(
                $"{valueTypeName} {valueLocalName} = " +
                valueExpression +
                ";");
            wroteLocal = true;
        }

        if (wroteLocal)
        {
            writer.Line();
        }
    }

    private static string ConstructorArgumentValueExpression(
        TypeMapperMappingModel owner,
        TypeMapperConstructorArgumentMappingModel mapping)
    {
        return mapping.ValueLocalName ??
               ConstructorArgumentUncachedValueExpression(
                   owner,
                   mapping);
    }

    private static string ConstructorArgumentUncachedValueExpression(
        TypeMapperMappingModel owner,
        TypeMapperConstructorArgumentMappingModel mapping)
    {
        return mapping.ExplicitValueExpression ??
               SourceValueExpression(
                   owner,
                   mapping.SourceMemberName,
                   sourceValueLocalName: null);
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
