    private static void WriteUnsupportedOperation(
        CodeWriter writer,
        TypeMapperMappingModel mapping,
        string operation)
    {
        writer.Line(
            "=> throw new global::Morphant.Exceptions." +
            "MappingOperationNotSupportedException(");
        writer.Indent();
        writer.Line(
            $"global::Morphant.Context.MappingOperation.{operation},");
        writer.Line($"typeof({mapping.SourceRuntimeTypeName}),");
        writer.Line($"typeof({mapping.DestinationRuntimeTypeName}),");
        writer.Line(
            "global::Morphant.MappingMode." +
            mapping.EffectiveSettings.MappingMode + ");");
        writer.Unindent();
    }

    private static void WriteLocalValues(
        CodeWriter writer,
        ImmutableArray<TypeMapperLocalValueModel> locals)
    {
        foreach (var local in locals)
        {
            WriteLocalValue(writer, local);
        }

        if (!locals.IsEmpty)
        {
            writer.Line();
        }
    }

    private static void WriteEvaluation(
        CodeWriter writer,
        string expression,
        string? condition,
        ImmutableArray<TypeMapperLocalValueModel> locals)
    {
        if (condition is null)
        {
            WriteLocalValues(
                writer,
                locals.IsDefault
                    ? ImmutableArray<TypeMapperLocalValueModel>.Empty
                    : locals);
            writer.Line($"_ = {expression};");
            writer.Line();
            return;
        }

        writer.Line($"if ({condition})");
        writer.Line("{");
        writer.Indent();
        WriteLocalValues(
            writer,
            locals.IsDefault
                ? ImmutableArray<TypeMapperLocalValueModel>.Empty
                : locals);
        writer.Line($"_ = {expression};");
        writer.Unindent();
        writer.Line("}");
        writer.Line();
    }

    private static void WriteMultilineDeclaration(
        CodeWriter writer,
        string declaration)
    {
        foreach (var line in declaration
                     .Replace("\r\n", "\n")
                     .Replace('\r', '\n')
                     .Split('\n'))
        {
            writer.Line(line);
        }
    }

    private static string SourceValueExpression(
        TypeMapperMappingModel mapping,
        string sourceMemberName,
        string? sourceValueLocalName)
    {
        return sourceValueLocalName ??
               $"{mapping.NonNullSourceName}." +
               Identifier(sourceMemberName);
    }

    private static string MemberValueExpression(
        TypeMapperMappingModel owner,
        TypeMapperMemberMappingModel mapping,
        GeneratedLocalNameAllocator localNames)
    {
        return mapping.ValueLocalName ??
               mapping.ExplicitValueExpression ??
               mapping.SourceValueLocalName ??
               mapping.ConventionValueExpression?.Render(localNames) ??
               SourceValueExpression(
                   owner,
                   mapping.SourceMemberName,
                   mapping.SourceValueLocalName);
    }

    private static void WriteMemberValueLocals(
        CodeWriter writer,
        IEnumerable<TypeMapperMemberMappingModel> mappings)
    {
        var wroteLocal = false;

        foreach (var mapping in mappings)
        {
            foreach (var local in mapping.EvaluationLocals.IsDefault
                         ? ImmutableArray<TypeMapperLocalValueModel>.Empty
                         : mapping.EvaluationLocals)
            {
                WriteLocalValue(writer, local);
                wroteLocal = true;
            }

            if (mapping.ValueLocalName is not { } valueLocalName)
            {
                continue;
            }

            var valueTypeName =
                mapping.ExplicitValueTypeName ??
                throw new InvalidOperationException(
                    "A member value local requires a value type.");
            var valueExpression =
                mapping.ExplicitValueExpression ??
                throw new InvalidOperationException(
                    "A member value local requires an explicit expression.");

            writer.Line(
                $"{valueTypeName} {valueLocalName} = " +
                valueExpression +
                ";");
            wroteLocal = true;
        }

        if (wroteLocal)
        {
            writer.Line();
        }
    }

    private static void WriteLocalValue(
        CodeWriter writer,
        TypeMapperLocalValueModel local)
    {
        writer.Line(
            (local.IsConst
                ? "const "
                : string.Empty) +
            $"{local.DeclarationType} {local.Name} = " +
            local.ValueExpression +
            ";");
    }

    private static void WriteInvocationArgumentLocals(
        CodeWriter writer,
        TypeMapperMemberMappingModel mapping)
    {
        WriteLocalValues(
            writer,
            mapping.InvocationArgumentLocals.IsDefault
                ? ImmutableArray<TypeMapperLocalValueModel>.Empty
                : mapping.InvocationArgumentLocals);
    }

    private static string ConstructorArgumentValueExpression(
        TypeMapperMappingModel owner,
        TypeMapperConstructorArgumentMappingModel mapping,
        GeneratedLocalNameAllocator localNames)
    {
        return mapping.ValueLocalName ??
               ConstructorArgumentUncachedValueExpression(
                   owner,
                   mapping,
                   localNames);
    }

    private static string ConstructorArgumentUncachedValueExpression(
        TypeMapperMappingModel owner,
        TypeMapperConstructorArgumentMappingModel mapping,
        GeneratedLocalNameAllocator localNames)
    {
        return mapping.ExplicitValueExpression ??
               mapping.ConventionValueExpression?.Render(localNames) ??
               SourceValueExpression(
                   owner,
                   mapping.SourceMemberName,
                   sourceValueLocalName: null);
    }

    private static string ResolveThrowExpression(
        string throwExpression,
        bool usesCurrentMappingOperation,
        string operationExpression)
    {
        if (!usesCurrentMappingOperation)
        {
            return throwExpression;
        }

        return throwExpression.Replace(
            "context.Operation",
            operationExpression);
    }

    private static string MappingOperationExpression(bool update) =>
        "global::Morphant.Context.MappingOperation." +
        (update ? "Update" : "Create");

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
