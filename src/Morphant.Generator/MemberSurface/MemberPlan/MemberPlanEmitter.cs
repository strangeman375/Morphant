using Microsoft.CodeAnalysis.CSharp;

namespace Morphant.Generator.MemberSurface.MemberPlan;

internal static class MemberPlanEmitter
{
    public static string Emit(MemberPlanModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        writer.OpenBlock($"namespace {model.Namespace}");

        WriteTypeDocumentation(writer, model);

        if (model.ObsoleteAttributeSource is { } obsoleteAttribute)
        {
            writer.Line($"[{obsoleteAttribute}]");
        }

        var typeName = Identifier(model.TypeName);
        var typeReference = BuildTypeReference(
            typeName,
            model.TypeParameters);

        WriteTypeDeclaration(
            writer,
            $"internal sealed record {typeReference}",
            model.TypeParameters);

        WriteMembers(writer, model.Members);

        writer.Line(
            $"public bool Equals({typeReference}? other) => false;");
        writer.Line();
        writer.Line("public override int GetHashCode() => 0;");
        writer.Line();
        writer.Line("public override string ToString() => string.Empty;");
        writer.Line();
        writer.Line(
            "private bool PrintMembers(" +
            "global::System.Text.StringBuilder builder) => false;");

        writer.CloseBlock();
        writer.CloseBlock();

        return writer.ToString();
    }

    private static void WriteMembers(
        CodeWriter writer,
        IReadOnlyList<MemberPlanPropertyModel> members)
    {
        for (var index = 0; index < members.Count; index++)
        {
            var member = members[index];

            ToggleNullableAnnotations(
                writer,
                member.RequiresNullableAnnotationsDisabled,
                index > 0 &&
                members[index - 1]
                    .RequiresNullableAnnotationsDisabled);

            WriteMemberDocumentation(writer, member);

            if (member.ObsoleteAttributeSource is { } obsoleteAttribute)
            {
                writer.Line($"[{obsoleteAttribute}]");
            }

            writer.OpenBlock(
                "public global::Morphant.Members.Member<" +
                member.TypeName +
                ">" +
                (member.AcceptsNull ? "? " : " ") +
                Identifier(member.Name));
            writer.Line("get => null!;");

            if (member.CanWrite)
            {
                writer.Line("set { }");
            }

            writer.CloseBlock();

            var nextRequiresDisabled =
                index + 1 < members.Count &&
                members[index + 1]
                    .RequiresNullableAnnotationsDisabled;

            if (member.RequiresNullableAnnotationsDisabled &&
                !nextRequiresDisabled)
            {
                writer.Line("#nullable enable annotations");
            }

            writer.Line();
        }
    }

    private static void WriteTypeDocumentation(
        CodeWriter writer,
        MemberPlanModel model)
    {
        var documentation = model.DestinationDocumentation;
        var cref = XmlAttribute(documentation.Cref);

        if (documentation.HasDocumentation)
        {
            writer.Line($"/// <inheritdoc cref=\"{cref}\"/>");
            return;
        }

        WriteSummary(
            writer,
            "Describes member mappings for " +
            $"<see cref=\"{cref}\"/>.");
    }

    private static void WriteMemberDocumentation(
        CodeWriter writer,
        MemberPlanPropertyModel member)
    {
        var documentation = member.Documentation;
        var cref = XmlAttribute(documentation.Cref);

        if (documentation.HasDocumentation)
        {
            writer.Line($"/// <inheritdoc cref=\"{cref}\"/>");
            return;
        }

        WriteSummary(
            writer,
            member.CanWrite
                ? $"Configures mapping for <see cref=\"{cref}\"/>."
                : $"Selects <see cref=\"{cref}\"/>.");
    }

    private static void WriteTypeDeclaration(
        CodeWriter writer,
        string declaration,
        IReadOnlyList<MemberPlanTypeParameterModel> typeParameters)
    {
        if (typeParameters.All(static parameter =>
                parameter.Constraints.IsEmpty))
        {
            writer.OpenBlock(declaration);
            return;
        }

        writer.Line(declaration);
        writer.Indent();
        var annotationsAreDisabled = false;

        foreach (var typeParameter in typeParameters)
        {
            if (typeParameter.Constraints.IsEmpty)
            {
                continue;
            }

            if (typeParameter.RequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    typeParameter.RequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");
                annotationsAreDisabled =
                    typeParameter.RequiresNullableAnnotationsDisabled;
            }

            writer.Line(
                "where " +
                Identifier(typeParameter.Name) +
                " : " +
                string.Join(", ", typeParameter.Constraints));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Unindent();
        writer.Line("{");
        writer.Indent();
    }

    private static string BuildTypeReference(
        string typeName,
        IReadOnlyList<MemberPlanTypeParameterModel> typeParameters)
    {
        return typeParameters.Count == 0
            ? typeName
            : typeName +
              "<" +
              string.Join(
                  ", ",
                  typeParameters.Select(static parameter =>
                      Identifier(parameter.Name))) +
              ">";
    }

    private static void ToggleNullableAnnotations(
        CodeWriter writer,
        bool requiresDisabled,
        bool previousRequiresDisabled)
    {
        if (requiresDisabled == previousRequiresDisabled)
        {
            return;
        }

        writer.Line(
            requiresDisabled
                ? "#nullable disable annotations"
                : "#nullable enable annotations");
    }

    private static void WriteSummary(CodeWriter writer, string summary)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {summary}");
        writer.Line("/// </summary>");
    }

    private static string XmlAttribute(string value)
    {
        return XmlText(value)
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
}
