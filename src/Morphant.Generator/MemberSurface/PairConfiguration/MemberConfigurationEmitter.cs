using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.ConstructionSurface.ConstructionPlan;
using Morphant.Generator.ConstructionSurface.PairConfiguration;

namespace Morphant.Generator.MemberSurface.PairConfiguration;

internal static class MemberConfigurationEmitter
{
    public static string Emit(PairConfigurationModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        writer.OpenBlock("namespace Morphant");
        writer.OpenBlock(
            "internal static partial class " +
            "MorphantGeneratedMappingExtensions");

        WriteMethod(
            writer,
            model,
            "Defines destination member mappings.",
            "The member plan.",
            "global::Morphant.Delegates.Members<" +
            model.DeclarativeSourceTypeName + ", " +
            model.MembersPlanTypeName + ">");
        writer.Line();
        WriteMethod(
            writer,
            model,
            "Defines member mappings using the optional existing destination.",
            "The member plan.",
            "global::Morphant.Delegates.Members<" +
            model.DeclarativeSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            model.MembersPlanTypeName + ">");
        writer.Line();
        WriteMethod(
            writer,
            model,
            "Defines member mappings using the selected result.",
            "The member plan.",
            "global::Morphant.Delegates.Members<" +
            model.DeclarativeSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            model.MembersPlanTypeName + ">");
        writer.Line();
        WriteMethod(
            writer,
            model,
            "Defines member mappings using the selected result and current " +
            "operation.",
            "The member plan.",
            "global::Morphant.Delegates.Members<" +
            model.DeclarativeSourceTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            model.PreviousDestinationTypeName + ", " +
            "global::Morphant.Context.MappingContextMarker, " +
            model.MembersPlanTypeName + ">");

        writer.CloseBlock();
        writer.CloseBlock();

        return writer.ToString();
    }

    private static void WriteMethod(
        CodeWriter writer,
        PairConfigurationModel model,
        string summary,
        string callbackDescription,
        string delegateTypeName)
    {
        WriteSummary(writer, summary);
        WriteTypeParameterDocumentation(writer, model.TypeParameters);
        WriteParameterDocumentation(
            writer,
            "builder",
            "The mapping to configure.");
        WriteParameterDocumentation(
            writer,
            "members",
            callbackDescription);
        writer.Line(
            "/// <returns>The same mapping builder.</returns>");

        writer.Line(
            "public static " +
            model.BuilderTypeName +
            " Members" +
            BuildTypeParameterList(model.TypeParameters) +
            "(");
        writer.Line($"    this {model.BuilderTypeName} builder,");
        writer.Line($"    {delegateTypeName} members)");
        WriteMethodEnd(writer, model.TypeParameters);
    }

    private static void WriteMethodEnd(
        CodeWriter writer,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        writer.Indent();
        var annotationsAreDisabled = false;

        foreach (var typeParameter in typeParameters)
        {
            if (typeParameter.Constraints.IsEmpty)
            {
                continue;
            }

            if (typeParameter.RequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    typeParameter.RequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");
                annotationsAreDisabled =
                    typeParameter.RequiresNullableAnnotationsDisabled;
            }

            writer.Line(
                "where " +
                Identifier(typeParameter.Name) +
                " : " +
                string.Join(", ", typeParameter.Constraints));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Line(
            "=> throw new global::Morphant.Exceptions." +
            "RuntimeInvocationNotSupportedException();");
        writer.Unindent();
    }

    private static string BuildTypeParameterList(
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        return typeParameters.Count == 0
            ? string.Empty
            : "<" +
              string.Join(
                  ", ",
                  typeParameters.Select(static parameter =>
                      Identifier(parameter.Name))) +
              ">";
    }

    private static void WriteTypeParameterDocumentation(
        CodeWriter writer,
        IReadOnlyList<ConstructionTypeParameterModel> typeParameters)
    {
        foreach (var typeParameter in typeParameters)
        {
            writer.Line(
                "/// <typeparam name=\"" +
                XmlAttribute(typeParameter.Name) +
                "\">A type parameter from the mapping declaration.</typeparam>");
        }
    }

    private static void WriteSummary(CodeWriter writer, string summary)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {summary}");
        writer.Line("/// </summary>");
    }

    private static void WriteParameterDocumentation(
        CodeWriter writer,
        string parameterName,
        string description)
    {
        writer.Line(
            "/// <param name=\"" +
            XmlAttribute(parameterName) +
            "\">" +
            XmlText(description) +
            "</param>");
    }

    private static string XmlAttribute(string value)
    {
        return XmlText(value)
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
}
