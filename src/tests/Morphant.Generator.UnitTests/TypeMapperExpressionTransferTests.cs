using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests;

[TestFixture]
internal sealed class TypeMapperExpressionTransferTests
{
    [Test]
    public async Task Emits_async_warning_and_extension_transfer_context()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using System.Threading.Tasks;
using Morphant;
using TransferExtensions;

namespace TransferExtensions
{
    public static class TextExtensions
    {
        public static int Measure(this string value) => value.Length;
    }
}

namespace TestCase
{
    public sealed class Source
    {
        public string? Text { get; set; }

        public string? ReadText() => Text;
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
#pragma warning disable CS8602
            builder.Map<Source, Task<int>>()
                .Convert(async source =>
                {
                    await Task.Yield();
                    return (source!.ReadText()?.Measure() ?? 0) +
                        source.Text.Length;
                });
#pragma warning restore CS8602
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::System.Threading.Tasks.Task<int>>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::System.Threading.Tasks.Task<int>)) ||
                base.Supports(sourceType, destinationType);

        #pragma warning disable CS8602

        /// <inheritdoc/>
        global::System.Threading.Tasks.Task<int> global::Morphant.ITypeMapper<global::TestCase.Source, global::System.Threading.Tasks.Task<int>>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(source);

        /// <inheritdoc/>
        global::System.Threading.Tasks.Task<int> global::Morphant.ITypeMapper<global::TestCase.Source, global::System.Threading.Tasks.Task<int>>.Update(
            global::TestCase.Source? source,
            global::System.Threading.Tasks.Task<int>? destination,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(source);

        private async global::System.Threading.Tasks.Task<int> __ConvertDestination(global::TestCase.Source? source)
        {
            await global::System.Threading.Tasks.Task.Yield();
            return ((source!.ReadText())is { } conditionalReceiver ? global::TransferExtensions.TextExtensions.Measure(conditionalReceiver) : default(int? ) ?? 0) + source.Text.Length;
        }

        #pragma warning restore CS8602
    }
}
""";

        await ConventionTypeMapperGeneratorTest
            .RunAndAssertIgnoringCompilerDiagnostics(
                LanguageVersion.CSharp9,
                source,
                expected);
    }

    [Test]
    public async Task Emits_unsafe_only_for_the_transferred_mapping()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using System;
using Morphant;

namespace TestCase
{
    public sealed class Source
    {
        public IntPtr Pointer { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override unsafe void Configure(MapperBuilder builder) =>
            builder.Map<Source, int>()
                .ConstructUsing(source => *(int*)source.Pointer);
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(int)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        int global::Morphant.ITypeMapper<global::TestCase.Source, int>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        int global::Morphant.ITypeMapper<global::TestCase.Source, int>.Update(
            global::TestCase.Source? source,
            int destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Update(source, destination, context);
        }

        private unsafe int __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            int result = __ConstructUsing(source);

            return result;
        }

        private unsafe int __Update(
            global::TestCase.Source source,
            int destination,
            global::Morphant.Context.MappingContext context)
        {
            return destination;
        }

        private unsafe int __ConstructUsing(global::TestCase.Source source) => *(int*)source.Pointer;
    }
}
""";

        await ConventionTypeMapperGeneratorTest
            .RunAndAssertIgnoringCompilerDiagnostics(
                LanguageVersion.CSharp9,
                source,
                expected,
                allowUnsafe: true);
    }
}
