using Morphant;

namespace TestCase
{
    public readonly struct Source { }
    public readonly struct AssemblyDestination { }
    public readonly struct RootDestination { }
    public readonly struct PairDestination { }
    public readonly struct ResetDestination { }

    [MorphantMapper]
    public partial class AssemblyMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, AssemblyDestination>();
    }

    [MorphantMapper]
    public partial class RootMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MappingMode(MappingMode.Update);
            builder.Map<Source, RootDestination>();
            builder.MappingMode(MappingMode.Create);
        }
    }

    [MorphantMapper]
    public partial class PairMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, PairDestination>(MappingMode.Update);
            builder.MappingMode(MappingMode.Create);
        }
    }

    [MorphantMapper]
    public partial class ResetMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MappingMode(MappingMode.Create);
            builder.Map<Source, ResetDestination>();
            builder.MappingMode(MappingMode.Default);
