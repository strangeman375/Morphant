    [Test]
    public async Task Gates_Create_and_Update_without_changing_the_shared_contract()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;
using Morphant.Context;
using System;

namespace TestCase
{
    public readonly struct Source
    {
        public int Value { get; init; }
    }

    public sealed class CreateDestination
    {
        public int Value { get; set; }
    }

    public sealed class UpdateDestination
    {
        public int Value { get; set; }
    }

    public sealed class BothDestination
    {
        public int Value { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, CreateDestination>(MappingMode.Create);
            builder.Map<Source, UpdateDestination>(MappingMode.Update);
            builder.Map<Source, BothDestination>();
        }
    }

    public static class Scenario
    {
        public static void Verify()
        {
            var mapper = new TestMapper();
            var source = new Source { Value = 17 };
            var context = default(MappingContext);
            var create =
                (ITypeMapper<Source, CreateDestination>)mapper;
            var update =
                (ITypeMapper<Source, UpdateDestination>)mapper;
            var both =
                (ITypeMapper<Source, BothDestination>)mapper;

            if (create.Map(source, context).Value != 17)
            {
                throw new InvalidOperationException(
                    "Create did not map a new destination.");
            }

            ExpectNotSupported(() =>
                create.Map(source, new CreateDestination(), context));
            ExpectNotSupported(() => update.Map(source, context));

            var previous = new UpdateDestination();
            var updated = update.Map(source, previous, context);
            var createdByUpdate = update.Map(source, null, context);

            if (!ReferenceEquals(previous, updated) ||
                updated.Value != 17 ||
                createdByUpdate.Value != 17)
            {
                throw new InvalidOperationException(
                    "Update did not preserve its declarative semantics.");
            }

            var bothPrevious = new BothDestination();
            var bothCreated = both.Map(source, context);
            var bothUpdated = both.Map(source, bothPrevious, context);

            if (bothCreated.Value != 17 ||
                !ReferenceEquals(bothPrevious, bothUpdated) ||
                bothUpdated.Value != 17)
            {
                throw new InvalidOperationException(
                    "CreateAndUpdate did not enable both operations.");
            }
        }

        private static void ExpectNotSupported(Action action)
        {
            try
            {
                action();
            }
            catch (NotSupportedException)
            {
                return;
            }

            throw new InvalidOperationException(
                "A disabled operation did not throw NotSupportedException.");
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.CreateDestination>,
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.UpdateDestination>,
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.BothDestination>
    {
        /// <inheritdoc/>
        global::TestCase.CreateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.CreateDestination>.Map(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.CreateDestination()
            {
                Value = source.Value
            };
        }

        /// <inheritdoc/>
        global::TestCase.CreateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.CreateDestination>.Map(
            global::TestCase.Source source,
            global::TestCase.CreateDestination? destination,
            global::Morphant.Context.MappingContext context)
            => throw new global::System.NotSupportedException(
                "The effective MappingMode does not include Update.");

        /// <inheritdoc/>
        global::TestCase.UpdateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.UpdateDestination>.Map(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => throw new global::System.NotSupportedException(
                "The effective MappingMode does not include Create.");

        /// <inheritdoc/>
        global::TestCase.UpdateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.UpdateDestination>.Map(
            global::TestCase.Source source,
            global::TestCase.UpdateDestination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (destination is null)
            {
                return CreateImpl(source);
            }

            destination.Value = source.Value;

            return destination;
        }

        private global::TestCase.UpdateDestination CreateImpl(
            global::TestCase.Source source)
        {
            return new global::TestCase.UpdateDestination()
            {
                Value = source.Value
            };
        }

        /// <inheritdoc/>
        global::TestCase.BothDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.BothDestination>.Map(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => CreateImpl1(source);

        /// <inheritdoc/>
        global::TestCase.BothDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.BothDestination>.Map(
            global::TestCase.Source source,
            global::TestCase.BothDestination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (destination is null)
            {
                return CreateImpl1(source);
            }

            destination.Value = source.Value;

            return destination;
        }

        private global::TestCase.BothDestination CreateImpl1(
            global::TestCase.Source source)
        {
            return new global::TestCase.BothDestination()
            {
                Value = source.Value
            };
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
        ConventionTypeMapperGeneratorTest.RunAndExecute(
            LanguageVersion.CSharp9,
            source,
            "TestCase.Scenario");
    }

