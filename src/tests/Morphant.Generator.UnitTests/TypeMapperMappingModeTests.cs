    [Test]
    public async Task Gates_Create_and_Update_without_changing_the_shared_contract()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;
using Morphant.Context;
using System;

namespace TestCase
{
    public readonly struct Source
    {
        public int Value { get; init; }
    }

    public sealed class CreateDestination
    {
        public int Value { get; set; }
    }

    public sealed class UpdateDestination
    {
        public int Value { get; set; }
    }

    public sealed class BothDestination
    {
        public int Value { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, CreateDestination>(MappingMode.Create);
            builder.Map<Source, UpdateDestination>(MappingMode.Update);
            builder.Map<Source, BothDestination>();
        }
    }

    public static class Scenario
    {
        public static void Verify()
        {
            var mapper = new TestMapper();
            var source = new Source { Value = 17 };
            var context = default(MappingContext);
            var create =
                (ITypeMapper<Source, CreateDestination>)mapper;
            var update =
                (ITypeMapper<Source, UpdateDestination>)mapper;
            var both =
                (ITypeMapper<Source, BothDestination>)mapper;

            if (create.Create(source, context).Value != 17)
            {
                throw new InvalidOperationException(
                    "Create did not map a new destination.");
            }

            ExpectOperationNotSupported(() =>
                create.Update(source, new CreateDestination(), context));
            ExpectOperationNotSupported(() => update.Create(source, context));

            var previous = new UpdateDestination();
            var updated = update.Update(source, previous, context);
            var createdByUpdate = update.Update(source, null, context);

            if (!ReferenceEquals(previous, updated) ||
                updated.Value != 17 ||
                createdByUpdate.Value != 17)
            {
                throw new InvalidOperationException(
                    "Update did not preserve its declarative semantics.");
            }

            var bothPrevious = new BothDestination();
            var bothCreated = both.Create(source, context);
            var bothUpdated = both.Update(source, bothPrevious, context);

            if (bothCreated.Value != 17 ||
                !ReferenceEquals(bothPrevious, bothUpdated) ||
                bothUpdated.Value != 17)
            {
                throw new InvalidOperationException(
                    "CreateAndUpdate did not enable both operations.");
            }
        }

        private static void ExpectOperationNotSupported(Action action)
        {
            try
            {
                action();
            }
            catch (Morphant.Exceptions.MappingOperationNotSupportedException)
            {
                return;
            }

            throw new InvalidOperationException(
                "A disabled operation did not report its mapping failure.");
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.CreateDestination>,
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.UpdateDestination>,
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.BothDestination>
    {
        /// <inheritdoc/>
        global::TestCase.CreateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.CreateDestination>.Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => __Create(source, context);

        /// <inheritdoc/>
        global::TestCase.CreateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.CreateDestination>.Update(
            global::TestCase.Source source,
            global::TestCase.CreateDestination? destination,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingOperationNotSupportedException(
                global::Morphant.Context.MappingOperation.Update,
                typeof(global::TestCase.Source),
                typeof(global::TestCase.CreateDestination));

        private global::TestCase.CreateDestination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.CreateDestination()
            {
                Value = source.Value
            };
        }

        /// <inheritdoc/>
        global::TestCase.UpdateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.UpdateDestination>.Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingOperationNotSupportedException(
                global::Morphant.Context.MappingOperation.Create,
                typeof(global::TestCase.Source),
                typeof(global::TestCase.UpdateDestination));

        /// <inheritdoc/>
        global::TestCase.UpdateDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.UpdateDestination>.Update(
            global::TestCase.Source source,
            global::TestCase.UpdateDestination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (destination is null)
            {
                return __Create1(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.UpdateDestination __Create1(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.UpdateDestination()
            {
                Value = source.Value
            };
        }

        private global::TestCase.UpdateDestination __Update(
            global::TestCase.Source source,
            global::TestCase.UpdateDestination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.Value = source.Value;

            return destination;
        }

        /// <inheritdoc/>
        global::TestCase.BothDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.BothDestination>.Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => __Create2(source, context);

        /// <inheritdoc/>
        global::TestCase.BothDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.BothDestination>.Update(
            global::TestCase.Source source,
            global::TestCase.BothDestination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (destination is null)
            {
                return __Create2(source, context);
            }

            return __Update1(source, destination, context);
        }

        private global::TestCase.BothDestination __Create2(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.BothDestination()
            {
                Value = source.Value
            };
        }

        private global::TestCase.BothDestination __Update1(
            global::TestCase.Source source,
            global::TestCase.BothDestination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.Value = source.Value;

            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }

