using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.ConstructionSurfaceTests;

[TestFixture]
internal sealed class TupleSurfaceTests
{
    [Test]
    public void Generates_flat_generic_construction_and_member_plans()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed record Source<T>(T Value, int Count);

    [MorphantMapper]
    public partial class TestMapper<T> : TypeMapper
        where T : class, new()
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source<T>, (T Value, int Count)>();
    }
}
""";

        // lang=c#
        const string expectedConstruction =
"""
// <auto-generated />
#nullable enable

namespace Morphant.Generated
{
    /// <summary>
    /// Maps constructor arguments for <see cref="T:System.ValueTuple`2"/>.
    /// </summary>
    internal sealed class ValueTuple2_4326ca7132239af9ConstructorParameters<T>
    {
        /// <summary>
        /// Maps the <c>Value</c> argument.
        /// </summary>
        public global::Morphant.Members.ConstructorParameter<T> Value = null!;

        /// <summary>
        /// Maps the <c>Count</c> argument.
        /// </summary>
        public global::Morphant.Members.ConstructorParameter<int> Count = null!;
    }

    /// <summary>
    /// Defines construction of <see cref="T:System.ValueTuple`2"/>.
    /// </summary>
    internal sealed class ValueTuple2_4326ca7132239af9Construction<T>
    {
        /// <summary>
        /// Uses convention-based construction.
        /// </summary>
        /// <param name="marker">The convention marker.</param>
        /// <param name="parameters">Optional argument mappings.</param>
        public ValueTuple2_4326ca7132239af9Construction(
            global::Morphant.Markers.ByConventionMarker marker,
            ValueTuple2_4326ca7132239af9ConstructorParameters<T>? parameters = null)
        {
        }

        /// <summary>
        /// Uses the corresponding destination constructor.
        /// </summary>
        /// <param name="Value">Maps the <c>Value</c> argument.</param>
        /// <param name="Count">Maps the <c>Count</c> argument.</param>
        public ValueTuple2_4326ca7132239af9Construction(
            global::Morphant.Members.ConstructorParameter<T> Value,
            global::Morphant.Members.ConstructorParameter<int> Count)
        {
        }

        /// <summary>
        /// Uses the existing destination as the result.
        /// </summary>
        /// <param name="previous">The existing destination.</param>
        public static implicit operator ValueTuple2_4326ca7132239af9Construction<T>(
            global::Morphant.Option<(T, int)> previous) =>
            throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        // lang=c#
        const string expectedMembers =
"""
// <auto-generated />
#nullable enable

namespace Morphant.Generated
{
    /// <summary>
    /// Maps members of <see cref="T:System.ValueTuple`2"/>.
    /// </summary>
    internal sealed record ValueTuple2_4326ca7132239af9Members<T>
    {
        /// <summary>
        /// Maps tuple element <c>Value</c>.
        /// </summary>
        public global::Morphant.Members.Member<T> Value
        {
            get => null!;
            set { }
        }

        /// <summary>
        /// Maps tuple element <c>Count</c>.
        /// </summary>
        public global::Morphant.Members.Member<int> Count
        {
            get => null!;
            set { }
        }

        public bool Equals(ValueTuple2_4326ca7132239af9Members<T>? other) => false;

        public override int GetHashCode() => 0;

        public override string ToString() => string.Empty;

        private bool PrintMembers(global::System.Text.StringBuilder builder) => false;
    }
}
""";

        var result = GeneratorTestDriver.Run(
            "TupleSurfaceConsumer",
            source,
            LanguageVersion.CSharp9);
        var tupleSources = result.GeneratedSources
            .Where(static generated => generated.HintName.Contains(
                ".Tuple_",
                StringComparison.Ordinal))
            .OrderBy(static generated => generated.HintName,
                StringComparer.Ordinal)
            .ToArray();

        Assert.Multiple(() =>
        {
            Assert.That(
                tupleSources.Select(static generated => generated.HintName),
                Is.EqualTo(new[]
                {
                    "Morphant.Generated.Construction.Tuple_" +
                    "ValueTuple2_4326ca7132239af9.g.cs",
                    "Morphant.Generated.Member.Tuple_" +
                    "ValueTuple2_4326ca7132239af9.g.cs"
                }));
            Assert.That(
                tupleSources[0].SourceText.ToString(),
                Is.EqualTo(GeneratedSourceText.Normalize(
                    expectedConstruction)));
            Assert.That(
                tupleSources[1].SourceText.ToString(),
                Is.EqualTo(GeneratedSourceText.Normalize(expectedMembers)));
            Assert.That(result.CompilerWarningsAndErrors, Is.Empty);
        });
    }
}
