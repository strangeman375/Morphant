using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.ConstructionSurfaceTests;

[TestFixture]
internal sealed class ConstructionSurfaceAttributeTests
{
    [Test]
    public async Task Copies_applicable_Obsolete_attributes_to_the_generated_plan()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using System;
using Morphant;

namespace TestCase
{
    public sealed class Source { }

    [Obsolete("Use CurrentDestination instead.")]
    public sealed class Destination
    {
        [Obsolete("Use the string constructor.", true)]
        public Destination(int value) { }

        public Destination(string value) { }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, {|CS0618:Destination|}>();
    }
}
""";

        // lang=c#
        const string construction =
"""
// <auto-generated />
#nullable enable

namespace TestCase.Morphant.Generated
{
    /// <summary>
    /// Contains mappings for constructor arguments of <see cref="global::TestCase.Destination"/>.
    /// </summary>
    internal sealed class DestinationConstructorParameters
    {
        /// <summary>
        /// Configures the <c>value</c> constructor argument.
        /// </summary>
        public global::Morphant.Members.ConstructorParameter<int> valueInt = null!;

        /// <summary>
        /// Configures the <c>value</c> constructor argument.
        /// </summary>
        public global::Morphant.Members.ConstructorParameter<string> valueString = null!;
    }

    /// <summary>
    /// Describes construction of <see cref="global::TestCase.Destination"/>.
    /// </summary>
    [global::System.ObsoleteAttribute("Use CurrentDestination instead.")]
    internal sealed class DestinationConstruction
    {
        /// <summary>
        /// Creates a destination instance using convention-based mapping.
        /// </summary>
        /// <param name="marker">Selects convention-based construction.</param>
        /// <param name="parameters">Specifies optional mappings for constructor arguments.</param>
        public DestinationConstruction(
            global::Morphant.Markers.ByConventionMarker marker,
            DestinationConstructorParameters? parameters = null)
        {
        }

        /// <summary>
        /// Creates a destination instance using factory-based construction.
        /// </summary>
        /// <param name="marker">Selects factory-based construction.</param>
        public DestinationConstruction(global::Morphant.Markers.IByFactoryMarker<global::TestCase.Destination> marker)
        {
        }

        /// <summary>
        /// Creates a destination instance using a corresponding constructor.
        /// </summary>
        /// <param name="value">Configures the <c>value</c> constructor argument.</param>
        [global::System.ObsoleteAttribute("Use the string constructor.", true)]
        public DestinationConstruction(global::Morphant.Members.ConstructorParameter<int> value)
        {
        }

        /// <summary>
        /// Creates a destination instance using a corresponding constructor.
        /// </summary>
        /// <param name="value">Configures the <c>value</c> constructor argument.</param>
        public DestinationConstruction(global::Morphant.Members.ConstructorParameter<string> value)
        {
        }

        /// <summary>
        /// Selects an existing destination as the mapping result.
        /// </summary>
        /// <param name="previous">The existing destination to select.</param>
        public static implicit operator DestinationConstruction(
            global::Morphant.Option<global::TestCase.Destination> previous) =>
            throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        // lang=c#
        const string extension =
"""
// <auto-generated />
#nullable enable

namespace Morphant
{
    internal static partial class MorphantGeneratedMappingExtensions
    {
        /// <summary>
        /// Configures how to construct a destination when no existing destination is used.
        /// </summary>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="construct">A lambda expression that receives the non-null source and describes destination construction.</param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Construct(
            this global::Morphant.MapperBuilder<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> builder,
            global::System.Func<global::TestCase.Source, {|CS0618:global::TestCase.Morphant.Generated.DestinationConstruction|}> construct)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Configures how to select or construct the destination from the source and an optional existing destination.
        /// </summary>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="construct">A lambda expression that receives the non-null source and the optional existing destination and describes destination construction.</param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Construct(
            this global::Morphant.MapperBuilder<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> builder,
            global::System.Func<global::TestCase.Source, global::Morphant.Option<{|CS0618:global::TestCase.Destination|}>, {|CS0618:global::TestCase.Morphant.Generated.DestinationConstruction|}> construct)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Configures a fully manual mapping algorithm.
        /// </summary>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="mapping">A lambda expression that receives the original source, the optional existing destination, and the current mapping context.</param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Convert(
            this global::Morphant.MapperBuilder<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> builder,
            global::System.Func<global::TestCase.Source?, global::Morphant.Option<{|CS0618:global::TestCase.Destination|}>, global::Morphant.Context.MappingContext, {|CS0618:global::TestCase.Destination|}> mapping)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        await ConstructionSurfaceGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.Construction.TestCase_Destination.g.cs",
                construction
            ),
            (
                "Morphant.Generated.MappingExtension.TestCase_Source__TestCase_Destination.g.cs",
                extension
            ));
    }

}
