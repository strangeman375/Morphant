using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests;

[TestFixture]
internal sealed class TemplateTypeGenerationTests
{
    [Test]
    public async Task Generates_template_type()
    {
        const string source =
"""
using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
        public int Id { get; set; }
    }

    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();
        }
    }
}
""";

        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase.Morphant.Generated
{

    internal sealed record DestinationMorphantTemplate
    {
        public DestinationMorphantTemplate(global::Morphant.Markers.ByConventionMarker _)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        public DestinationMorphantTemplate()
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        public global::Morphant.Members.Member<int> @Id
        {
            get => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
            set => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
        }
    }
}

""";

        await RunAndAssert(LanguageVersion.CSharp9, source, "Morphant.TemplateType.TestCase_Destination.g.cs", expected);
    }

    private static async Task RunAndAssert(LanguageVersion languageVersion, string sourceFileContent, string expectedFileName, string expectedFileContent)
    {
        var test = new TemplateTypeGeneratorTest(languageVersion)
        {
            TestCode = sourceFileContent
        };

        test.TestState.GeneratedSources.Add((typeof(TestTemplateTypeGenerator), expectedFileName, expectedFileContent));
        await test.RunAsync();
    }
}
