    [Test]
    public async Task Uses_boxed_runtime_type_for_nullable_strict_source()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public readonly struct Number
    {
        public Number(int value) => Value = value;
        public int Value { get; }
    }

    public sealed class NumberDto
    {
        public int Value { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Number?, NumberDto>(MappingMode.Create)
                .UnknownDerivedTypeHandling(
                    UnknownDerivedTypeHandling.Throw);
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Number?, global::TestCase.NumberDto>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Number?) &&
                    destinationType == typeof(global::TestCase.NumberDto)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.NumberDto global::Morphant.ITypeMapper<global::TestCase.Number?, global::TestCase.NumberDto>.Create(
            global::TestCase.Number? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            var sourceValue = source.Value;

            return __CreatePolymorphic(sourceValue, context);
        }

        /// <inheritdoc/>
        global::TestCase.NumberDto global::Morphant.ITypeMapper<global::TestCase.Number?, global::TestCase.NumberDto>.Update(
            global::TestCase.Number? source,
            global::TestCase.NumberDto? destination,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingOperationNotSupportedException(
                global::Morphant.Context.MappingOperation.Update,
                typeof(global::TestCase.Number?),
                typeof(global::TestCase.NumberDto),
                global::Morphant.MappingMode.Create);

        private global::TestCase.NumberDto __CreatePolymorphic(
            global::TestCase.Number sourceValue,
            global::Morphant.Context.MappingContext context)
        {
            if (sourceValue.GetType() != typeof(global::TestCase.Number))
            {
                throw new global::Morphant.Exceptions.UnmatchedPolymorphicMappingException(
                    global::Morphant.Context.MappingOperation.Create,
                    typeof(global::TestCase.Number?),
                    typeof(global::TestCase.NumberDto),
                    sourceValue.GetType());
            }

            return __Create(sourceValue, context);
        }

        private global::TestCase.NumberDto __Create(
            global::TestCase.Number sourceValue,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.NumberDto()
            {
                Value = sourceValue.Value
            };
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }
