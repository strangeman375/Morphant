using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.RuntimePolymorphismTests;

[TestFixture]
internal sealed class ValueDestinationDispatchTests
{
    [Test]
    public async Task Keeps_value_destination_dispatch_strongly_typed()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public class Animal { }
    public sealed class Dog : Animal { }
    public readonly struct AnimalDto { }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Animal, AnimalDto>()
                .ForDerived<Dog, AnimalDto>();
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Animal, global::TestCase.AnimalDto>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Animal) &&
                    destinationType == typeof(global::TestCase.AnimalDto)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.AnimalDto global::Morphant.ITypeMapper<global::TestCase.Animal, global::TestCase.AnimalDto>.Create(
            global::TestCase.Animal? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (__TryCreatePolymorphic(source, context, out var polymorphicDestination))
            {
                return polymorphicDestination;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.AnimalDto global::Morphant.ITypeMapper<global::TestCase.Animal, global::TestCase.AnimalDto>.Update(
            global::TestCase.Animal? source,
            global::TestCase.AnimalDto destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (__TryUpdatePolymorphic(source, destination, context, out var polymorphicDestination))
            {
                return polymorphicDestination;
            }

            return __Update(source, destination, context);
        }

        private bool __TryCreatePolymorphic(
            global::TestCase.Animal source,
            global::Morphant.Context.MappingContext context,
            out global::TestCase.AnimalDto result)
        {
            switch (source)
            {
                case global::TestCase.Dog polymorphicSource:
                    result = context.Mapper.Map<global::TestCase.Dog, global::TestCase.AnimalDto>(polymorphicSource);
                    return true;

                default:
                    result = default!;
                    return false;
            }
        }

        private bool __TryUpdatePolymorphic(
            global::TestCase.Animal source,
            global::TestCase.AnimalDto destination,
            global::Morphant.Context.MappingContext context,
            out global::TestCase.AnimalDto result)
        {
            switch (source)
            {
                case global::TestCase.Dog polymorphicSource:
                    result = context.Mapper.Map<global::TestCase.Dog, global::TestCase.AnimalDto>(polymorphicSource, destination);
                    return true;

                default:
                    result = default!;
                    return false;
            }
        }

        private global::TestCase.AnimalDto __Create(
            global::TestCase.Animal source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.AnimalDto();
        }

        private global::TestCase.AnimalDto __Update(
            global::TestCase.Animal source,
            global::TestCase.AnimalDto destination,
            global::Morphant.Context.MappingContext context)
        {
            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }

    [Test]
    public async Task Keeps_nullable_value_destination_dispatch_strongly_typed()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public class Animal { }
    public sealed class Dog : Animal { }
    public readonly struct AnimalDto { }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Animal, AnimalDto?>()
                .ForDerived<Dog, AnimalDto?>();
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Animal, global::TestCase.AnimalDto?>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Animal) &&
                    destinationType == typeof(global::TestCase.AnimalDto?)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.AnimalDto? global::Morphant.ITypeMapper<global::TestCase.Animal, global::TestCase.AnimalDto?>.Create(
            global::TestCase.Animal? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (__TryCreatePolymorphic(source, context, out var polymorphicDestination))
            {
                return polymorphicDestination;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.AnimalDto? global::Morphant.ITypeMapper<global::TestCase.Animal, global::TestCase.AnimalDto?>.Update(
            global::TestCase.Animal? source,
            global::TestCase.AnimalDto? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (__TryUpdatePolymorphic(source, destination, context, out var polymorphicDestination))
            {
                return polymorphicDestination;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination.Value, context);
        }

        private bool __TryCreatePolymorphic(
            global::TestCase.Animal source,
            global::Morphant.Context.MappingContext context,
            out global::TestCase.AnimalDto? result)
        {
            switch (source)
            {
                case global::TestCase.Dog polymorphicSource:
                    result = context.Mapper.Map<global::TestCase.Dog, global::TestCase.AnimalDto?>(polymorphicSource);
                    return true;

                default:
                    result = default!;
                    return false;
            }
        }

        private bool __TryUpdatePolymorphic(
            global::TestCase.Animal source,
            global::TestCase.AnimalDto? destination,
            global::Morphant.Context.MappingContext context,
            out global::TestCase.AnimalDto? result)
        {
            switch (source)
            {
                case global::TestCase.Dog polymorphicSource:
                    result = context.Mapper.Map<global::TestCase.Dog, global::TestCase.AnimalDto?>(polymorphicSource, destination);
                    return true;

                default:
                    result = default!;
                    return false;
            }
        }

        private global::TestCase.AnimalDto? __Create(
            global::TestCase.Animal source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.AnimalDto();
        }

        private global::TestCase.AnimalDto? __Update(
            global::TestCase.Animal source,
            global::TestCase.AnimalDto destination,
            global::Morphant.Context.MappingContext context)
        {
            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }

}
