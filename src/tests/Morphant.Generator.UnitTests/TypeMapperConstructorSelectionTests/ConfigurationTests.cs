using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperConstructorSelectionTests;

[TestFixture]
internal sealed class ConfigurationTests
{
    [Test]
    public void Resolves_mapping_mapper_and_library_Default_precedence()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;
using Morphant.Context;
using System;

namespace TestCase
{
    public sealed class Source
    {
        public int Id { get; init; }

        public int Code { get; init; }
    }

    public sealed class RootDestination
    {
        public RootDestination()
        {
            Kind = "parameterless";
        }

        public RootDestination(int id)
        {
            Kind = id.ToString();
        }

        public string Kind { get; }
    }

    public sealed class MappingDestination
    {
        public MappingDestination(int id)
        {
            Kind = "small:" + id;
        }

        public MappingDestination(
            int code,
            string label = "default")
        {
            Kind = "largest:" + code + ":" + label;
        }

        public string Kind { get; }
    }

    public sealed class LibraryDestination
    {
        public LibraryDestination()
        {
            Kind = "parameterless";
        }

        public LibraryDestination(int id)
        {
            Kind = "unambiguous:" + id;
        }

        public string Kind { get; }
    }

    [MorphantMapper]
    public partial class ConfiguredMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.ConstructorSelection(
                ConstructorSelection.Parameterless);

            builder.Map<Source, RootDestination>()
                .ConstructorSelection(ConstructorSelection.Default);
            builder.Map<Source, MappingDestination>()
                .ConstructorSelection(ConstructorSelection.Largest);
        }
    }

    [MorphantMapper]
    public partial class LibraryMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, LibraryDestination>();
    }

    public static class Scenario
    {
        public static void Verify()
        {
            var source = new Source { Id = 17, Code = 31 };
            var context = default(MappingContext);
            var configured = new ConfiguredMapper();
            var root =
                ((ITypeMapper<Source, RootDestination>)configured)
                    .Create(source, context);
            var mapping =
                ((ITypeMapper<Source, MappingDestination>)configured)
                    .Create(source, context);
            var library =
                ((ITypeMapper<Source, LibraryDestination>)
                    new LibraryMapper()).Create(source, context);

            if (root.Kind != "parameterless" ||
                mapping.Kind != "largest:31:default" ||
                library.Kind != "unambiguous:17")
            {
                throw new InvalidOperationException(
                    "ConstructorSelection precedence was not preserved.");
            }
        }
    }
}
""";

        ConventionTypeMapperGeneratorTest.RunAndExecute(
            LanguageVersion.CSharp9,
            source,
            "TestCase.Scenario");
    }

    [Test]
    public async Task Resolves_Default_to_the_assembly_ConstructorSelection()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
        public int Id { get; init; }
    }

    public sealed class Destination
    {
        public Destination()
        {
        }

        public Destination(int id)
        {
            Id = id;
        }

        public int Id { get; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder
                .ConstructorSelection(ConstructorSelection.Default)
                .Map<Source, Destination>()
                .ConstructorSelection(ConstructorSelection.Default);
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination();
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest
            .RunAndAssertWithAnalyzerConfig(
                LanguageVersion.CSharp9,
                source,
                """
is_global = true

build_property.MorphantConstructorSelection = Parameterless
""",
                (
                    "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs",
                    expected
                ));
    }
}
