using Microsoft.CodeAnalysis.CSharp;

namespace Morphant.Generator.UnitTests.TestUtils;

internal static class TemplateTypeNamingTestHarness
{
    public static Task RunAndAssert(
        string source,
        params ExpectedTemplateType[] expectedTemplateTypes)
    {
        var expectedSources =
            new (string FileName, string Content)[expectedTemplateTypes.Length];

        for (var i = 0; i < expectedTemplateTypes.Length; i++)
        {
            var expected = expectedTemplateTypes[i];

            expectedSources[i] =
            (
                "Morphant.Generated.TemplateType." + expected.HintNamePart + ".g.cs",
                BuildExpectedSource(expected)
            );
        }

        return TemplateTypeGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expectedSources);
    }

    public static ExpectedTemplateType ExpectedTemplate(
        string hintNamePart,
        string templateNamespace,
        string templateTypeName,
        string destinationTypeName)
    {
        return new ExpectedTemplateType(
            hintNamePart,
            templateNamespace,
            templateTypeName,
            destinationTypeName);
    }

    private static string BuildExpectedSource(
        ExpectedTemplateType expected)
    {
        return $$"""
                 // <auto-generated />
                 #nullable enable

                 namespace {{expected.TemplateNamespace}}
                 {
                     /// <inheritdoc cref="{{expected.DestinationTypeName}}"/>
                     internal sealed record {{expected.TemplateTypeName}}
                     {
                         /// <summary>
                         /// Creates a destination instance using convention-based mapping.
                         /// </summary>
                         /// <param name="marker">Selects convention-based mapping.</param>
                         public {{expected.TemplateTypeName}}(global::Morphant.Markers.ByConventionMarker marker)
                         {
                         }

                         /// <summary>
                         /// Creates a destination instance using factory-based destination construction.
                         /// </summary>
                         /// <param name="marker">Selects factory-based construction.</param>
                         public {{expected.TemplateTypeName}}(global::Morphant.Markers.ByFactoryMarker<{{expected.DestinationTypeName}}> marker)
                         {
                         }

                         /// <summary>
                         /// Creates a destination instance using a corresponding constructor.
                         /// </summary>
                         public {{expected.TemplateTypeName}}()
                         {
                         }

                         public bool Equals({{expected.TemplateTypeName}}? other) => false;

                         public override int GetHashCode() => 0;

                         public override string ToString() => string.Empty;

                         private bool PrintMembers(global::System.Text.StringBuilder builder) => false;
                     }
                 }
                 """;
    }

    internal readonly record struct ExpectedTemplateType(
        string HintNamePart,
        string TemplateNamespace,
        string TemplateTypeName,
        string DestinationTypeName);
}
