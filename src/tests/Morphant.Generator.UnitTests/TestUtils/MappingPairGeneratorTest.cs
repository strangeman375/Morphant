using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Testing;
using Microsoft.CodeAnalysis.Testing;

namespace Morphant.Generator.UnitTests.TestUtils;

internal sealed class MappingPairGeneratorTest :
    CSharpSourceGeneratorTest<TestMappingPairGenerator, DefaultVerifier>
{
    private const string NewLine = "\r\n";

    private readonly LanguageVersion _languageVersion;

    private MappingPairGeneratorTest(LanguageVersion languageVersion)
    {
        _languageVersion = languageVersion;
        CompilerDiagnostics = CompilerDiagnostics.Warnings;
        TestState.AdditionalReferences.Add(typeof(TypeMapper).Assembly);
    }

    protected override ParseOptions CreateParseOptions()
    {
        return new CSharpParseOptions(
            _languageVersion,
            DocumentationMode.Diagnose);
    }

    public static async Task RunAndAssert(
        LanguageVersion languageVersion,
        string sourceFileContent,
        string expectedSource)
    {
        var test = new MappingPairGeneratorTest(languageVersion)
        {
            TestCode = sourceFileContent
        };

        test.TestState.GeneratedSources.Add(
        (
            typeof(TestMappingPairGenerator),
            "MappingPairModel.g.cs",
            NormalizeGeneratedSource(expectedSource)
        ));

        await test.RunAsync();
    }

    public static Task RunAndAssert(
        LanguageVersion languageVersion,
        string sourceFileContent,
        string mapperIdentity,
        bool hasUnifiablePairs,
        params MappingPairExpectation[] pairs)
    {
        return RunAndAssert(
            languageVersion,
            sourceFileContent,
            BuildExpectedSource(
                mapperIdentity,
                hasUnifiablePairs,
                pairs));
    }

    private static string BuildExpectedSource(
        string mapperIdentity,
        bool hasUnifiablePairs,
        IReadOnlyList<MappingPairExpectation> pairs)
    {
        var builder = new StringBuilder();

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.Append("// Mapper: ").AppendLine(mapperIdentity);
        builder.Append("// Unifiable: ")
            .AppendLine(hasUnifiablePairs.ToString());
        builder.Append("// Pairs: ").AppendLine(pairs.Count.ToString());

        for (var index = 0; index < pairs.Count; index++)
        {
            var pair = pairs[index];

            builder.Append("// Pair ")
                .Append(index)
                .Append(": ")
                .Append(pair.Source)
                .Append(" -> ")
                .AppendLine(pair.Destination);
            builder.Append("// Capabilities ")
                .Append(index)
                .Append(": Runtime=True; Manual=True; Structured=")
                .Append(pair.Structured)
                .Append("; Direct=")
                .Append(!pair.Structured)
                .Append("; Members=")
                .AppendLine(pair.Members.ToString());
        }

        return builder.ToString();
    }

    private static string NormalizeGeneratedSource(string source)
    {
        var normalized = source
            .Replace("\r\n", "\n")
            .Replace('\r', '\n')
            .Replace("\n", NewLine);

        return normalized.EndsWith(NewLine, StringComparison.Ordinal)
            ? normalized
            : normalized + NewLine;
    }
}

internal readonly record struct MappingPairExpectation(
    string Source,
    string Destination,
    bool Structured,
    bool Members);
