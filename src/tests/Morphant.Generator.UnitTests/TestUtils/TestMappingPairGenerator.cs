using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Morphant.Generator.MappingPair;
using Morphant.Generator.MapperBuilderMap;
using Morphant.Generator.TypeMapperConfigure;

namespace Morphant.Generator.UnitTests.TestUtils;

internal sealed class TestMappingPairGenerator : IIncrementalGenerator
{
    public void Initialize(
        IncrementalGeneratorInitializationContext context)
    {
        var compilationContext =
            CompilationContextPipeline.Build(context);
        var configureInfos = TypeMapperConfigurePipeline.Build(
            context,
            compilationContext);
        var mapInfos = MapperBuilderMapPipeline.Build(
            compilationContext,
            configureInfos);
        var mappingPairs = MappingPairPipeline.Build(
            compilationContext,
            mapInfos);

        context.RegisterSourceOutput(
            mappingPairs,
            static (sourceProductionContext, model) =>
                sourceProductionContext.AddSource(
                    "MappingPairModel.g.cs",
                    Emit(model)));
    }

    private static SourceText Emit(MapperMappingPairModel model)
    {
        const string newLine = "\r\n";
        var builder = new StringBuilder();

        builder.Append("// <auto-generated />").Append(newLine);
        builder.Append("#nullable enable").Append(newLine);
        builder.Append(newLine);
        builder.Append("// Mapper: ")
            .Append(model.MapperIdentity)
            .Append(newLine);
        builder.Append("// Unifiable: ")
            .Append(model.HasUnifiablePairs)
            .Append(newLine);
        builder.Append("// Pairs: ")
            .Append(model.Pairs.Length)
            .Append(newLine);

        for (var index = 0; index < model.Pairs.Length; index++)
        {
            var pair = model.Pairs[index];
            var capabilities = pair.Capabilities;

            builder.Append("// Pair ")
                .Append(index)
                .Append(": ")
                .Append(pair.Identity.Source.DisplayName)
                .Append(" -> ")
                .Append(pair.Identity.Destination.DisplayName)
                .Append(newLine);
            builder.Append("// Capabilities ")
                .Append(index)
                .Append(": Runtime=")
                .Append(capabilities.Runtime)
                .Append("; Manual=")
                .Append(capabilities.Manual)
                .Append("; Structured=")
                .Append(capabilities.StructuredConstruction)
                .Append("; Direct=")
                .Append(capabilities.DirectConstruction)
                .Append("; Members=")
                .Append(capabilities.Members)
                .Append(newLine);
        }

        return SourceText.From(builder.ToString(), Encoding.UTF8);
    }
}
