    [Test]
    public void Suppression_and_severity_do_not_change_recovery_artifacts()
    {
        var visible = InheritanceDiagnosticsGeneratorTest.Run(MissingSource);
        var suppressed = InheritanceDiagnosticsGeneratorTest.Run(
            MissingSource,
            new Dictionary<string, ReportDiagnostic>
            {
                ["MORPH0026"] = ReportDiagnostic.Suppress
            });
        var warning = InheritanceDiagnosticsGeneratorTest.Run(
            MissingSource,
            new Dictionary<string, ReportDiagnostic>
            {
                ["MORPH0026"] = ReportDiagnostic.Warn
            });

        var visibleSources = visible.GeneratedSources
            .Select(static source =>
                (source.HintName, source.SourceText.ToString()))
            .ToArray();
        var suppressedSources = suppressed.GeneratedSources
            .Select(static source =>
                (source.HintName, source.SourceText.ToString()))
            .ToArray();
        var warningSources = warning.GeneratedSources
            .Select(static source =>
                (source.HintName, source.SourceText.ToString()))
            .ToArray();
        var expectedSources = new[]
        {
            (
                "Morphant.Generated.Construction." +
                "TestCase_Destination.g.cs",
                NormalizeExpected(ExpectedConstruction)),
            (
                "Morphant.Generated.MappingExtension." +
                "TestCase_Source__TestCase_Destination.g.cs",
                NormalizeExpected(ExpectedMappingExtension)),
            (
                "Morphant.Generated.TypeMapper." +
                "TestCase_TestMapper.g.cs",
                NormalizeExpected(ExpectedTypeMapper))
        };

        Assert.Multiple(() =>
        {
            Assert.That(
                visible.EffectiveDiagnostics.Single().Id,
                Is.EqualTo("MORPH0026"));
            Assert.That(suppressed.EffectiveDiagnostics, Is.Empty);
            Assert.That(
                warning.EffectiveDiagnostics.Single().Severity,
                Is.EqualTo(DiagnosticSeverity.Warning));
            Assert.That(visibleSources, Is.EqualTo(expectedSources));
            Assert.That(suppressedSources, Is.EqualTo(expectedSources));
            Assert.That(warningSources, Is.EqualTo(expectedSources));
            Assert.That(visible.CompilerWarningsAndErrors, Is.Empty);
            Assert.That(suppressed.CompilerWarningsAndErrors, Is.Empty);
            Assert.That(warning.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    private static string NormalizeExpected(string source)
    {
        return source.ReplaceLineEndings("\r\n") + "\r\n";
    }

    [Test]
    public void Actualizes_lookup_compatibility_and_restoration_on_one_driver()
    {
        // lang=c#
        const string validSource =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public class BaseSource { }
    public sealed class Source : BaseSource { }
    public class BaseDestination { }
    public sealed class Destination : BaseDestination { }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<BaseSource, BaseDestination>();
            builder.Map<Source, Destination>()
                .IncludeBase<BaseSource, BaseDestination>();
        }
    }
}
""";

        // lang=c#
        const string incompatibleSource =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class BaseSource { }
    public sealed class Source { }
    public sealed class BaseDestination { }
    public sealed class Destination { public int Value { get; set; } }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<BaseSource, BaseDestination>();
            builder.Map<Source, Destination>()
                .IncludeBase<BaseSource, BaseDestination>();
        }
    }
}
""";

        var valid = InheritanceDiagnosticsGeneratorTest.Run(validSource);
        var missing = InheritanceDiagnosticsGeneratorTest.Run(
            MissingSource,
            driver: valid.Driver);
        var incompatible = InheritanceDiagnosticsGeneratorTest.Run(
            incompatibleSource,
            driver: missing.Driver);
        var restored = InheritanceDiagnosticsGeneratorTest.Run(
            validSource,
            driver: incompatible.Driver);

        Assert.Multiple(() =>
        {
            Assert.That(valid.EffectiveDiagnostics, Is.Empty);
            Assert.That(
                missing.EffectiveDiagnostics.Select(static diagnostic =>
                    diagnostic.Id),
                Is.EqualTo(new[] { "MORPH0026" }));
            Assert.That(
                incompatible.EffectiveDiagnostics.Select(static diagnostic =>
                    diagnostic.Id),
                Is.EqualTo(new[] { "MORPH0027", "MORPH0027" }));
            Assert.That(restored.EffectiveDiagnostics, Is.Empty);
            Assert.That(restored.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    [Test]
    public void Publishes_in_ID_order_with_independent_earlier_categories()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source { }
    public sealed class Destination { public int Value { get; set; } }
    public sealed class MissingSource { }
    public sealed class MissingDestination { }

    public abstract class RootMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) { }
    }

    [MorphantMapper]
    public partial class TestMapper : RootMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            base.Configure(builder);
            base.Configure(builder);
            builder.Map<Source, Destination>()
                .Members(_ => new())
                .Members(_ => new())
                .IncludeBase<MissingSource, MissingDestination>();
        }
    }
}
""";

        var result = InheritanceDiagnosticsGeneratorTest.Run(source);

        Assert.That(
            result.EffectiveDiagnostics.Select(static diagnostic =>
                diagnostic.Id),
            Is.EqualTo(new[]
            {
                "MORPH0019",
                "MORPH0024",
                "MORPH0026"
            }));
    }
