using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;
using static Morphant.Generator.UnitTests.TestUtils.GeneratorActualizationTest;

namespace Morphant.Generator.UnitTests.ActualizationTests;

[TestFixture]
internal sealed class TypeMapperReferenceActualizationTests
{
    [Test]
    public void Actualizes_mapper_implementation_when_a_reference_changes()
    {
        // lang=c#
        const string referenceV1Source =
"""
#nullable enable
#pragma warning disable CS1591

namespace ExternalModels
{
    public sealed class Destination
    {
        public int Value { get; set; }
    }
}
""";

        // lang=c#
        const string referenceV2Source =
"""
#nullable enable
#pragma warning disable CS1591

namespace ExternalModels
{
    public sealed class Destination
    {
        public Destination(string label) => Label = label;

        public string Label { get; }
    }
}
""";

        // lang=c#
        const string consumerSource =
"""
#nullable enable
#pragma warning disable CS1591

using ExternalModels;
using Morphant;

namespace TestCase
{
    public readonly struct Source
    {
        public int Value { get; init; }

        public string Label { get; init; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string valueMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::ExternalModels.Destination>
    {
        /// <inheritdoc/>
        global::ExternalModels.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::ExternalModels.Destination>.Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => __Create(source, context);

        /// <inheritdoc/>
        global::ExternalModels.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::ExternalModels.Destination>.Update(
            global::TestCase.Source source,
            global::ExternalModels.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::ExternalModels.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::ExternalModels.Destination()
            {
                Value = source.Value
            };
        }

        private global::ExternalModels.Destination __Update(
            global::TestCase.Source source,
            global::ExternalModels.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.Value = source.Value;

            return destination;
        }
    }
}
""";

        // lang=c#
        const string labelMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::ExternalModels.Destination>
    {
        /// <inheritdoc/>
        global::ExternalModels.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::ExternalModels.Destination>.Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
            => __Create(source, context);

        /// <inheritdoc/>
        global::ExternalModels.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::ExternalModels.Destination>.Update(
            global::TestCase.Source source,
            global::ExternalModels.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::ExternalModels.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::ExternalModels.Destination(
                label: source.Label);
        }

        private global::ExternalModels.Destination __Update(
            global::TestCase.Source source,
            global::ExternalModels.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            return destination;
        }
    }
}
""";

        var referenceV1 = CreateReference(
            "ExternalModels",
            referenceV1Source);
        var referenceV2 = CreateReference(
            "ExternalModels",
            referenceV2Source);
        const string hint =
            "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs";

        RunAndAssert(
            LanguageVersion.CSharp9,
            new TestConventionTypeMapperGenerator(),
            StepWithReferences(
                "reference version one",
                consumerSource,
                [referenceV1],
                (hint, valueMapper)),
            StepWithReferences(
                "reference version two",
                consumerSource,
                [referenceV2],
                (hint, labelMapper)),
            StepWithReferences(
                "reference version one restored",
                consumerSource,
                [referenceV1],
                (hint, valueMapper)));
    }
}
