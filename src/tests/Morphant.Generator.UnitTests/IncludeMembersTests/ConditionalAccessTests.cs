using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.IncludeMembersTests;

[TestFixture]
internal sealed class ConditionalAccessTests
{
    [Test]
    public async Task Uses_conditional_access_after_a_receiver_cast_and_guards_casts_inside_the_path()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using Morphant;

namespace TestCase
{
    public sealed class BeforeDetails { public string? BeforeName { get; init; } }
    public sealed class AfterDetails { public string? AfterName { get; init; } }

    public class BaseSource
    {
        public BeforeDetails? Before { get; init; }
        public AfterDetails? After { get; init; }
    }

    public sealed class DerivedSource : BaseSource
    {
        public new BeforeDetails? Before { get; init; }
        public new AfterDetails? After { get; init; }
    }

    public sealed class Box<T> where T : BaseSource
    {
        public T Head { get; init; } = default!;
        public T? Tail { get; init; }
    }

    public sealed class Destination
    {
        public string? BeforeName { get; set; }
        public string? AfterName { get; set; }
    }

    public abstract class Family<TMapper, T> : TypeMapper<TMapper>
        where TMapper : Family<TMapper, T>
        where T : BaseSource
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Box<T>, Destination>()
                .IncludeMembers(source => new
                {
                    Before = source.Head.Before,
                    After = source.Tail?.After
                });
    }

    [MorphantMapper]
    public partial class TestMapper : Family<TestMapper, DerivedSource>
    {
        protected override void Configure(MapperBuilder builder)
        {
            base.Configure(builder);
            builder.Map<Box<DerivedSource>, Destination>()
                .IncludeBase<Box<DerivedSource>, Destination>();
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Box<global::TestCase.DerivedSource>, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Box<global::TestCase.DerivedSource>) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Box<global::TestCase.DerivedSource>, global::TestCase.Destination>.Create(
            global::TestCase.Box<global::TestCase.DerivedSource>? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Box<global::TestCase.DerivedSource>, global::TestCase.Destination>.Update(
            global::TestCase.Box<global::TestCase.DerivedSource>? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Box<global::TestCase.DerivedSource> source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination()
            {
                BeforeName = ((global::TestCase.BaseSource)(source.Head)).Before?.BeforeName,
                AfterName = (source.Tail is { } tail && ((global::TestCase.BaseSource)(tail)).After is { } after ? after.AfterName : default(string?))
            };
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Box<global::TestCase.DerivedSource> source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.BeforeName = ((global::TestCase.BaseSource)(source.Head)).Before?.BeforeName;
            destination.AfterName = (source.Tail is { } tail && ((global::TestCase.BaseSource)(tail)).After is { } after ? after.AfterName : default(string?));

            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(LanguageVersion.CSharp9, source, expected);
    }
}
