    [Test]
    public async Task Does_not_substitute_default_T_for_a_missing_unconstrained_generic_member()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source<T>
    {
        public Details<T>? Details { get; init; }
    }

    public sealed class Details<T>
    {
        public T Value { get; init; } = default!;

        public T Boxed { get; init; } = default!;
    }

    public sealed class Destination<T>
    {
        public T? Value { get; set; }

        public object? Boxed { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper<T> : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source<T>, Destination<T>>()
