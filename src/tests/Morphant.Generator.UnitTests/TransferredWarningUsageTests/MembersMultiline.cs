using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TransferredWarningUsageTests;

[TestFixture]
internal sealed partial class RegressionSnapshotTests
{
    [Test]
    public async Task MembersMultiline()
    {
        const string source =
// lang=c#
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
namespace TestCase
{
    public sealed class Source
    {
        [Obsolete("Legacy value.")]
        public string Legacy => "value";
    }
    public sealed class Destination
    {
        [Obsolete("Legacy constructor.")]
        public Destination(string text) => Text = text;
        public string Text { get; set; }
    }
    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>().Members(source => { var {|CS0219:unused|} = 1; return new() { Text = $@"first
  {{|CS0618:source!.Legacy|}} ""quoted"" {{braces}}
last" }; });
    }
}
""";

        const string expectedMapper =
// lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source);
            }

            return __Update(source, destination);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source)
        {
            #pragma warning disable CS0219
            var unused = 1;
            #pragma warning restore CS0219

            return {|CS0618:new global::TestCase.Destination(
                #pragma warning disable CS0618
                text: $@"first
  {source!.Legacy} ""quoted"" {{braces}}
last")|};
                #pragma warning restore CS0618
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination)
        {
            #pragma warning disable CS0219
            var unused = 1;
            #pragma warning restore CS0219

            #pragma warning disable CS0618
            destination.Text = $@"first
  {source!.Legacy} ""quoted"" {{braces}}
last";
            #pragma warning restore CS0618

            return destination;
        }
    }
}
""";

        await ProductionGeneratorTest.RunAndAssert(LanguageVersion.CSharp9,
            source.ReplaceLineEndings("\r\n"),
            MultilineSurfaces.Append(("Morphant.Generated.TypeMapper.Mapper__f6afa7d38a3eeb111905cdec012f335d.g.cs", expectedMapper)).ToArray());
    }
}
