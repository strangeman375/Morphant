using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TransferredWarningUsageTests;

[TestFixture]
internal sealed partial class WarningTests
{
    [Test]
    public async Task Keeps_custom_obsolete_diagnostic_suppression_local()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
namespace TestCase
{
    public sealed class Source
    {
        public int Value => 10;
        [Obsolete("Legacy property.", DiagnosticId = "MIGRATE001")]
        public int Legacy => 20;
    }
    public sealed class Destination
    {
        [Obsolete("Legacy constructor.", DiagnosticId = "MIGRATE001")]
        public Destination(int value) => Value = value;
        public int Value { get; }
        public int Observed { get; set; }
    }
    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>().Members(source => new() {
#pragma warning disable MIGRATE001
                Observed = source.Legacy
#pragma warning restore MIGRATE001
            });
    }
}
""";
        // lang=c#
        const string expectedMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source);
            }

            return __Update(source, destination);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source)
        {
            return {|MIGRATE001:new global::TestCase.Destination(
                value: source.Value)
            {
                #pragma warning disable MIGRATE001
                Observed = source.Legacy
                #pragma warning restore MIGRATE001
            }|};
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination)
        {
            #pragma warning disable MIGRATE001
            destination.Observed = source.Legacy;
            #pragma warning restore MIGRATE001

            return destination;
        }
    }
}
""";

        await ProductionGeneratorTest.RunAndAssert(LanguageVersion.CSharp9, source,
            CustomSurfaces.Append(("Morphant.Generated.TypeMapper.TestMapper__3257fb115d47a54e47a0d30bb8ee81d3.g.cs", expectedMapper)).ToArray());
    }
}
