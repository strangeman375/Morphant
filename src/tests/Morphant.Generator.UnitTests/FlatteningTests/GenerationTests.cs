using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.FlatteningTests;

[TestFixture]
internal sealed class GenerationTests
{
    [Test]
    public async Task Maps_multilevel_nullable_paths_into_constructor_and_members()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
        public Customer? Customer { get; init; }
    }

    public sealed class Customer
    {
        public Address? Address { get; init; }
    }

    public sealed class Address
    {
        public string? City { get; init; }

        public int Count { get; init; }
    }

    public sealed class Destination
    {
        public Destination(string? customerAddressCity)
        {
            CustomerAddressCity = customerAddressCity;
        }

        public string? CustomerAddressCity { get; }

        public int? CustomerAddressCount { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination(
                customerAddressCity: (source.Customer is { } __morphantIncluded0_c_0_0 && __morphantIncluded0_c_0_0.Address is { } __morphantIncluded0_c_0_1 ? __morphantIncluded0_c_0_1.City : default(string?)))
            {
                CustomerAddressCount = (source.Customer is { } __morphantIncluded0_m_0_0 && __morphantIncluded0_m_0_0.Address is { } __morphantIncluded0_m_0_1 ? __morphantIncluded0_m_0_1.Count : default(int?))
            };
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.CustomerAddressCount = (source.Customer is { } __morphantIncluded0_m_0_0 && __morphantIncluded0_m_0_0.Address is { } __morphantIncluded0_m_0_1 ? __morphantIncluded0_m_0_1.Count : default(int?));

            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }
}
