using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.FlatteningTests;

[TestFixture]
internal sealed class GenerationTests
{
    [Test]
    public async Task Maps_multilevel_nullable_paths_into_constructor_and_members()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
        public Customer? Customer { get; init; }
    }

    public sealed class Customer
    {
        public Address? Address { get; init; }
    }

    public sealed class Address
    {
        public string? City { get; init; }

        public int Count { get; init; }
    }

    public sealed class Destination
    {
        public Destination(string? customerAddressCity)
        {
            CustomerAddressCity = customerAddressCity;
        }

        public string? CustomerAddressCity { get; }

        public int? CustomerAddressCount { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination(
                customerAddressCity: source.Customer?.Address?.City)
            {
                CustomerAddressCount = source.Customer?.Address?.Count
            };
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.CustomerAddressCount = source.Customer?.Address?.Count;

            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }

    [Test]
    public async Task Honors_output_nullability_on_intermediate_members()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;
using System.Diagnostics.CodeAnalysis;

namespace TestCase
{
    public sealed class Source
    {
        [MaybeNull]
        public Customer MaybeCustomer { get; init; }

        [NotNull]
        public Customer? CertainCustomer { get; init; } = new();

        [MaybeNull]
        public Customer MaybeCustomerField = null!;

        [NotNull]
        public Customer? CertainCustomerField = new();

        [NotNull]
        public Metrics? CertainMetrics { get; init; } = new();
    }

    public sealed class Customer
    {
        public string Name { get; init; } = string.Empty;
    }

    public struct Metrics
    {
        public int Count { get; init; }
    }

    public sealed class Destination
    {
        public string? MaybeCustomerName { get; set; }

        public string CertainCustomerName { get; set; } = string.Empty;

        public string? MaybeCustomerFieldName { get; set; }

        public string CertainCustomerFieldName { get; set; } = string.Empty;

        public int CertainMetricsCount { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination()
            {
                MaybeCustomerName = source.MaybeCustomer?.Name,
                CertainCustomerName = source.CertainCustomer.Name,
                MaybeCustomerFieldName = source.MaybeCustomerField?.Name,
                CertainCustomerFieldName = source.CertainCustomerField.Name,
                CertainMetricsCount = source.CertainMetrics.Value.Count
            };
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.MaybeCustomerName = source.MaybeCustomer?.Name;
            destination.CertainCustomerName = source.CertainCustomer.Name;
            destination.MaybeCustomerFieldName = source.MaybeCustomerField?.Name;
            destination.CertainCustomerFieldName = source.CertainCustomerField.Name;
            destination.CertainMetricsCount = source.CertainMetrics.Value.Count;

            return destination;
        }
    }
}
""";

        await ConventionTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }
}
