namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.Tuples;

internal sealed partial class TuplesTests
{
    [Test]
    [Description("A member configuration alias still refers to the same tuple element as the constructor argument.")]
    public void TupleElementWhoseNameConflictsWithMemberPlanType()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed class Source
    {
        public int Id => 7;
        public string Name => "from convention";
        public int Item1 => 7;
        public string Item2 => "from convention";
        public string FromConstruct() => "from constructor";
        public string FromMembers() => "from members";
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, (int Id, string TupleMembers)>()
                .MemberSelection(MemberSelection.Explicit)
                .Construct(source => new(source.Id, source.FromConstruct()))
                .Members(source => new() { TupleMembers_ = source.FromMembers() });
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.TestCase_Mapper.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string TupleMembers)>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof((int Id, string TupleMembers))) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        (int Id, string TupleMembers) global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string TupleMembers)>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        (int Id, string TupleMembers) global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string TupleMembers)>.Update(
            global::TestCase.Source? source,
            (int Id, string TupleMembers) destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Update(source, destination, context);
        }

        private (int Id, string TupleMembers) __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            int id = source.Id;
            string tupleMembers = source.FromConstruct();
            tupleMembers = source.FromMembers();

            return (Id: id, TupleMembers: tupleMembers);
        }

        private (int Id, string TupleMembers) __Update(
            global::TestCase.Source source,
            (int Id, string TupleMembers) destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.TupleMembers = source.FromMembers();

            return destination;
        }
    }
}
""")
            ],
            expectedSurfaces: TupleElementWhoseNameConflictsWithMemberPlanTypeSurfaces);
    }
}
