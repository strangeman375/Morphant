namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.Tuples;

internal sealed partial class TuplesTests
{
    [Test]
    [Description("Different source and destination element names cannot be matched merely by position.")]
    public void NamedTupleWithoutPositionalConventionFallback()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed class Source { public int Id => 7; public string Name => "source"; }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, (int Code, string Text)>()
                .MemberSelection(MemberSelection.Explicit)
                .Construct(_ => new(ByConvention()));
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.TestCase_Mapper.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, (int Code, string Text)>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof((int Code, string Text))) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        (int Code, string Text) global::Morphant.ITypeMapper<global::TestCase.Source, (int Code, string Text)>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, global::Morphant.Context.MappingOperation.Create, context);
        }

        /// <inheritdoc/>
        (int Code, string Text) global::Morphant.ITypeMapper<global::TestCase.Source, (int Code, string Text)>.Update(
            global::TestCase.Source? source,
            (int Code, string Text) destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Update(source, destination, context);
        }

        private (int Code, string Text) __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingOperation operation,
            global::Morphant.Context.MappingContext context)
        {
            throw new global::Morphant.Exceptions.MappingConfigurationException(
                operation,
                typeof(global::TestCase.Source),
                typeof((int Code, string Text)),
                "This Construct or Resolve expression is not supported.");
        }

        private (int Code, string Text) __Update(
            global::TestCase.Source source,
            (int Code, string Text) destination,
            global::Morphant.Context.MappingContext context)
        {
            return destination;
        }
    }
}
""")
            ],
            expectedSurfaces: NamedTupleWithoutPositionalConventionFallbackSurfaces);
    }
}
