namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.Tuples;

internal sealed partial class TuplesTests
{
    [Test]
    [Description("The member rules depend on each other, with no source convention to seed either element.")]
    public void CrossElementDependenciesWithoutInitialValues()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed class Source { }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, (int Id, string Name)>()
                .MemberSelection(MemberSelection.Explicit)
                .Construct(_ => new(Auto(), Auto()))
                .Members((source, previous, result) => new() { Id = result.Name.Length, Name = result.Id.ToString() });
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.TestCase_Mapper.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string Name)>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof((int Id, string Name))) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        (int Id, string Name) global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string Name)>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, global::Morphant.Context.MappingOperation.Create, context);
        }

        /// <inheritdoc/>
        (int Id, string Name) global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string Name)>.Update(
            global::TestCase.Source? source,
            (int Id, string Name) destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Update(source, destination, context);
        }

        private (int Id, string Name) __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingOperation operation,
            global::Morphant.Context.MappingContext context)
        {
            throw new global::Morphant.Exceptions.MappingConfigurationException(
                operation,
                typeof(global::TestCase.Source),
                typeof((int Id, string Name)),
                "This Construct or Resolve expression is not supported.");
        }

        private (int Id, string Name) __Update(
            global::TestCase.Source source,
            (int Id, string Name) destination,
            global::Morphant.Context.MappingContext context)
        {
            int id = destination.Name.Length;
            string name = destination.Id.ToString();

            destination.Id = id;
            destination.Name = name;

            return destination;
        }
    }
}
""")
            ],
            expectedSurfaces: ValueTupleWithDifferentExpressionsForOneElementSurfaces,
            expectedDiagnostics: """
MORPH0037 Error: Rule for constructor parameter 'Id' is invalid in mapping 'TestCase.Source -> System.ValueTuple<int, string>': Auto could not find exactly one compatible source member.
  at TestCase.cs(17,37-17,41); <no source>
MORPH0037 Error: Rule for constructor parameter 'Name' is invalid in mapping 'TestCase.Source -> System.ValueTuple<int, string>': Auto could not find exactly one compatible source member.
  at TestCase.cs(17,45-17,49); <no source>
""");
    }
}
