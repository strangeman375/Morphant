internal sealed partial class TuplesTests
{
    [Test]
    [Description("A member rule overrides the eighth element, beyond the first physical tuple segment.")]
    public void LongValueTupleOverridesAnElementInsideRest()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
using Morphant.Context;

namespace TestCase
{
