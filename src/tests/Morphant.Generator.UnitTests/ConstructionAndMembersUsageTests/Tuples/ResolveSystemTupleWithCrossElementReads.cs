internal sealed partial class TuplesTests
{
    [Test]
    [Description("Resolve preserves initial System.Tuple element reads when member rules construct the final tuple.")]
    public void ResolveSystemTupleWithCrossElementReads()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed class Source
    {
        public bool Reuse { get; set; }
        public int Id => 7;
        public string Name => "from convention";
        public int Item1 => 7;
        public string Item2 => "from convention";
        public string FromConstruct() => "from constructor";
        public string FromMembers() => "from members";
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Tuple<int, string>>()
                .MemberSelection(MemberSelection.Explicit)
                .Resolve((source, previous) =>
                {
                    if (previous.TryGetValue(out var current) && source.Reuse)
                        return current;
                    return new(source.Id, source.FromConstruct());
                })
                .Members((source, previous, result) => new()
                {
                    Item1 = result.Item2.Length,
                    Item2 = result.Item1.ToString()
                });
    }
}
""";

        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.Mapper__b93622f58bb33946b8901b3146112f51.g.cs",
            // lang=c#
"""
