namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.Factories;

internal sealed partial class FactoriesTests
{
    [Test]
    [Description("ResolveUsing applies writable tuple member rules to either a reused or a factory-created tuple.")]
    public void ResolveUsingValueTupleFactoryThenMemberAssignment()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using System;
using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed class Source
    {
        public bool Reuse { get; set; }
        public int Id => 7;
        public string Name => "from convention";
        public int Item1 => 7;
        public string Item2 => "from convention";
        public string FromConstruct() => "from constructor";
        public string FromMembers() => "from members";
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, (int Id, string Name)>()
                .MemberSelection(MemberSelection.Explicit)
                .ResolveUsing((source, previous) => previous.HasValue && source.Reuse
                    ? previous.Value
                    : (source.Id, source.FromConstruct()))
                .Members(source => new() { Name = source.FromMembers() });
    }
}
""";

        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.Mapper__b93622f58bb33946b8901b3146112f51.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string Name)>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof((int Id, string Name))) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        (int Id, string Name) global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string Name)>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        (int Id, string Name) global::Morphant.ITypeMapper<global::TestCase.Source, (int Id, string Name)>.Update(
            global::TestCase.Source? source,
            (int Id, string Name) destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Update(source, destination, context);
        }

        private (int Id, string Name) __Create(
            global::TestCase.Source source)
        {
            (int Id, string Name) result = __ResolveUsing(source, global::Morphant.Option<(int Id, string Name)>.None);

            result.Name = source.FromMembers();

            return result;
        }

        private (int Id, string Name) __Update(
            global::TestCase.Source source,
            (int Id, string Name) destination)
        {
            (int Id, string Name) result = __ResolveUsing(source, global::Morphant.Option<(int Id, string Name)>.Some(destination));

            result.Name = source.FromMembers();

            return result;
        }

        private (int Id, string Name) __ResolveUsing(global::TestCase.Source source, global::Morphant.Option<(int Id, string Name)> previous) => previous.HasValue && source.Reuse
            ? previous.Value
            : (source.Id, source.FromConstruct());
    }
}
""")
            ],
            expectedSurfaces: ValueTupleFactoryThenMemberAssignmentSurfaces);
    }
}
