        public string FromMembers() => "from members";
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Tuple<int, string>>()
                .MemberSelection(MemberSelection.Explicit)
                .ResolveUsing((source, previous) => previous.HasValue && source.Reuse
                    ? previous.Value
                    : new Tuple<int, string>(source.Id, source.FromConstruct()))
                .Members(source => new() { Item2 = source.FromMembers() });
    }
}
""";

