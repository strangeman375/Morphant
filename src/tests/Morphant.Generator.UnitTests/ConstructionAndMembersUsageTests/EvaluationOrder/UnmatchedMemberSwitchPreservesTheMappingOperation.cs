namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.EvaluationOrder;

internal sealed partial class EvaluationOrderTests
{
    [Test]
    [Description("A non-exhaustive member switch runs after construction and reports the original Create or Update operation.")]
    public void UnmatchedMemberSwitchPreservesTheMappingOperation()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using Morphant;

namespace TestCase
{
    public sealed class Source { public int Value { get; set; } }
    public sealed class Destination
    {
        public Destination(int value) => Value = value;
        public int Value { get; set; }
    }
    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>()
                .Construct(source => new(source.Value))
                .Members(source => source.Value switch
                {
                    0 => new() { Value = 10 },
                    > 0 => new() { Value = source.Value + 10 }
                });
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.TestCase_Mapper.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            var result = new global::TestCase.Destination(
                value: source.Value);

            var switchValue = source.Value;

            switch (switchValue)
            {
                case 0:
                {
                    result.Value = 10;

                    return result;
                }
                case > 0:
                {
                    result.Value = source.Value + 10;

                    return result;
                }
            }

            throw new global::Morphant.Exceptions.UnmatchedMappingSwitchException(global::Morphant.Context.MappingOperation.Create, typeof(global::TestCase.Source), typeof(global::TestCase.Destination));
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            var switchValue = source.Value;

            switch (switchValue)
            {
                case 0:
                {
                    destination.Value = 10;

                    return destination;
                }
                case > 0:
                {
                    destination.Value = source.Value + 10;

                    return destination;
                }
            }

            throw new global::Morphant.Exceptions.UnmatchedMappingSwitchException(global::Morphant.Context.MappingOperation.Update, typeof(global::TestCase.Source), typeof(global::TestCase.Destination));
        }
    }
}
""")
            ],
            expectedSurfaces: UnmatchedMemberSwitchPreservesTheMappingOperationSurfaces,
            expectedDiagnostics: """
CS8509 Warning: The switch expression does not handle all possible values of its input type (it is not exhaustive). For example, the pattern '-1' is not covered.
  at TestCase.cs(19,49-19,55)
""");
    }
}
