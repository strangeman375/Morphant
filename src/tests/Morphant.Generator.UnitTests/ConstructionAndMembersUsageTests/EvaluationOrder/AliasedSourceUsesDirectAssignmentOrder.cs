namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.EvaluationOrder;

internal sealed partial class EvaluationOrderTests
{
    [Test]
    [Description("Update(value, value) reads source again after assigning Value; starting at 5 produces Value = 15 and Copy = 25.")]
    public void AliasedSourceUsesDirectAssignmentOrder()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using Morphant;

namespace TestCase
{
    public sealed class Mutable
    {
        public Mutable(int value) => Value = value;
        public int Value { get; set; }
        public int Copy { get; set; }
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Mutable, Mutable>()
                .Construct(source => new(Observe(source.Value)))
                .Members(source => new()
                {
                    Value = Observe(source.Value),
                    Copy = Observe(source.Value)
                });

        private static int Observe(int value) => value + 10;
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.TestCase_Mapper.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Mutable, global::TestCase.Mutable>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Mutable) &&
                    destinationType == typeof(global::TestCase.Mutable)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Mutable global::Morphant.ITypeMapper<global::TestCase.Mutable, global::TestCase.Mutable>.Create(
            global::TestCase.Mutable? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Mutable global::Morphant.ITypeMapper<global::TestCase.Mutable, global::TestCase.Mutable>.Update(
            global::TestCase.Mutable? source,
            global::TestCase.Mutable? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Mutable __Create(
            global::TestCase.Mutable source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Mutable(
                value: global::TestCase.Mapper.Observe(source.Value))
            {
                Value = global::TestCase.Mapper.Observe(source.Value),
                Copy = global::TestCase.Mapper.Observe(source.Value)
            };
        }

        private global::TestCase.Mutable __Update(
            global::TestCase.Mutable source,
            global::TestCase.Mutable destination,
            global::Morphant.Context.MappingContext context)
        {
            destination.Value = global::TestCase.Mapper.Observe(source.Value);
            destination.Copy = global::TestCase.Mapper.Observe(source.Value);

            return destination;
        }
    }
}
""")
            ],
            expectedSurfaces: AliasedSourceUsesDirectAssignmentOrderSurfaces);
    }
}
