namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.EvaluationOrder;

internal sealed partial class EvaluationOrderTests
{
    [Test]
    [Description("Resolve preserves written argument order before independent member evaluations on replacement.")]
    public void ResolveNamedArgumentsAndIndependentMemberEvaluationOrder()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using Morphant;
using Morphant.Context;
using System.Diagnostics.CodeAnalysis;

namespace TestCase
{
    public sealed class Source
    {
        public bool Reuse { get; set; }
        private int _reads;
        public string Read(string site) => site + ++_reads;
    }

    public sealed class Destination
    {
        public Destination(string first, string second) { First = first; Second = second; }
        public string First { get; }
        public string Second { get; }
        public string Label { get; set; } = "";
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>()
                .Resolve((source, previous) =>
                {
                    if (previous.TryGetValue(out var current) && source.Reuse)
                        return current;
                    return new(second: source.Read("second"), first: source.Read("first"));
                })
                .Members(source => new() { Label = source.Read("member") });
    }
}
""";

        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.Mapper__b93622f58bb33946b8901b3146112f51.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

