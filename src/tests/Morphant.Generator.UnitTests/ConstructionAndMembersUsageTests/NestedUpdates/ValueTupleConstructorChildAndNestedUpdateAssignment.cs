        public bool Reuse => true;
        public ChildSource Child { get; } = new();
    }

    public sealed class ChildDestination
    {
        public string Name { get; set; } = "constructor child";
    }



    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<ChildSource, ChildDestination>()
                .Members((source, previous, result, context) => new()
                {
                    Name = context.Operation + ":" + source.Name
                });

            builder.Map<Source, (ChildDestination Child, int Id)>()
                .MemberSelection(MemberSelection.Explicit)
                .Construct(_ => new(new ChildDestination(), 7))
                .Members((source, previous, result) => new() { Child = Update<ChildDestination>(source.Child, result.Child) });
        }
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
