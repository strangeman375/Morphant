            return destination;
        }
    }
}
""")
            ],
            expectedSurfaces: AllowNullConstructorAndRequiredMemberSurfaces,
            languageVersion: Microsoft.CodeAnalysis.CSharp.LanguageVersion.CSharp11);
    }
}
