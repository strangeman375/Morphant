namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.Lifecycle;

internal sealed partial class LifecycleTests
{
    [Test]
    [Description("A known operation must not bypass user-defined logical operators and conversions.")]
    public void MemberOperationGuardPreservesUserDefinedOperators()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using Morphant;
using Morphant.Context;
using System.Diagnostics.CodeAnalysis;

namespace TestCase
{
    public readonly struct Truth
    {
        public static implicit operator Truth(bool value) => default;
        public static Truth operator &(Truth left, Truth right) => default;
        public static bool operator true(Truth value) => true;
        public static bool operator false(Truth value) => false;
    }

    public sealed class Source
    {
        public string Name => "from convention";
        public Truth ShouldMap() => default;
        public string FromConstruct() => "from constructor";
        public string FromMembers() => "from members";
    }

    public sealed class Destination
    {
        public Destination(string name) => Name = name;
        public string Name { get; set; }
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>()
                .Construct(source => new(source.FromConstruct()))
                .Members((source, previous, result, context) =>
                {
                    if (context.Operation != MappingOperation.Update && source.ShouldMap())
                        return new() { Name = source.FromMembers() };
                    return new() { Name = Ignore() };
                });
    }
}
""";

        // Complete mapper output; the companion surface snapshots cover the generated DSL.
        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.Mapper__b93622f58bb33946b8901b3146112f51.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            var result = new global::TestCase.Destination(
                name: source.FromConstruct());

            if (context.Operation != global::Morphant.Context.MappingOperation.Update && source.ShouldMap())
            {
                result.Name = source.FromMembers();

                return result;
            }

            return result;
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            if (false && source.ShouldMap())
            {
                destination.Name = source.FromMembers();

                return destination;
            }

            return destination;
        }
    }
}
""")
            ],
            expectedSurfaces: ResolveReusesOrConstructsWithSetMemberSurfaces);
    }
}
