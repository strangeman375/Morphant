namespace Morphant.Generator.UnitTests.ConstructionAndMembersUsageTests.Lifecycle;

internal sealed partial class LifecycleTests
{
    [Test]
    [Description("Resolve preserves the original previous destination, selected result and operation across reuse and replacement.")]
    public void ResolveOperationContextWithPreviousAndResult()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591
using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed class Source
    {
        public bool Reuse { get; set; }
        public int Id { get; set; }
        public string Label { get; set; } = "source";
    }

    public sealed class Destination
    {
        public Destination(int id, string label) { Id = id; Label = label; }
        public int Id { get; }
        public string Label { get; }
        public string Trace { get; set; } = "initial";
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper<Mapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>()
                .MemberSelection(MemberSelection.Explicit)
                .Resolve((source, previous, context) =>
                {
                    if (previous.TryGetValue(out var current) && source.Reuse)
                        return current;
                    return new(
                        source.Id,
                        context.Operation == MappingOperation.Create
                            ? source.Label
                            : "update:" + source.Label);
                })
                .Members((source, previous, result, context) => new()
                {
                    Trace = (previous.HasValue ? previous.Value.Label : "none")
                        + "|" + result.Label
                        + "|" + context.Operation
                });
    }
}
""";

        ConstructionAndMembersSnapshot.Verify(
            source,
            expectedMappers:
            [
            ("Morphant.Generated.TypeMapper.Mapper__b93622f58bb33946b8901b3146112f51.g.cs",
            // lang=c#
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return __Create(source, context);
            }

            return __Update(source, destination, context);
        }

        private global::TestCase.Destination __Create(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            _ = global::Morphant.Option<global::TestCase.Destination>.None.TryGetValue(out global::TestCase.Destination? current) && source.Reuse;

            var result = new global::TestCase.Destination(
                id: source.Id,
                label: context.Operation == global::Morphant.Context.MappingOperation.Create
                    ? source.Label
                    : "update:" + source.Label);

            result.Trace = ("none")
                + "|" + result.Label
                + "|" + context.Operation;

            return result;
        }

        private global::TestCase.Destination __Update(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.Context.MappingContext context)
        {
            if (global::Morphant.Option<global::TestCase.Destination>.Some(destination).TryGetValue(out global::TestCase.Destination? current) && source.Reuse)
            {
                destination.Trace = (destination.Label)
                    + "|" + destination.Label
                    + "|" + context.Operation;

                return destination;
            }

            var result = new global::TestCase.Destination(
                id: source.Id,
                label: context.Operation == global::Morphant.Context.MappingOperation.Create
                    ? source.Label
                    : "update:" + source.Label);

            result.Trace = (destination.Label)
                + "|" + result.Label
                + "|" + context.Operation;

            return result;
        }
    }
}
""")
            ],
            expectedSurfaces: ConstructOperationContextWithPreviousAndResultSurfaces);
    }
}
