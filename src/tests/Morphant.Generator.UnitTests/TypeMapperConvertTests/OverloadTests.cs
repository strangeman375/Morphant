using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperConvertTests;

[TestFixture]
internal sealed class OverloadTests
{
    [Test]
    public async Task Emits_source_only_and_previous_aware_callbacks_independently()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed record Source(int Value, string Text);

    [MorphantMapper]
    public partial class SourceOnlyMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>()
                .Convert(source => source?.Value);
    }

    [MorphantMapper]
    public partial class PreviousMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>()
                .Convert((source, previous) =>
                    previous.HasValue
                        ? previous.Value + (source?.Value ?? 0)
                        : source?.Value);
    }

    [MorphantMapper]
    public partial class CreateOnlyMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>(MappingMode.Create)
                .Convert(source => source?.Value);
    }

    [MorphantMapper]
    public partial class UpdateOnlyMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>(MappingMode.Update)
                .Convert((source, previous) =>
                    previous.HasValue
                        ? previous.Value
                        : source?.Value);
    }
}
""";

        // lang=c#
        const string intExtension =
            ExpectedGeneratedSources.SourceToNullableIntMappingExtension;

        // lang=c#
        const string sourceOnlyMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class SourceOnlyMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int?>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(int?)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(source);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Update(
            global::TestCase.Source? source,
            int? destination,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(source);

        private int? __ConvertDestination(global::TestCase.Source? source) => source?.Value;
    }
}
""";

        // lang=c#
        const string previousMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class PreviousMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int?>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(int?)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(
                source,
                global::Morphant.Option<int>.None);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Update(
            global::TestCase.Source? source,
            int? destination,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(
                source,
                destination is null
                    ? global::Morphant.Option<int>.None
                    : global::Morphant.Option<int>.Some(destination.Value));

        private int? __ConvertDestination(global::TestCase.Source? source, global::Morphant.Option<int> previous) => previous.HasValue ? previous.Value + (source?.Value ?? 0) : source?.Value;
    }
}
""";

        // lang=c#
        const string createOnlyMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class CreateOnlyMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int?>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(int?)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(source);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Update(
            global::TestCase.Source? source,
            int? destination,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingOperationNotSupportedException(
                global::Morphant.Context.MappingOperation.Update,
                typeof(global::TestCase.Source),
                typeof(int?),
                global::Morphant.MappingMode.Create);

        private int? __ConvertDestination(global::TestCase.Source? source) => source?.Value;
    }
}
""";

        // lang=c#
        const string updateOnlyMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class UpdateOnlyMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int?>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(int?)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingOperationNotSupportedException(
                global::Morphant.Context.MappingOperation.Create,
                typeof(global::TestCase.Source),
                typeof(int?),
                global::Morphant.MappingMode.Update);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Update(
            global::TestCase.Source? source,
            int? destination,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(
                source,
                destination is null
                    ? global::Morphant.Option<int>.None
                    : global::Morphant.Option<int>.Some(destination.Value));

        private int? __ConvertDestination(global::TestCase.Source? source, global::Morphant.Option<int> previous) => previous.HasValue ? previous.Value : source?.Value;
    }
}
""";

        await ProductionGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.MappingExtension.TestCase_Source__System_Nullable_System_Int32_.g.cs",
                intExtension
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_SourceOnlyMapper.g.cs",
                sourceOnlyMapper
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_PreviousMapper.g.cs",
                previousMapper
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_CreateOnlyMapper.g.cs",
                createOnlyMapper
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_UpdateOnlyMapper.g.cs",
                updateOnlyMapper
            ));
    }
}
