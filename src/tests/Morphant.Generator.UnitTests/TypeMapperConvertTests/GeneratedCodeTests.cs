using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperConvertTests;

[TestFixture]
internal sealed class GeneratedCodeTests
{
    [Test]
    public async Task Emits_one_opaque_helper_and_direct_manual_dispatch()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;
using Morphant.Context;

namespace TestCase
{
    public sealed record Source(int Value);

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>()
                .Convert((source, previous, context) =>
                {
                    if (source is null)
                    {
                        return null;
                    }

                    if (context.Operation == MappingOperation.Update &&
                        previous.TryGetValue(out var value))
                    {
                        return value + source.Value;
                    }

                    return source.Value;
                });

        private static int? ConvertDestination() => null;
    }
}
""";

        // lang=c#
        const string expectedMappingExtension =
"""
// <auto-generated />
#nullable enable

namespace Morphant
{
    internal static partial class MorphantGeneratedMappingExtensions
    {
        /// <summary>
        /// Configures how to construct a destination when no existing destination is used.
        /// </summary>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="construct">A lambda expression that receives the non-null source and describes destination construction.</param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<global::TestCase.Source, int?> Construct(
            this global::Morphant.MapperBuilder<global::TestCase.Source, int?> builder,
            global::Morphant.Delegates.Construct<global::TestCase.Source, int?> construct)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Configures how to select or construct the destination from the source and an optional existing destination.
        /// </summary>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="construct">A lambda expression that receives the non-null source and the optional existing destination and describes destination construction.</param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<global::TestCase.Source, int?> Construct(
            this global::Morphant.MapperBuilder<global::TestCase.Source, int?> builder,
            global::Morphant.Delegates.Construct<global::TestCase.Source, int, int?> construct)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Configures a fully manual mapping algorithm.
        /// </summary>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="mapping">A lambda expression that receives the original source, the optional existing destination, and the current mapping context.</param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<global::TestCase.Source, int?> Convert(
            this global::Morphant.MapperBuilder<global::TestCase.Source, int?> builder,
            global::Morphant.Delegates.Convert<global::TestCase.Source?, int, int?> mapping)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        // lang=c#
        const string expectedTypeMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int?>
    {
        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => ConvertDestination1(
                source,
                global::Morphant.Option<int>.None,
                context);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Update(
            global::TestCase.Source? source,
            int? destination,
            global::Morphant.Context.MappingContext context)
            => ConvertDestination1(
                source,
                destination is null
                    ? global::Morphant.Option<int>.None
                    : global::Morphant.Option<int>.Some(destination.Value),
                context);

        private int? ConvertDestination1(global::TestCase.Source? source, global::Morphant.Option<int> previous, global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return null;
            }

            if (context.Operation == global::Morphant.Context.MappingOperation.Update && previous.TryGetValue(out int value))
            {
                return value + source.Value;
            }

            return source.Value;
        }
    }
}
""";

        await BasicMembersTypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.MappingExtension.TestCase_Source__System_Nullable_System_Int32_.g.cs",
                expectedMappingExtension
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs",
                expectedTypeMapper
            ));
    }
}
