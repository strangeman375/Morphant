    [Test]
    public async Task Pair_Auto_and_Explicit_override_the_mapper_selection()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
        public int Value { get; init; }
    }

    public sealed class AutoDestination
    {
        public int Value { get; set; }
    }

    public sealed class ExplicitDestination
    {
        public int Value { get; set; } = 41;
    }

    [MorphantMapper]
    public partial class AutoMapper : TypeMapper<AutoMapper>
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MemberSelection(MemberSelection.Explicit);
            builder.Map<Source, AutoDestination>()
                .MemberSelection(MemberSelection.Auto);
        }
    }

    [MorphantMapper]
    public partial class ExplicitMapper : TypeMapper<ExplicitMapper>
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MemberSelection(MemberSelection.Auto);
            builder.Map<Source, ExplicitDestination>()
                .MemberSelection(MemberSelection.Explicit);
        }
    }
}
""";

        // lang=c#
        const string autoExpected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class AutoMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.AutoDestination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.AutoDestination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.AutoDestination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.AutoDestination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return __Create(source, context);
