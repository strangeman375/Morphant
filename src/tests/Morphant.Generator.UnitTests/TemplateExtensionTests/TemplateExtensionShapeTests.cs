using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TemplateExtensionTests;

[TestFixture]
internal sealed class TemplateExtensionShapeTests
{
    [Test]
    public async Task Generates_canonical_generated_template_extension_shape()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591
#nullable enable

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();
        }
    }
}

namespace TestCase.Morphant.Generated
{
    internal sealed record DestinationMorphantTemplate;
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace Morphant
{
    internal static partial class MorphantGeneratedTemplateExtensions
    {
        /// <summary>
        /// Configures a mapping template.
        /// </summary>
        /// <typeparam name="TSource">The source type.</typeparam>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="template">
        /// A lambda expression that receives the non-null source value and describes the mapping.
        /// </param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<TSource, global::TestCase.Destination> Template<TSource>(
            this global::Morphant.MapperBuilder<TSource, global::TestCase.Destination> builder,
            global::System.Func<TSource, global::TestCase.Morphant.Generated.DestinationMorphantTemplate> template)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Configures a mapping template for an existing destination.
        /// </summary>
        /// <typeparam name="TSource">The source type.</typeparam>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="template">
        /// A lambda expression that receives the non-null source value and the non-null
        /// existing destination and describes the mapping.
        /// </param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<TSource, global::TestCase.Destination> Template<TSource>(
            this global::Morphant.MapperBuilder<TSource, global::TestCase.Destination> builder,
            global::System.Func<TSource, global::TestCase.Destination, global::TestCase.Morphant.Generated.DestinationMorphantTemplate> template)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        await TemplateExtensionGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.TemplateExtension.TestCase_Destination.g.cs",
                expected
            ));
    }

    [Test]
    public async Task Generates_canonical_direct_template_extension_shape()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, int>();
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace Morphant
{
    internal static partial class MorphantGeneratedTemplateExtensions
    {
        /// <summary>
        /// Configures a mapping template.
        /// </summary>
        /// <typeparam name="TSource">The source type.</typeparam>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="template">
        /// A lambda expression that receives the non-null source value and describes the mapping.
        /// </param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<TSource, int> Template<TSource>(
            this global::Morphant.MapperBuilder<TSource, int> builder,
            global::System.Func<TSource, int> template)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Configures a mapping template for an existing destination.
        /// </summary>
        /// <typeparam name="TSource">The source type.</typeparam>
        /// <param name="builder">The mapping builder to configure.</param>
        /// <param name="template">
        /// A lambda expression that receives the non-null source value and the non-null
        /// existing destination and describes the mapping.
        /// </param>
        /// <returns>The <paramref name="builder"/> instance.</returns>
        public static global::Morphant.MapperBuilder<TSource, int> Template<TSource>(
            this global::Morphant.MapperBuilder<TSource, int> builder,
            global::System.Func<TSource, int, int> template)
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        await TemplateExtensionGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.TemplateExtension.System_Int32.g.cs",
                expected
            ));
    }
}
