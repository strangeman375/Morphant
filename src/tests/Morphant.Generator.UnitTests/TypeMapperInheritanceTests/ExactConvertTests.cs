using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperInheritanceTests;

[TestFixture]
internal sealed class ExactConvertTests
{
    [Test]
    public async Task Inherits_the_complete_manual_Convert_plan_for_an_exact_pair()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed record Source(int Value);

    public abstract class BaseMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>()
                .Convert((source, previous) =>
                    previous.HasValue
                        ? previous.Value + (source?.Value ?? 0)
                        : source?.Value);
    }

    [MorphantMapper]
    public partial class DerivedMapper : BaseMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            base.Configure(builder);
            builder.Map<Source, int?>()
                .IncludeBase<Source, int?>();
        }
    }
}
""";

        // lang=c#
        const string mapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class DerivedMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int?>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(int?)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(
                source,
                global::Morphant.Option<int>.None);

        /// <inheritdoc/>
        int? global::Morphant.ITypeMapper<global::TestCase.Source, int?>.Update(
            global::TestCase.Source? source,
            int? destination,
            global::Morphant.Context.MappingContext context)
            => __ConvertDestination(
                source,
                destination is null
                    ? global::Morphant.Option<int>.None
                    : global::Morphant.Option<int>.Some(destination.Value));

        private int? __ConvertDestination(global::TestCase.Source? source, global::Morphant.Option<int> previous) => previous.HasValue ? previous.Value + (source?.Value ?? 0) : source?.Value;
    }
}
""";

        await ProductionGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.MappingExtension.TestCase_Source__System_Nullable_System_Int32_.g.cs",
                ExpectedGeneratedSources
                    .SourceToNullableIntMappingExtension
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_DerivedMapper.g.cs",
                mapper
            ));
    }
}
