"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed record Source(int Value);

    public abstract class BaseMapper<TMapper> : TypeMapper<TMapper>
        where TMapper : BaseMapper<TMapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, int?>()
                .Convert((source, previous) =>
                    previous.HasValue
                        ? previous.Value + (source?.Value ?? 0)
                        : source?.Value);
    }

    [MorphantMapper]
    public partial class DerivedMapper : BaseMapper<DerivedMapper>
    {
        protected override void Configure(MapperBuilder builder)
        {
            base.Configure(builder);
            builder.Map<Source, int?>()
                .IncludeBase<Source, int?>();
        }
    }
}
""";

