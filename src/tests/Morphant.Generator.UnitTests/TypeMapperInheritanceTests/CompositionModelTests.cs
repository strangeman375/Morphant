using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperInheritanceTests;

[TestFixture]
internal sealed class CompositionModelTests
{
    [Test]
    public void Exposes_only_the_typed_IncludeBase_API()
    {
        var method = typeof(global::Morphant.MapperBuilder<,>)
            .GetMethods()
            .Single(candidate => candidate.Name == "IncludeBase");

        Assert.That(method.IsGenericMethodDefinition, Is.True);
        Assert.That(method.GetGenericArguments(), Has.Length.EqualTo(2));
        Assert.That(method.GetParameters(), Is.Empty);
    }

    [Test]
    public async Task Reads_the_assembly_UnmappedMemberValidation_level()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

// Assembly UnmappedMemberValidation: Destination
// Mappers: 1
// Mapper 0: TestCase.TestMapper
// Unifiable: False
// Root settings: MappingMode=Unset; NullSourceHandling=Unset; NullDestinationHandling=Unset; ConstructorSelection=Unset; MemberSelection=Unset; UnmappedMemberValidation=Unset
// Pairs: 1
// Pair 0: global::TestCase.Source -> global::TestCase.Destination
// Map: builder.Map<Source, Destination>()
// Map settings: MappingMode=Implicit(Default); NullSourceHandling=Unset; NullDestinationHandling=Unset; ConstructorSelection=Unset; MemberSelection=Unset; UnmappedMemberValidation=Unset
// Declarative: Constructs=0; Members=0
// Manual: Converts=0
// IncludeBase: 0
// Conflicts: None
""";

        await PairConfigurationGeneratorTest.RunAndAssertWithAnalyzerConfig(
            LanguageVersion.CSharp9,
            source,
            """
is_global = true

build_property.MorphantUnmappedMemberValidation = Destination
""",
            expected);
    }

    [Test]
    public async Task Keeps_the_complete_cross_pair_setting_chain()
    {
