using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests;

[TestFixture]
internal sealed class OutputCoordinationTests
{
    private const string FirstSource = "// <auto-generated />\r\n#nullable enable\r\n\r\n// First\r\n";
    private const string SecondSource = "// <auto-generated />\r\n#nullable enable\r\n\r\n// Second\r\n";
    private const string HealthySource = "// <auto-generated />\r\n#nullable enable\r\n\r\n// Healthy\r\n";

    [Test]
    public void Reports_collisions_deterministically_and_recovers_after_a_rename(
        [Values("Exact", "Case", "Slash", "Suffix")] string collision,
        [Values(false, true)] bool reverse,
        [Values(false, true)] bool initiallyHealthy,
        [Values(LanguageVersion.CSharp9, LanguageVersion.CSharp10)] LanguageVersion languageVersion)
    {
        var (firstName, secondName, normalizedName) = collision switch
        {
            "Case" => ("Shared.g.cs", "shared.g.cs", "Shared.g.cs"),
            "Slash" => ("folder\\Shared.g.cs", "folder/Shared.g.cs", "folder/Shared.g.cs"),
            "Suffix" => ("Shared.g", "Shared.g.cs", "Shared.g.cs"),
            _ => ("Shared.g.cs", "Shared.g.cs", "Shared.g.cs")
        };
        var first = new InputFile(firstName, FirstSource);
        var second = new InputFile(secondName, SecondSource);
        var healthy = new InputFile("Healthy.g.cs", HealthySource);
        var files = reverse ? new AdditionalText[] { healthy, second, first } : [first, second, healthy];
        var parseOptions = new CSharpParseOptions(languageVersion);
        var compilation = CreateCompilation(parseOptions);
        GeneratorDriver driver = CSharpGeneratorDriver.Create([new OutputGenerator().AsSourceGenerator()],
            additionalTexts: files, parseOptions: parseOptions);
        SourceText? healthyBeforeCollision = null;
        if (initiallyHealthy)
        {
            var initialFirst = new InputFile("First.g.cs", FirstSource);
            var initialSecond = new InputFile("Second.g.cs", SecondSource);
            driver = driver.ReplaceAdditionalText(first, initialFirst).ReplaceAdditionalText(second, initialSecond);
            driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var initialOutput, out var initialDiagnostics);
            var initialResult = driver.GetRunResult().Results.Single();
            Assert.That(initialDiagnostics, Is.Empty);
            AssertSources(initialResult, [("First.g.cs", FirstSource), ("Second.g.cs", SecondSource), ("Healthy.g.cs", HealthySource)]);
            AssertCompiler(initialOutput);
            healthyBeforeCollision = initialResult.GeneratedSources.Single(source => source.HintName == "Healthy.g.cs").SourceText;
            driver = driver.ReplaceAdditionalText(initialFirst, first).ReplaceAdditionalText(initialSecond, second);
        }
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var output, out var diagnostics);
        var result = driver.GetRunResult().Results.Single();
        var reportName = collision == "Slash"
            ? "Morphant.Generated.GeneratorFailure.TestOutputNames__c3e26fc020d23a1388724b9fd5a8b430.g.cs"
            : "Morphant.Generated.GeneratorFailure.TestOutputNames__d04bf151d3dc5f98fd04a5f3d4ea1fc8.g.cs";
        var message = "Generated source hint name '" + normalizedName + "' is not unique.";
        var report = collision == "Slash" ? """
// <auto-generated />
#nullable enable

/*
MORPH0057: Morphant generator 0.5.0 failed unexpectedly.
Stage: TestOutputNames

System.InvalidOperationException: Generated source hint name 'folder/Shared.g.cs' is not unique.
*/
""" : """
// <auto-generated />
#nullable enable

/*
MORPH0057: Morphant generator 0.5.0 failed unexpectedly.
Stage: TestOutputNames

System.InvalidOperationException: Generated source hint name 'Shared.g.cs' is not unique.
*/
""";
        Assert.Multiple(() =>
        {
            Assert.That(result.Exception, Is.Null);
            Assert.That(diagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(new[] { "MORPH0057" }));
            var diagnostic = diagnostics.Single();
            Assert.That(diagnostic.Location, Is.EqualTo(Location.None));
            Assert.That(diagnostic.Severity, Is.EqualTo(DiagnosticSeverity.Error));
            Assert.That(diagnostic.AdditionalLocations, Is.Empty);
            Assert.That(diagnostic.GetMessage(), Is.EqualTo(
                "Morphant generator 0.5.0 failed unexpectedly in stage 'TestOutputNames': " +
                "System.InvalidOperationException: " + message + ". Full exception details are available in generated file '" + reportName + "'."));
            Assert.That(diagnostic.Properties, Is.EqualTo(ImmutableDictionary<string, string?>.Empty
                .Add("GeneratorVersion", "0.5.0").Add("StageName", "TestOutputNames")
                .Add("ExceptionType", "System.InvalidOperationException").Add("ExceptionMessage", message)
                .Add("ExceptionDetails", "System.InvalidOperationException: " + message).Add("ReportHintName", reportName)));
            AssertSources(result, [("Healthy.g.cs", HealthySource), (reportName, Normalize(report))]);
            if (initiallyHealthy)
                Assert.That(result.GeneratedSources.Single(source => source.HintName == "Healthy.g.cs").SourceText,
                    Is.SameAs(healthyBeforeCollision));
            AssertCompiler(output);
        });

        var healthyText = result.GeneratedSources.Single(source => source.HintName == "Healthy.g.cs").SourceText;
        driver = driver.ReplaceAdditionalText(second, new InputFile("Recovered.g.cs", SecondSource));
        // Path separators are themselves invalid on older Roslyn hosts.
        // Recover that spelling as well as the collision.
        var recoveredName = normalizedName;
        if (collision == "Slash")
        {
            recoveredName = "Shared.g.cs";
            driver = driver.ReplaceAdditionalText(first, new InputFile(recoveredName, FirstSource));
        }
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out output, out diagnostics);
        result = driver.GetRunResult().Results.Single();
        Assert.Multiple(() =>
        {
            Assert.That(result.Exception, Is.Null);
            Assert.That(diagnostics, Is.Empty);
            AssertSources(result, [(recoveredName, FirstSource), ("Recovered.g.cs", SecondSource), ("Healthy.g.cs", HealthySource)]);
            Assert.That(result.GeneratedSources.Single(source => source.HintName == "Healthy.g.cs").SourceText, Is.SameAs(healthyText));
            AssertCompiler(output);
        });
    }

    [Test]
    public void Keeps_an_independent_output_cached_when_another_file_changes_or_is_removed()
    {
        var first = new InputFile("First.g.cs", FirstSource);
        var second = new InputFile("Second.g.cs", SecondSource);
        var options = new CSharpParseOptions(LanguageVersion.CSharp10);
        var compilation = CreateCompilation(options);
        GeneratorDriver driver = CSharpGeneratorDriver.Create([new OutputGenerator().AsSourceGenerator()],
            additionalTexts: [first, second], parseOptions: options);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var output, out var diagnostics);
        var result = driver.GetRunResult().Results.Single();
        Assert.That(diagnostics, Is.Empty);
        AssertSources(result, [("First.g.cs", FirstSource), ("Second.g.cs", SecondSource)]);
        AssertCompiler(output);
        var secondText = result.GeneratedSources.Single(source => source.HintName == "Second.g.cs").SourceText;

        const string editedSource = "// <auto-generated />\r\n#nullable enable\r\n\r\n// Edited first\r\n";
        var editedFirst = new InputFile("First.g.cs", editedSource);
        driver = driver.ReplaceAdditionalText(first, editedFirst);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out output, out diagnostics);
        result = driver.GetRunResult().Results.Single();
        Assert.That(diagnostics, Is.Empty);
        AssertSources(result, [("First.g.cs", editedSource), ("Second.g.cs", SecondSource)]);
        Assert.That(result.GeneratedSources.Single(source => source.HintName == "Second.g.cs").SourceText, Is.SameAs(secondText));
        AssertCompiler(output);

        driver = driver.RemoveAdditionalTexts([editedFirst]);
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out output, out diagnostics);
        result = driver.GetRunResult().Results.Single();
        Assert.That(diagnostics, Is.Empty);
        AssertSources(result, [("Second.g.cs", SecondSource)]);
        Assert.That(result.GeneratedSources.Single().SourceText, Is.SameAs(secondText));
        AssertCompiler(output);
    }

    private static void AssertSources(GeneratorRunResult result, (string Name, string Source)[] expected) =>
        Assert.That(result.GeneratedSources.Select(source => (source.HintName, source.SourceText.ToString()))
            .OrderBy(source => source.HintName, StringComparer.Ordinal),
            Is.EqualTo(expected.OrderBy(source => source.Name, StringComparer.Ordinal)));

    private static void AssertCompiler(Compilation compilation) => Assert.That(compilation.GetDiagnostics()
        .Where(diagnostic => diagnostic.Severity is DiagnosticSeverity.Warning or DiagnosticSeverity.Error), Is.Empty);
    private static string Normalize(string source) => source.Replace("\r\n", "\n").Replace("\n", "\r\n") + "\r\n";
    private static CSharpCompilation CreateCompilation(CSharpParseOptions options) => CSharpCompilation.Create("OutputCoordinationTests",
        [CSharpSyntaxTree.ParseText("#nullable enable\nclass Input { }", options, "Input.cs")],
        [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)], new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

    private sealed class InputFile(string path, string text) : AdditionalText
    {
        public override string Path => path;
        public override SourceText GetText(CancellationToken cancellationToken = default) => SourceText.From(text, Encoding.UTF8);
    }
    private sealed record OutputRequest(string Name, string Source);
    private sealed class OutputGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var requests = context.AdditionalTextsProvider.Select(static (file, token) =>
                new OutputRequest(file.Path, file.GetText(token)!.ToString()));
            GeneratorStageGuard.RegisterSourceOutput(context, requests, "TestOutputNames", static request => request.Name,
                static (output, request) => output.AddSource(request.Name, request.Source));
        }
    }
}
