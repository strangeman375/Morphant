using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests;

[TestFixture]
internal sealed class ExceptionFormattingTests
{
    [Test]
    public void Preserves_the_original_failure_when_exception_text_is_unavailable(
        [Values("Values", "Value", "Request", "Output", "Initialize")] string stage,
        [Values("Message", "Details", "Both", "Null")] string unavailable)
    {
        var (message, details, reportName) = unavailable switch
        {
            "Message" => ("[Exception message unavailable.]", "FormattingException: original details",
                "Morphant.Generated.GeneratorFailure.TestFormatting__6eb70b6df2448fc2fb541bcbaccedc32.g.cs"),
            "Details" => ("original failure",
                "Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests.ExceptionFormattingTests+FormattingException: original failure\r\n" +
                "   at OriginalStage.Run()\r\n[Full exception details unavailable.]",
                "Morphant.Generated.GeneratorFailure.TestFormatting__1b17cf4b68b10177a25a7b80d7d29764.g.cs"),
            _ => ("[Exception message unavailable.]",
                "Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests.ExceptionFormattingTests+FormattingException: [Exception message unavailable.]\r\n" +
                "[Full exception details unavailable.]",
                "Morphant.Generated.GeneratorFailure.TestFormatting__e2305bfbc135080d94a7124d69f9b337.g.cs")
        };
        if (stage == "Initialize")
            reportName = "Morphant.Generated.GeneratorFailure.TestFormatting__959b25d7de36fe112e22820a637ccffe.g.cs";

        // These reports retain all available original information, including a
        // readable original stack when only ToString fails. They remain comments.
        var report = unavailable switch
        {
            "Message" => """
// <auto-generated />
#nullable enable

/*
MORPH0057: Morphant generator 0.5.0 failed unexpectedly.
Stage: TestFormatting

FormattingException: original details
*/
""",
            "Details" => """
// <auto-generated />
#nullable enable

/*
MORPH0057: Morphant generator 0.5.0 failed unexpectedly.
Stage: TestFormatting

Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests.ExceptionFormattingTests+FormattingException: original failure
   at OriginalStage.Run()
[Full exception details unavailable.]
*/
""",
            _ => """
// <auto-generated />
#nullable enable

/*
MORPH0057: Morphant generator 0.5.0 failed unexpectedly.
Stage: TestFormatting

Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests.ExceptionFormattingTests+FormattingException: [Exception message unavailable.]
[Full exception details unavailable.]
*/
"""
        };
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new FormattingGenerator(stage, unavailable));
        driver = driver.RunGeneratorsAndUpdateCompilation(CreateCompilation(), out var output, out var diagnostics);
        var result = driver.GetRunResult().Results.Single();
        const string exceptionType =
            "Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests.ExceptionFormattingTests+FormattingException";
        Assert.Multiple(() =>
        {
            Assert.That(result.Exception, Is.Null);
            Assert.That(diagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(new[] { "MORPH0057" }));
            var diagnostic = diagnostics.Single();
            Assert.That(diagnostic.Severity, Is.EqualTo(DiagnosticSeverity.Error));
            Assert.That(diagnostic.Location, Is.EqualTo(Location.None));
            Assert.That(diagnostic.AdditionalLocations, Is.Empty);
            Assert.That(diagnostic.GetMessage(), Is.EqualTo(
                "Morphant generator 0.5.0 failed unexpectedly in stage 'TestFormatting': " +
                exceptionType + ": " + message + ". Full exception details are available in generated file '" + reportName + "'."));
            Assert.That(diagnostic.Properties, Is.EqualTo(ImmutableDictionary<string, string?>.Empty
                .Add("ExceptionType", exceptionType).Add("ExceptionMessage", message).Add("ExceptionDetails", details)
                .Add("GeneratorVersion", "0.5.0").Add("StageName", "TestFormatting").Add("ReportHintName", reportName)));
            Assert.That(result.GeneratedSources.Select(source => source.HintName).Order(StringComparer.Ordinal),
                Is.EqualTo(new[] { "Healthy.g.cs", reportName }.Order(StringComparer.Ordinal)));
            Assert.That(result.GeneratedSources.Single(source => source.HintName == "Healthy.g.cs").SourceText.ToString(),
                Is.EqualTo("// <auto-generated />\r\n#nullable enable\r\n\r\n// Healthy\r\n"));
            Assert.That(result.GeneratedSources.Single(source => source.HintName == reportName).SourceText.ToString(),
                Is.EqualTo(report.Replace("\r\n", "\n").Replace("\n", "\r\n") + "\r\n"));
            Assert.That(output.GetDiagnostics().Where(diagnostic =>
                diagnostic.Severity is DiagnosticSeverity.Warning or DiagnosticSeverity.Error), Is.Empty);
        });
    }

    [TestCase("Message")]
    [TestCase("Details")]
    [TestCase("StackTrace")]
    public void Propagates_requested_cancellation_during_exception_formatting(string unavailable)
    {
        using var cancellation = new CancellationTokenSource();
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new FormattingGenerator("Values", unavailable, cancellation));
        Assert.Throws<OperationCanceledException>(() =>
            driver.RunGeneratorsAndUpdateCompilation(CreateCompilation(), out _, out _, cancellation.Token));
    }

    private static CSharpCompilation CreateCompilation() => CSharpCompilation.Create("ExceptionFormattingTests",
        [CSharpSyntaxTree.ParseText("#nullable enable\nclass Input { }", path: "Input.cs")],
        [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

    private sealed class FormattingGenerator(string stage, string unavailable, CancellationTokenSource? cancellation = null)
        : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterSourceOutput(context.CompilationProvider, static (output, _) => output.AddSource("Healthy.g.cs",
                "// <auto-generated />\r\n#nullable enable\r\n\r\n// Healthy\r\n"));
            var values = context.CompilationProvider.SelectMany(static (_, _) => ImmutableArray.Create(0));
            switch (stage)
            {
                case "Values":
                    var transformed = GeneratorStageGuard.Select<int, int>(context, values, "TestFormatting",
                        (_, _) => throw new FormattingException(unavailable, cancellation), static _ => Location.None);
                    context.RegisterSourceOutput(transformed, static (_, _) => { });
                    break;
                case "Value":
                    var value = GeneratorStageGuard.Select<Compilation, int>(context, context.CompilationProvider, "TestFormatting",
                        (_, _) => throw new FormattingException(unavailable, cancellation), 42);
                    context.RegisterSourceOutput(value, static (_, _) => { });
                    break;
                case "Request":
                    var requests = GeneratorStageGuard.SelectTrackedSourceRequest<int, Request>(context, values, "TestFormatting",
                        (_, _) => throw new FormattingException(unavailable, cancellation), static _ => Location.None);
                    context.RegisterSourceOutput(requests, static (_, _) => { });
                    break;
                case "Output":
                    GeneratorStageGuard.RegisterSourceOutput(context, values, "TestFormatting", static _ => null!,
                        (_, _) => throw new FormattingException(unavailable, cancellation));
                    break;
                case "Initialize":
                    try { throw new FormattingException(unavailable, cancellation); }
                    catch (Exception exception) when (GeneratorStageGuard.CanReport(exception, CancellationToken.None))
                    { GeneratorStageGuard.RegisterInitializationFailure(context, "TestFormatting", exception); }
                    break;
                default:
                    throw new ArgumentOutOfRangeException(nameof(stage));
            }
        }
    }

    private sealed record Request(string HintName) : IGeneratedSourceRequest;

    private sealed class FormattingException(string unavailable, CancellationTokenSource? cancellation) : Exception
    {
        public override string Message => unavailable is "Message" or "Both" or "Null"
            ? Unavailable("message")! : "original failure";
        public override string ToString() => unavailable == "Message" ? "FormattingException: original details" : Unavailable("details")!;
        public override string? StackTrace => unavailable is "Both" or "Null" or "StackTrace"
            ? Unavailable("stack trace") : "   at OriginalStage.Run()";

        private string? Unavailable(string part)
        {
            if (cancellation is not null && (unavailable != "StackTrace" || part == "stack trace"))
            {
                cancellation.Cancel();
                throw new OperationCanceledException(cancellation.Token);
            }
            if (unavailable == "Null") return null;
            throw new InvalidOperationException("Cannot format " + part);
        }
    }
}
