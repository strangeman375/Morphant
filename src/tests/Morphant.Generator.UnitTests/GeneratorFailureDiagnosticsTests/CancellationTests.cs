using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests;

[TestFixture]
internal sealed class CancellationTests
{
    [TestCase("Values")]
    [TestCase("Value")]
    [TestCase("Output")]
    public void Driver_propagates_requested_cancellation_and_can_retry(string stage)
    {
        using var cancellation = new CancellationTokenSource();
        var generator = new CancellationGenerator(stage, cancellation);
        GeneratorDriver driver = CSharpGeneratorDriver.Create(generator);
        var compilation = CreateCompilation();

        Assert.Throws<OperationCanceledException>(() =>
            driver.RunGeneratorsAndUpdateCompilation(compilation, out _, out _, cancellation.Token));

        generator.Fail = false;
        driver = driver.RunGeneratorsAndUpdateCompilation(compilation, out var output, out var diagnostics);
        var result = driver.GetRunResult().Results.Single();

        Assert.Multiple(() =>
        {
            Assert.That(diagnostics, Is.Empty);
            Assert.That(result.Exception, Is.Null);
            Assert.That(output.GetDiagnostics().Where(static diagnostic =>
                diagnostic.Severity is DiagnosticSeverity.Warning or DiagnosticSeverity.Error), Is.Empty);
            Assert.That(result.GeneratedSources.Select(static source => source.HintName),
                Is.EqualTo(new[] { "Healthy.g.cs" }));
            Assert.That(result.GeneratedSources.Single().SourceText.ToString(),
                Is.EqualTo("// <auto-generated />\r\n#nullable enable\r\n\r\n// Healthy\r\n"));
        });
    }

    [TestCase("Values")]
    [TestCase("Value")]
    [TestCase("Output")]
    public void Driver_reports_unrequested_cancellation_as_a_failure(string stage)
    {
        GeneratorDriver driver = CSharpGeneratorDriver.Create(new CancellationGenerator(stage));
        driver = driver.RunGeneratorsAndUpdateCompilation(CreateCompilation(), out var output, out var diagnostics);
        var result = driver.GetRunResult().Results.Single();
        var diagnostic = diagnostics.Single();
        var reportName = diagnostic.Properties["ReportHintName"];

        Assert.Multiple(() =>
        {
            Assert.That(result.Exception, Is.Null);
            Assert.That(diagnostic.Id, Is.EqualTo("MORPH0057"));
            Assert.That(diagnostic.Severity, Is.EqualTo(DiagnosticSeverity.Error));
            Assert.That(diagnostic.Location, Is.EqualTo(Location.None));
            Assert.That(diagnostic.AdditionalLocations, Is.Empty);
            Assert.That(diagnostic.GetMessage(), Is.EqualTo(
                "Morphant generator 0.4.0 failed unexpectedly in stage 'TestCancellation': " +
                "Morphant.Generator.UnitTests.GeneratorFailureDiagnosticsTests.CancellationTests+UnrequestedCancellation: " +
                "deliberate cancellation. Full exception details are available in generated file '" + reportName + "'."));
            Assert.That(result.GeneratedSources.Select(static source => source.HintName).Order(StringComparer.Ordinal),
                Is.EqualTo((stage == "Value" ? new[] { reportName, "Healthy.g.cs" } : new[] { reportName })
                    .Order(StringComparer.Ordinal)));
            Assert.That(result.GeneratedSources.Single(source => source.HintName == reportName).SourceText.ToString(),
                Is.EqualTo("// <auto-generated />\r\n#nullable enable\r\n\r\n/*\r\n" +
                    "MORPH0057: Morphant generator 0.4.0 failed unexpectedly.\r\n" +
                    "Stage: TestCancellation\r\n\r\nUnrequestedCancellation: deliberate cancellation\r\n*/\r\n"));
            Assert.That(output.GetDiagnostics().Where(static diagnostic =>
                diagnostic.Severity is DiagnosticSeverity.Warning or DiagnosticSeverity.Error), Is.Empty);
        });
    }

    private static CSharpCompilation CreateCompilation() => CSharpCompilation.Create(
        "CancellationTests",
        [CSharpSyntaxTree.ParseText("#nullable enable\nclass Input { }", path: "Input.cs")],
        [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)],
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

    private sealed class CancellationGenerator(string stage, CancellationTokenSource? cancellation = null)
        : IIncrementalGenerator
    {
        public bool Fail { get; set; } = true;

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            switch (stage)
            {
                case "Values":
                    var values = GeneratorStageGuard.Select(context,
                        context.CompilationProvider.SelectMany(static (_, _) => ImmutableArray.Create(0)),
                        "TestCancellation", (_, token) => Execute(token), static _ => Location.None);
                    context.RegisterSourceOutput(values, static (output, _) => Emit(output));
                    break;
                case "Value":
                    var value = GeneratorStageGuard.Select(context, context.CompilationProvider,
                        "TestCancellation", (_, token) => Execute(token), fallback: 42);
                    context.RegisterSourceOutput(value, static (output, _) => Emit(output));
                    break;
                case "Output":
                    GeneratorStageGuard.RegisterSourceOutput(context, context.CompilationProvider,
                        "TestCancellation", "output", (output, _) =>
                        {
                            Execute(output.CancellationToken);
                            Emit(output);
                        });
                    break;
                default:
                    throw new ArgumentOutOfRangeException(nameof(stage));
            }
        }

        private int Execute(CancellationToken token)
        {
            if (Fail)
            {
                cancellation?.Cancel();
                token.ThrowIfCancellationRequested();
                throw new UnrequestedCancellation();
            }

            return 0;
        }

        private static void Emit(SourceProductionContext context) => context.AddSource("Healthy.g.cs",
            SourceText.From("// <auto-generated />\r\n#nullable enable\r\n\r\n// Healthy\r\n", Encoding.UTF8));
    }

    private sealed class UnrequestedCancellation() : OperationCanceledException("deliberate cancellation")
    {
        public override string ToString() => "UnrequestedCancellation: deliberate cancellation";
    }
}
