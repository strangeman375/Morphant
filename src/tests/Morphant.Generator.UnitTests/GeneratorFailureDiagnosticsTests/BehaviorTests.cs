    [Test]
    public void Reports_a_transform_failure_and_keeps_independent_output()
    {
        var run = Run(
            BrokenSource,
            new TransformFailureGenerator());
        var diagnostic = run.Result.Diagnostics.Single();
        var exceptionType = typeof(TestGeneratorException).FullName!;

        Assert.Multiple(() =>
        {
            Assert.That(run.Result.Exception, Is.Null);
            Assert.That(diagnostic.Id, Is.EqualTo("MORPH0057"));
            Assert.That(
                diagnostic.Severity,
                Is.EqualTo(DiagnosticSeverity.Error));
            Assert.That(
                diagnostic.GetMessage(),
                Is.EqualTo(
                    "Morphant generator 0.4.0 failed unexpectedly in " +
                    $"stage 'TestTransform': {exceptionType}: deliberate " +
                    "failure. Full exception details are available in " +
                    $"generated file '{TransformFailureHintName}'."));
            Assert.That(
                diagnostic.Location.SourceTree,
                Is.SameAs(run.InputTree));
            Assert.That(
                diagnostic.Location.SourceSpan.Start,
                Is.EqualTo(BrokenSource.IndexOf(
                    "BrokenMapper",
                    StringComparison.Ordinal)));
            Assert.That(
                diagnostic.Location.SourceSpan.Length,
                Is.EqualTo("BrokenMapper".Length));
            Assert.That(diagnostic.AdditionalLocations, Is.Empty);
            Assert.That(
                diagnostic.Properties,
                Is.EqualTo(
                    ImmutableDictionary<string, string?>.Empty
                        .Add("ExceptionDetails", ExceptionDetails)
                        .Add("ExceptionMessage", "deliberate failure")
                        .Add("ExceptionType", exceptionType)
                        .Add("GeneratorVersion", "0.4.0")
                        .Add(
                            "ReportHintName",
                            TransformFailureHintName)
                        .Add("StageName", "TestTransform")));
            Assert.That(
                SnapshotSources(run.Result),
                Is.EqualTo(new[]
                {
                    new GeneratedSource(
                        "HealthyMapper.g.cs",
                        NormalizeExpected(HealthyMapperOutput)),
                    new GeneratedSource(
                        TransformFailureHintName,
                        NormalizeExpected(TransformFailureReport))
                }));
        });
    }

    [Test]
    public void Rebinds_a_cached_failure_and_recovers_after_the_edit()
    {
        var first = Run(
            BrokenSource,
            new TransformFailureGenerator());
        var recreated = Run(
            BrokenSource,
            new TransformFailureGenerator(),
            first.Driver);
        var recovered = Run(
            RecoveredSource,
            new TransformFailureGenerator(),
            recreated.Driver);

        Assert.Multiple(() =>
        {
            Assert.That(
                recreated.Result.Diagnostics.Single().Location.SourceTree,
                Is.SameAs(recreated.InputTree));
            Assert.That(recreated.Result.Exception, Is.Null);
            Assert.That(recovered.Result.Exception, Is.Null);
            Assert.That(recovered.Result.Diagnostics, Is.Empty);
            Assert.That(
                SnapshotSources(recovered.Result),
                Is.EqualTo(new[]
                {
                    new GeneratedSource(
                        "HealthyMapper.g.cs",
                        NormalizeExpected(HealthyMapperOutput)),
                    new GeneratedSource(
                        "RecoveredMapper.g.cs",
                        NormalizeExpected(RecoveredMapperOutput))
                }));
        });
    }

    [Test]
    public void Failure_hint_is_stable_across_platform_source_forms()
    {
        const string lfSource =
            "#nullable enable\n" +
