    private static TestRun Run(
        string source,
        IIncrementalGenerator generator,
        GeneratorDriver? driver = null,
        string sourcePath = "TestCase.cs")
    {
        var parseOptions = new CSharpParseOptions(LanguageVersion.CSharp9);
        var syntaxTree = CSharpSyntaxTree.ParseText(
            SourceText.From(source, Encoding.UTF8),
            parseOptions,
            sourcePath);
        var compilation = CSharpCompilation.Create(
            "GeneratorFailureTests",
            [syntaxTree],
            FrameworkReferences,
            new CSharpCompilationOptions(
                OutputKind.DynamicallyLinkedLibrary,
                nullableContextOptions: NullableContextOptions.Enable));
        driver ??= CSharpGeneratorDriver.Create(
            [generator.AsSourceGenerator()],
            parseOptions: parseOptions);
        driver = driver.RunGeneratorsAndUpdateCompilation(
            compilation,
            out var outputCompilation,
            out var driverDiagnostics);
        var result = driver.GetRunResult().Results.Single();

        Assert.That(
            driverDiagnostics,
            Has.None.Matches<Diagnostic>(diagnostic =>
                diagnostic.Id is "CS8784" or "CS8785"));
        Assert.That(
            outputCompilation.GetDiagnostics(),
            Has.None.Matches<Diagnostic>(diagnostic =>
                diagnostic.Severity is
                    DiagnosticSeverity.Warning or DiagnosticSeverity.Error));

        return new TestRun(driver, result, syntaxTree);
    }

    private static void AssertFatalFailure(Exception exception)
    {
        Assert.That(
            () => GeneratorStageGuard.Execute<int, int>(
                0,
                "TestFatalFailure",
                (_, _) => throw exception,
                static _ => Location.None,
                CancellationToken.None),
            Throws.TypeOf(exception.GetType()));
    }

    private static GeneratedSource[] SnapshotSources(
        GeneratorRunResult result)
    {
        return result.GeneratedSources
            .Select(static source => new GeneratedSource(
                source.HintName,
                source.SourceText.ToString()))
            .OrderBy(static source => source.HintName, StringComparer.Ordinal)
            .ToArray();
    }

    private static string NormalizeExpected(string source) =>
        source.Replace("\r\n", "\n")
            .Replace('\r', '\n')
            .Replace("\n", "\r\n") +
        "\r\n";

    private static ImmutableArray<MetadataReference>
        BuildFrameworkReferences()
    {
        var trustedPlatformAssemblies =
            (string?)AppContext.GetData("TRUSTED_PLATFORM_ASSEMBLIES") ??
            throw new InvalidOperationException(
                "Trusted platform assemblies are unavailable.");

        return trustedPlatformAssemblies
            .Split(Path.PathSeparator)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Select(static path =>
                (MetadataReference)MetadataReference.CreateFromFile(path))
            .ToImmutableArray();
    }

    private sealed class TransformFailureGenerator : IIncrementalGenerator
    {
        public void Initialize(
            IncrementalGeneratorInitializationContext context)
        {
            var candidates = context.SyntaxProvider
                .CreateSyntaxProvider(
                    static (node, _) => node is ClassDeclarationSyntax,
                    static (syntaxContext, _) => new Candidate(
                        (ClassDeclarationSyntax)syntaxContext.Node))
                .WithComparer(CandidateComparer.Instance);
            var outputs = GeneratorStageGuard.Select(
                context,
                candidates,
                "TestTransform",
                Transform,
                static candidate =>
                    candidate.Declaration.Identifier.GetLocation());

            context.RegisterSourceOutput(
                outputs,
                static (productionContext, output) =>
                    productionContext.AddSource(
                        output.Name + ".g.cs",
                        SourceText.From(
                            output.Source,
                            Encoding.UTF8)));
        }

        private static TestOutput Transform(
            Candidate candidate,
            CancellationToken cancellationToken)
        {
            cancellationToken.ThrowIfCancellationRequested();
            var name = candidate.Declaration.Identifier.ValueText;

            if (name.StartsWith("Broken", StringComparison.Ordinal))
            {
                throw new TestGeneratorException();
            }

            return new TestOutput(name, BuildGeneratedOutput(name));
        }
    }

    private sealed class OutputFailureGenerator : IIncrementalGenerator
    {
        public void Initialize(
            IncrementalGeneratorInitializationContext context)
        {
            var outputs = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (syntaxContext, _) =>
                    ((ClassDeclarationSyntax)syntaxContext.Node)
                    .Identifier.ValueText);

            GeneratorStageGuard.RegisterSourceOutput(
                context,
                outputs,
                "TestOutput",
                static name => name.StartsWith(
                    "Broken",
                    StringComparison.Ordinal)
                        ? throw new InvalidOperationException(
                            "identity failed")
                        : name,
                static (productionContext, name) =>
                {
                    if (name.StartsWith("Broken", StringComparison.Ordinal))
                    {
                        throw new TestGeneratorException();
                    }

                    productionContext.AddSource(
                        name + ".g.cs",
                        SourceText.From(
                            BuildGeneratedOutput(name),
                            Encoding.UTF8));
                });
        }
    }

    private sealed class LocationlessFailureGenerator :
        IIncrementalGenerator
    {
        public void Initialize(
            IncrementalGeneratorInitializationContext context)
        {
            var names = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax,
                static (syntaxContext, _) =>
                    ((ClassDeclarationSyntax)syntaxContext.Node)
                    .Identifier.ValueText);
            var outputs = GeneratorStageGuard.Select(
                context,
                names,
                "TestLocationlessTransform",
                static (name, _) => name.StartsWith(
                    "Broken",
                    StringComparison.Ordinal)
                        ? throw new TestGeneratorException()
                        : new TestOutput(
                            name,
                            BuildGeneratedOutput(name)),
                static _ => Location.None);

            context.RegisterSourceOutput(
                outputs,
                static (productionContext, output) =>
                    productionContext.AddSource(
                        output.Name + ".g.cs",
                        SourceText.From(
                            output.Source,
                            Encoding.UTF8)));
        }
    }

    private static string BuildGeneratedOutput(string name)
    {
        return "// <auto-generated />\r\n" +
               "#nullable enable\r\n\r\n" +
               "// " + name + "\r\n";
    }

    private sealed class InitializationFailureGenerator :
        IIncrementalGenerator
    {
        public void Initialize(
            IncrementalGeneratorInitializationContext context)
        {
            try
            {
                throw new TestGeneratorException();
            }
            catch (Exception exception) when (
                GeneratorStageGuard.CanReport(
                    exception,
                    CancellationToken.None))
            {
                GeneratorStageGuard.RegisterInitializationFailure(
                    context,
                    "TestInitialize",
                    exception);
            }
        }
    }

    private sealed class ValueFailureGenerator : IIncrementalGenerator
    {
        public void Initialize(
            IncrementalGeneratorInitializationContext context)
        {
            var value = GeneratorStageGuard.Select<Compilation, int>(
                context,
                context.CompilationProvider,
                "TestValueTransform",
                static (_, _) => throw new TestGeneratorException(),
                fallback: 42);

            context.RegisterSourceOutput(
                value,
                static (productionContext, fallback) =>
                    productionContext.AddSource(
                        "FallbackOutput.g.cs",
                        SourceText.From(
                            "// <auto-generated />\r\n" +
                            "#nullable enable\r\n\r\n" +
                            "// Fallback: " + fallback + "\r\n",
                            Encoding.UTF8)));
        }
    }

    private sealed class CommentTerminatorFailureGenerator :
        IIncrementalGenerator
    {
        public void Initialize(
            IncrementalGeneratorInitializationContext context)
        {
            GeneratorStageGuard.RegisterInitializationFailure(
                context,
                "TestCommentTerminator",
                new CommentTerminatorException());
        }
    }

    private sealed class TestGeneratorException : Exception
    {
        public TestGeneratorException()
            : base("deliberate failure")
        {
        }

        public override string ToString() => ExceptionDetails;
    }

    private sealed class CommentTerminatorException : Exception
    {
        public CommentTerminatorException()
            : base("before */ after")
        {
        }

        public override string ToString() =>
            "CommentTerminatorException: before */ after";
    }

    private sealed class CandidateComparer : IEqualityComparer<Candidate>
    {
        public static CandidateComparer Instance { get; } = new();

        public bool Equals(Candidate left, Candidate right)
        {
            return StringComparer.Ordinal.Equals(
                left.Declaration.ToFullString(),
                right.Declaration.ToFullString());
        }

        public int GetHashCode(Candidate value)
        {
            return StringComparer.Ordinal.GetHashCode(
                value.Declaration.ToFullString());
        }
    }

    private readonly record struct Candidate(
        ClassDeclarationSyntax Declaration);

    private readonly record struct TestOutput(
        string Name,
        string Source);

    private readonly record struct TestRun(
        GeneratorDriver Driver,
        GeneratorRunResult Result,
        SyntaxTree InputTree);

    private readonly record struct GeneratedSource(
        string HintName,
        string Source);
