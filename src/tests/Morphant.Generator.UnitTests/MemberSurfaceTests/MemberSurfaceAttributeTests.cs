using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.MemberSurfaceTests;

[TestFixture]
internal sealed class MemberSurfaceAttributeTests
{
    [Test]
    public async Task Copies_only_applicable_Obsolete_attributes()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using System;
using System.ComponentModel;
using Morphant;

namespace TestCase
{
    public sealed class Source { }

    [Obsolete("Use CurrentDestination instead.")]
    public sealed class Destination
    {
        [Description("An ordinary attribute is not copied.")]
        public int Current { get; set; }

        [Obsolete("Legacy was removed.", true)]
        public int Legacy { get; set; }
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, {|CS0618:Destination|}>();
    }
}
""";

        // lang=c#
        const string members =
"""
// <auto-generated />
#nullable enable

namespace Morphant.Generated.Types.N_TestCase.Plans
{
    /// <summary>
    /// Maps members of <see cref="global::TestCase.Destination"/>.
    /// </summary>
    [global::System.ObsoleteAttribute("Use CurrentDestination instead.")]
    internal sealed record DestinationMembers
    {
        /// <summary>
        /// Maps <see cref="global::TestCase.Destination.Current"/>.
        /// </summary>
        public global::Morphant.Members.Member<int> Current
        {
            get => null!;
            set { }
        }

        /// <summary>
        /// Maps <see cref="global::TestCase.Destination.Legacy"/>.
        /// </summary>
        [global::System.ObsoleteAttribute("Legacy was removed.", true)]
        public global::Morphant.Members.Member<int> Legacy
        {
            get => null!;
            set { }
        }

        public bool Equals(DestinationMembers? other) => false;

        public override int GetHashCode() => 0;

        public override string ToString() => string.Empty;

        private bool PrintMembers(global::System.Text.StringBuilder builder) => false;
    }
}
""";

        // lang=c#
        const string extension =
"""
// <auto-generated />
#nullable enable

namespace Morphant
{
    internal static partial class MorphantGeneratedMappingExtensions
    {
        /// <summary>
        /// Defines destination member mappings.
        /// </summary>
        /// <typeparam name="TMapper">A type parameter from the mapping declaration.</typeparam>
        /// <param name="builder">The mapping to configure.</param>
        /// <param name="members">The member plan.</param>
        /// <returns>The same mapping builder.</returns>
        public static global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Members<TMapper>(
            this global::Morphant.MapperBuilderBase<global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}>> builder,
            global::Morphant.Delegates.Members<global::TestCase.Source, {|CS0618:global::Morphant.Generated.Types.N_TestCase.Plans.DestinationMembers|}> members)
            where TMapper : global::Morphant.TypeMapper<TMapper>
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Defines member mappings using the optional existing destination.
        /// </summary>
        /// <typeparam name="TMapper">A type parameter from the mapping declaration.</typeparam>
        /// <param name="builder">The mapping to configure.</param>
        /// <param name="members">The member plan.</param>
        /// <returns>The same mapping builder.</returns>
        public static global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Members<TMapper>(
            this global::Morphant.MapperBuilderBase<global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}>> builder,
            global::Morphant.Delegates.Members<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}, {|CS0618:global::Morphant.Generated.Types.N_TestCase.Plans.DestinationMembers|}> members)
            where TMapper : global::Morphant.TypeMapper<TMapper>
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Defines member mappings using the selected result.
        /// </summary>
        /// <typeparam name="TMapper">A type parameter from the mapping declaration.</typeparam>
        /// <param name="builder">The mapping to configure.</param>
        /// <param name="members">The member plan.</param>
        /// <returns>The same mapping builder.</returns>
        public static global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Members<TMapper>(
            this global::Morphant.MapperBuilderBase<global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}>> builder,
            global::Morphant.Delegates.Members<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}, {|CS0618:global::TestCase.Destination|}, {|CS0618:global::Morphant.Generated.Types.N_TestCase.Plans.DestinationMembers|}> members)
            where TMapper : global::Morphant.TypeMapper<TMapper>
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();

        /// <summary>
        /// Defines member mappings with access to the selected result and current mapping context.
        /// </summary>
        /// <typeparam name="TMapper">A type parameter from the mapping declaration.</typeparam>
        /// <param name="builder">The mapping to configure.</param>
        /// <param name="members">The member plan.</param>
        /// <returns>The same mapping builder.</returns>
        public static global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}> Members<TMapper>(
            this global::Morphant.MapperBuilderBase<global::Morphant.MappingBuilder<TMapper, global::TestCase.Source, {|CS0618:global::TestCase.Destination|}>> builder,
            global::Morphant.Delegates.Members<global::TestCase.Source, {|CS0618:global::TestCase.Destination|}, {|CS0618:global::TestCase.Destination|}, global::Morphant.Context.MappingContextMarker, {|CS0618:global::Morphant.Generated.Types.N_TestCase.Plans.DestinationMembers|}> members)
            where TMapper : global::Morphant.TypeMapper<TMapper>
            => throw new global::Morphant.Exceptions.RuntimeInvocationNotSupportedException();
    }
}
""";

        await MemberSurfaceGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.Member.TestCase_Destination.g.cs",
                members
            ),
            (
                "Morphant.Generated.MemberExtension.TestCase_Source__TestCase_Destination.g.cs",
                extension
            ));
    }
}
