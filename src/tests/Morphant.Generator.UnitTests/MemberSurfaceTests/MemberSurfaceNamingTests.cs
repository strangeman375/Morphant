"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

public sealed class Source { }

public sealed class Destination
{
    public int @required { get; set; }

    public int Clone { get; set; }

    public int EqualityContract { get; set; }

    public int PrintMembers { get; set; }

    public new int Equals { get; set; }

    public new int GetHashCode { get; set; }

    public new int ToString { get; set; }

    public int DestinationMembers { get; set; }
}

[MorphantMapper]
public partial class TestMapper : TypeMapper
{
    protected override void Configure(MapperBuilder builder) =>
        builder.Map<Source, Destination>();
}
""";

        // lang=c#
        const string members =
"""
// <auto-generated />
#nullable enable

namespace Morphant.Generated
{
    /// <summary>
    /// Maps members of <see cref="global::Destination"/>.
    /// </summary>
