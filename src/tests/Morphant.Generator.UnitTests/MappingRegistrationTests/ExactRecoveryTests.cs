using Microsoft.CodeAnalysis;

namespace Morphant.Generator.UnitTests.MappingRegistrationTests;

[TestFixture]
internal sealed class ExactRecoveryTests
{
    [Test]
    public void Unavailable_only_mapper_generates_no_artifacts()
    {
        // lang=c#
        const string source =
"""
#nullable enable

using Morphant;

#pragma warning disable CS1591

namespace TestCase;

public partial class Container
{
    private sealed class Source { }
    public sealed class Destination { }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper<TestMapper>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        var result = MappingRegistrationGeneratorTest.Run(source);

        Assert.Multiple(() =>
        {
            Assert.That(
                result.Diagnostics.Select(static diagnostic => diagnostic.Id),
                Is.EqualTo(new[] { "MORPH0011" }));
            Assert.That(result.GeneratedSources, Is.Empty);
            Assert.That(result.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    [Test]
    public void Unsupported_authoritative_duplicate_generates_the_exact_stub()
    {
        // lang=c#
        const string source =
"""
#nullable enable

using Morphant;

#pragma warning disable CS1591, MORPH0012, MORPH0013

namespace TestCase;

public sealed class Destination { }

[MorphantMapper]
public partial class TestMapper<T> : TypeMapper<TestMapper<T>>
{
    protected override void Configure(MapperBuilder builder)
    {
        builder.Map<T, Destination>();
        builder.Map<T, Destination>();
    }
}
""";

        // lang=c#
        const string expectedMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper<T> :
        global::Morphant.ITypeMapper<T, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(T) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<T, global::TestCase.Destination>.Create(
            T? source,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingConfigurationException(
                global::Morphant.Context.MappingOperation.Create,
                typeof(T),
                typeof(global::TestCase.Destination),
                "The source type 'T' is not supported as a mapping root because it is a root type parameter.");

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<T, global::TestCase.Destination>.Update(
            T? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingConfigurationException(
                global::Morphant.Context.MappingOperation.Update,
                typeof(T),
                typeof(global::TestCase.Destination),
                "The source type 'T' is not supported as a mapping root because it is a root type parameter.");
    }
}
""";

        var result = MappingRegistrationGeneratorTest.Run(
            source,
            diagnosticOptions: new Dictionary<string, ReportDiagnostic>
            {
                ["MORPH0012"] = ReportDiagnostic.Suppress,
                ["MORPH0013"] = ReportDiagnostic.Suppress
            });

        Assert.Multiple(() =>
        {
            Assert.That(result.EffectiveDiagnostics, Is.Empty);
            Assert.That(
                result.GeneratedSources.Select(static generated =>
                    (generated.HintName, generated.SourceText.ToString())),
                Is.EqualTo(new[]
                {
                    (
                        "Morphant.Generated.TypeMapper." +
                        "TestCase_TestMapper_1.g.cs",
                        NormalizeExpected(expectedMapper))
                }));
            Assert.That(result.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    private static string NormalizeExpected(string source)
    {
        return source.ReplaceLineEndings("\r\n") + "\r\n";
    }
}
