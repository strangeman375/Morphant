    [Test]
    public void Suppression_or_warning_does_not_restore_an_invalid_mapping()
    {
        var visible = MappingRegistrationGeneratorTest.Run(InvalidSource);
        var suppressed = MappingRegistrationGeneratorTest.Run(
            InvalidSource,
            diagnosticOptions: new Dictionary<string, ReportDiagnostic>
            {
                ["MORPH0060"] = ReportDiagnostic.Suppress
            });
        var warning = MappingRegistrationGeneratorTest.Run(
            InvalidSource,
            diagnosticOptions: new Dictionary<string, ReportDiagnostic>
            {
                ["MORPH0060"] = ReportDiagnostic.Warn
            });

        Assert.Multiple(() =>
        {
            Assert.That(
                visible.EffectiveDiagnostics.Single().Severity,
                Is.EqualTo(DiagnosticSeverity.Error));
            Assert.That(suppressed.EffectiveDiagnostics, Is.Empty);
            Assert.That(
                warning.EffectiveDiagnostics.Single().Severity,
                Is.EqualTo(DiagnosticSeverity.Warning));
            Assert.That(
                GeneratedSources(suppressed),
                Is.EqualTo(GeneratedSources(visible)));
            Assert.That(
                GeneratedSources(warning),
                Is.EqualTo(GeneratedSources(visible)));
            Assert.That(visible.CompilerWarningsAndErrors, Is.Empty);
            Assert.That(suppressed.CompilerWarningsAndErrors, Is.Empty);
            Assert.That(warning.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    [Test]
    public void Invalid_family_callback_cannot_become_a_shared_configuration()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase;

public sealed class Source<T>
{
    public T Value { get; set; } = default!;
}

public sealed class Destination<T>
{
    public T Value { get; set; } = default!;
}

[MorphantMapper]
public partial class ObjectMapper : TypeMapper<ObjectMapper>
{
    protected override void Configure(MapperBuilder builder) =>
        builder.Map<Source<object>, Destination<object>>();
}

[MorphantMapper]
public abstract partial class Family<TMapper, TState> : TypeMapper<TMapper>
    where TMapper : Family<TMapper, TState>
{
    protected override void Configure(MapperBuilder builder) =>
        builder.Map<Source<dynamic>, Destination<dynamic>>()
            .Convert(_ => new Destination<dynamic> { Value = "family" });
}
""";

        var result = MappingRegistrationGeneratorTest.Run(source);

        Assert.Multiple(() =>
        {
            Assert.That(
                result.Diagnostics.Select(static diagnostic => diagnostic.Id),
                Is.EqualTo(new[] { "MORPH0060" }));
            Assert.That(
                result.Diagnostics,
                Has.None.Matches<Diagnostic>(diagnostic =>
                    diagnostic.Id == "MORPH0018"));
            Assert.That(result.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    [Test]
    public void Actualizes_and_restores_the_family_parameter_rule()
    {
        var valid = MappingRegistrationGeneratorTest.Run(
            ActualizationSource.Replace("__TYPE__", "TState"));
        var invalid = MappingRegistrationGeneratorTest.Run(
            ActualizationSource.Replace("__TYPE__", "int"),
            driver: valid.Driver);
        var restored = MappingRegistrationGeneratorTest.Run(
            ActualizationSource.Replace("__TYPE__", "TState"),
            driver: invalid.Driver);

        Assert.Multiple(() =>
        {
            Assert.That(valid.Diagnostics, Is.Empty);
            Assert.That(
                invalid.Diagnostics.Select(static diagnostic =>
                    diagnostic.Id),
                Is.EqualTo(new[] { "MORPH0060" }));
            Assert.That(restored.Diagnostics, Is.Empty);
            Assert.That(
                GeneratedSources(restored),
                Is.EqualTo(GeneratedSources(valid)));
            Assert.That(valid.CompilerWarningsAndErrors, Is.Empty);
            Assert.That(invalid.CompilerWarningsAndErrors, Is.Empty);
            Assert.That(restored.CompilerWarningsAndErrors, Is.Empty);
        });
    }

    private static (string HintName, string Source)[] GeneratedSources(
        MappingRegistrationGeneratorResult result)
    {
        return result.GeneratedSources
            .Select(static generated =>
                (generated.HintName, generated.SourceText.ToString()))
            .ToArray();
    }

    private static string NormalizeExpected(string source)
    {
        return source.ReplaceLineEndings("\r\n") + "\r\n";
    }

