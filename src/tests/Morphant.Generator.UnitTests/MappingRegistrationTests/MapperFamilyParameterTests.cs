    [Test]
    public void Reports_a_family_parameter_absent_from_the_pair()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source { }
    public sealed class Destination { }

    [MorphantMapper]
    public abstract partial class Family<TMapper, TState> : TypeMapper<TMapper>
        where TMapper : Family<TMapper, TState>
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string expectedMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Family<TMapper, TState> :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        protected override bool Supports(
            global::System.Type sourceType,
            global::System.Type destinationType) =>
                (sourceType == typeof(global::TestCase.Source) &&
                    destinationType == typeof(global::TestCase.Destination)) ||
                base.Supports(sourceType, destinationType);

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Create(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingConfigurationException(
                global::Morphant.Context.MappingOperation.Create,
                typeof(global::TestCase.Source),
                typeof(global::TestCase.Destination),
                "The mapper family type parameter 'TState' must occur in the source or destination type of this mapping.");

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Update(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
            => throw new global::Morphant.Exceptions.MappingConfigurationException(
                global::Morphant.Context.MappingOperation.Update,
                typeof(global::TestCase.Source),
                typeof(global::TestCase.Destination),
                "The mapper family type parameter 'TState' must occur in the source or destination type of this mapping.");
    }
}
""";

        var result = MappingRegistrationGeneratorTest.Run(
            source,
            LanguageVersion.CSharp9);
        var diagnostic = result.Diagnostics.Single();

        Assert.Multiple(() =>
        {
            Assert.That(diagnostic.Id, Is.EqualTo("MORPH0060"));
            Assert.That(
                diagnostic.GetMessage(),
                Is.EqualTo(
                    "Mapper family type parameter 'TState' must occur in " +
                    "the source or destination type of mapping " +
                    "'TestCase.Source -> TestCase.Destination'."));
            Assert.That(
                MappingRegistrationGeneratorTest.SourceText(
                    diagnostic.Location),
                Is.EqualTo("Map"));
            Assert.That(
                MappingRegistrationGeneratorTest.SourceText(
                    diagnostic.AdditionalLocations.Single()),
                Is.EqualTo("TState"));
            Assert.That(
                GeneratedSources(result),
                Is.EqualTo(new[]
                {
                    (
                        "Morphant.Generated.TypeMapper." +
                        "TestCase_Family_2.g.cs",
                        NormalizeExpected(expectedMapper))
                }));
            Assert.That(result.CompilerWarningsAndErrors, Is.Empty);
        });
    }

