using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.PairConfigurationTests;

[TestFixture]
internal sealed class PairConfigurationSettingsTests
{
    [Test]
    public async Task Keeps_last_local_root_and_map_setting_calls_without_resolving_inheritance()
    {
        // lang=c#
        const string source =
"""
#nullable enable
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source { }

    public sealed class Destination
    {
        public int Value { get; set; }
    }

    public sealed class OtherSource { }

    public sealed class OtherDestination { }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MappingMode(MappingMode.Create);
            builder.NullSourceHandling(NullSourceHandling.Throw);
            builder.ConstructorSelection(ConstructorSelection.Largest);

            builder.Map<Source, Destination>(MappingMode.Update)
                .Construct(source => default!)
                .NullSourceHandling(NullSourceHandling.ReturnDestination)
                .NullDestinationHandling(NullDestinationHandling.Throw)
                .ConstructorSelection(ConstructorSelection.Greediest)
                .Members((source, previous) => default!)
                .MemberSelection(MemberSelection.Auto)
                .MemberSelection(MemberSelection.Explicit)
                .UnmappedMemberValidation(UnmappedMemberValidation.Strict);

            builder.Map<OtherSource, OtherDestination>((MappingMode)8);

            builder.MappingMode(MappingMode.Update);
            builder.NullSourceHandling(NullSourceHandling.Default);
            builder.NullDestinationHandling(NullDestinationHandling.Create);
            builder.ConstructorSelection(ConstructorSelection.Unambiguous);
            builder.MemberSelection(MemberSelection.Explicit);
            builder.UnmappedMemberValidation(UnmappedMemberValidation.Destination);
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

// Mappers: 1
// Mapper 0: TestCase.TestMapper
// Unifiable: False
// Root settings: MappingMode=Explicit(Update); NullSourceHandling=Explicit(Default); NullDestinationHandling=Explicit(Create); ConstructorSelection=Explicit(Unambiguous); MemberSelection=Explicit(Explicit); UnmappedMemberValidation=Explicit(Destination)
// Pairs: 2
// Pair 0: global::TestCase.Source -> global::TestCase.Destination
// Map: builder.Map<Source, Destination>(MappingMode.Update)
// Map settings: MappingMode=Explicit(Update); NullSourceHandling=Explicit(ReturnDestination); NullDestinationHandling=Explicit(Throw); ConstructorSelection=Explicit(Greediest); MemberSelection=Explicit(Explicit); UnmappedMemberValidation=Explicit(Strict)
// Declarative: Constructs=1; Members=1
// Construct 0: Form=Source; Inputs=(global::TestCase.Source); Output=global::TestCase.Morphant.Generated.DestinationConstruction; Operation=AnonymousFunction; Syntax=source => default!
// Members 0: Form=SourceAndPrevious; Inputs=(global::TestCase.Source, global::Morphant.Option<global::TestCase.Destination>); Output=global::TestCase.Morphant.Generated.DestinationMembers; Operation=AnonymousFunction; Syntax=(source, previous) => default!
// Manual: Converts=0
// IncludeBase: 0
// Conflicts: None
// Pair 1: global::TestCase.OtherSource -> global::TestCase.OtherDestination
// Map: builder.Map<OtherSource, OtherDestination>((MappingMode)8)
// Map settings: MappingMode=Explicit(Invalid); NullSourceHandling=Unset; NullDestinationHandling=Unset; ConstructorSelection=Unset; MemberSelection=Unset; UnmappedMemberValidation=Unset
// Declarative: Constructs=0; Members=0
// Manual: Converts=0
// IncludeBase: 0
// Conflicts: None
""";

        await PairConfigurationGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            expected);
    }
}
