using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperTests;

[TestFixture]
internal sealed class TypeMapperConventionOnlyBridgeTests
{
    [Test]
    public void Production_generator_composes_the_surface_with_the_mapper_bridge()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return MapNewImpl(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return MapNewImpl(source, context);
            }

            return destination;
        }

        private global::TestCase.Destination MapNewImpl(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination();
        }
    }
}
""";

        var generated = ConstructionSurfaceCompilationTest
            .RunProductionAndGetGeneratedSources(
                LanguageVersion.CSharp9,
                source);

        Assert.That(
            generated.Keys,
            Is.EquivalentTo(new[]
            {
                "Morphant.Generated.Construction.TestCase_Destination.g.cs",
                "Morphant.Generated.MappingExtension.TestCase_Source__TestCase_Destination.g.cs",
                "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs",
            }));
        Assert.That(
            NormalizeNewLines(generated[
                "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs"]),
            Is.EqualTo(NormalizeNewLines(expected)));
    }

    private static string NormalizeNewLines(string value)
    {
        return value
            .Replace("\r\n", "\n")
            .Replace('\r', '\n')
            .TrimEnd('\n');
    }
}
