    [Test]
    public async Task Resolves_map_then_mapper_then_assembly_precedence()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class AssemblyDestination
    {
    }

    public sealed class RootDestination
    {
    }

    public sealed class MappingDestination
    {
    }

    [MorphantMapper]
    public partial class AssemblyMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.NullSourceHandling(
                NullSourceHandling.ReturnDestination);
            builder.NullDestinationHandling(
                NullDestinationHandling.CreateNew);
            builder.Map<Source, AssemblyDestination>();
            builder.NullSourceHandling(
                NullSourceHandling.Default);
            builder.NullDestinationHandling(
                NullDestinationHandling.Default);
        }
    }

    [MorphantMapper]
    public partial class RootMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, RootDestination>();
            builder.NullSourceHandling(
                NullSourceHandling.ReturnDestination);
            builder.NullDestinationHandling(
                NullDestinationHandling.CreateNew);
        }
    }

    [MorphantMapper]
    public partial class MappingMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.NullSourceHandling(
                NullSourceHandling.Throw);
            builder.NullDestinationHandling(
                NullDestinationHandling.Throw);

            builder.Map<Source, MappingDestination>()
                .NullSourceHandling(
                    NullSourceHandling.ReturnNull)
                .NullDestinationHandling(
                    NullDestinationHandling.CreateNew);
        }
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssertWithAnalyzerConfig(
            LanguageVersion.CSharp9,
