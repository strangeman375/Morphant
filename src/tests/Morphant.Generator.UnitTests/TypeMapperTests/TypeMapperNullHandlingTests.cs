    private static string BuildExpectedSimpleMapper(
        string mapperName,
        string destinationName,
        string mapNewNullSourceStatement,
        string mapExistingNullSourceStatement,
        string nullDestinationStatement,
        bool useMapNewImpl = false)
    {
        var mapNewStatement = useMapNewImpl
            ? "return MapNewImpl(source, context);"
            : $"return new global::TestCase.{destinationName}();";
        var effectiveNullDestinationStatement =
            useMapNewImpl
                ? "return MapNewImpl(source, context);"
                : nullDestinationStatement;
        var mapNewImpl = useMapNewImpl
            ? $$"""


                         private global::TestCase.{{destinationName}}? MapNewImpl(
                             global::TestCase.Source source,
                             global::Morphant.MappingContext context)
                         {
                             return new global::TestCase.{{destinationName}}();
                         }
                 """
            : string.Empty;

        // lang=c#
        return $$"""
                 // <auto-generated />
                 #nullable enable

                 namespace TestCase
                 {
                     public partial class {{mapperName}} :
                         global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.{{destinationName}}>
                     {
                         /// <inheritdoc/>
                         global::TestCase.{{destinationName}}? global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.{{destinationName}}>.Map(
                             global::TestCase.Source? source,
                             global::Morphant.MappingContext context)
                         {
                             if (source is null)
                             {
                                 {{mapNewNullSourceStatement}}
                             }

                             {{mapNewStatement}}
                         }

                         /// <inheritdoc/>
                         global::TestCase.{{destinationName}}? global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.{{destinationName}}>.Map(
                             global::TestCase.Source? source,
                             global::TestCase.{{destinationName}}? destination,
                             global::Morphant.MappingContext context)
                         {
                             if (source is null)
                             {
                                 {{mapExistingNullSourceStatement}}
                             }

                             if (destination is null)
                             {
                                 {{effectiveNullDestinationStatement}}
                             }

                             return destination;
                         }{{mapNewImpl}}
                     }
                 }
                 """;
    }

