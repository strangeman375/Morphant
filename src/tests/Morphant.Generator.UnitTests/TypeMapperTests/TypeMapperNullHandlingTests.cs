    public void Defines_stable_public_enum_values()
    {
        Assert.Multiple(() =>
        {
            Assert.That(
                (int)NullSourceHandling.Default,
                Is.Zero);
            Assert.That(
                (int)NullSourceHandling.ReturnNull,
                Is.EqualTo(1));
            Assert.That(
                (int)NullSourceHandling.ReturnDestination,
                Is.EqualTo(2));
            Assert.That(
                (int)NullSourceHandling.Throw,
                Is.EqualTo(3));

            Assert.That(
                (int)NullDestinationHandling.Default,
                Is.Zero);
            Assert.That(
                (int)NullDestinationHandling.CreateNew,
                Is.EqualTo(1));
            Assert.That(
                (int)NullDestinationHandling.Throw,
                Is.EqualTo(2));
        });
    }

