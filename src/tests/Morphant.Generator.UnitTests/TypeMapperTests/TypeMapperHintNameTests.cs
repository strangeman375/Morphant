using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperTests;

[TestFixture]
internal sealed class TypeMapperHintNameTests
{
    [Test]
    public async Task Does_not_add_hash_without_hint_name_collision()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public partial class Container<TContainer>
    {
        [MorphantMapper]
        public partial class TestMapper<TMapper> : TypeMapper
        {
            protected override void Configure(MapperBuilder builder)
            {
                builder.Map<object, object>();
            }
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    partial class Container<TContainer>
    {
        public partial class TestMapper<TMapper> :
            global::Morphant.ITypeMapper<object, object>
        {
            object global::Morphant.ITypeMapper<object, object>.Map(
                object source,
                global::Morphant.MappingContext context)
                => throw new global::System.NotImplementedException();

            object global::Morphant.ITypeMapper<object, object>.Map(
                object source,
                object destination,
                global::Morphant.MappingContext context)
                => throw new global::System.NotImplementedException();
        }
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.TypeMapper.TestCase_Container_1_TestMapper_1.g.cs",
                expected
            ));
    }

    [Test]
    public async Task Adds_hash_only_for_sanitized_hint_name_collision()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

public sealed class Source
{
}

public sealed class Destination
{
}

namespace A_B
{
    [MorphantMapper]
    public partial class C : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();
        }
    }
}

namespace A
{
    [MorphantMapper]
    public partial class B_C : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();
        }
    }
}
""";

        // lang=c#
        const string expectedFirstMapper =
"""
// <auto-generated />
#nullable enable

namespace A
{
    public partial class B_C :
        global::Morphant.ITypeMapper<global::Source, global::Destination>
    {
        global::Destination global::Morphant.ITypeMapper<global::Source, global::Destination>.Map(
            global::Source source,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();

        global::Destination global::Morphant.ITypeMapper<global::Source, global::Destination>.Map(
            global::Source source,
            global::Destination destination,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();
    }
}
""";

        // lang=c#
        const string expectedSecondMapper =
"""
// <auto-generated />
#nullable enable

namespace A_B
{
    public partial class C :
        global::Morphant.ITypeMapper<global::Source, global::Destination>
    {
        global::Destination global::Morphant.ITypeMapper<global::Source, global::Destination>.Map(
            global::Source source,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();

        global::Destination global::Morphant.ITypeMapper<global::Source, global::Destination>.Map(
            global::Source source,
            global::Destination destination,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.TypeMapper.A_B_C.g.cs",
                expectedFirstMapper
            ),
            (
                "Morphant.Generated.TypeMapper.A_B_C__a143b4740e1429ca.g.cs",
                expectedSecondMapper
            ));
    }

    [Test]
    public async Task Adds_hash_only_for_case_insensitive_hint_name_collision()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    [MorphantMapper]
    public partial class mapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();
        }
    }

    [MorphantMapper]
    public partial class Mapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();
        }
    }
}
""";

        // lang=c#
        const string expectedUpperMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class Mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source source,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();

        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();
    }
}
""";

        // lang=c#
        const string expectedLowerMapper =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class mapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source source,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();

        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source source,
            global::TestCase.Destination destination,
            global::Morphant.MappingContext context)
            => throw new global::System.NotImplementedException();
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.TypeMapper.TestCase_Mapper.g.cs",
                expectedUpperMapper
            ),
            (
                "Morphant.Generated.TypeMapper.TestCase_mapper__ec18d90bb22d10e8.g.cs",
                expectedLowerMapper
            ));
    }
}
