    [Test]
    public async Task Generates_nested_type_mapper_inside_deep_generic_partial_hierarchy()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source<TOuter, TMiddle, TInner, TMapper>
    {
    }

    public sealed class Destination<TOuter, TMiddle, TInner, TMapper>
    {
    }

    public abstract partial class Outer<TOuter>
        where TOuter : class
    {
        protected internal sealed partial record Middle<TMiddle>
            where TMiddle : struct
        {
            public partial struct Inner<TInner>
                where TInner : unmanaged
            {
                [MorphantMapper]
                private sealed partial class TestMapper<TMapper> : TypeMapper
                    where TMapper : new()
                {
                    protected override void Configure(MapperBuilder builder)
                    {
                        builder.Map<
                            Source<TOuter, TMiddle, TInner, TMapper>,
                            Destination<TOuter, TMiddle, TInner, TMapper>>();
                    }
                }
            }
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    partial class Outer<TOuter>
    {
        partial record Middle<TMiddle>
        {
            partial struct Inner<TInner>
            {
                private partial class TestMapper<TMapper> :
                    global::Morphant.ITypeMapper<global::TestCase.Source<TOuter, TMiddle, TInner, TMapper>, global::TestCase.Destination<TOuter, TMiddle, TInner, TMapper>>
