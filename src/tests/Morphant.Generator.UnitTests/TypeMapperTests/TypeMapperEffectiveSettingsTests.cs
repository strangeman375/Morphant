using Microsoft.CodeAnalysis.CSharp;
using Morphant.Generator.UnitTests.TestUtils;

namespace Morphant.Generator.UnitTests.TypeMapperTests;

[TestFixture]
internal sealed class TypeMapperEffectiveSettingsTests
{
    [TestCase(null)]
    [TestCase("")]
    [TestCase("Default")]
    [TestCase("default")]
    public async Task Uses_library_default_when_assembly_mode_is_missing_empty_or_Default(
        string? assemblyMappingMode)
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MappingMode(MappingMode.Default);
            builder.Map<Source, Destination>(MappingMode.Default);
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>
    {
        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source? source,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            return MapNewImpl(source, context);
        }

        /// <inheritdoc/>
        global::TestCase.Destination global::Morphant.ITypeMapper<global::TestCase.Source, global::TestCase.Destination>.Map(
            global::TestCase.Source? source,
            global::TestCase.Destination? destination,
            global::Morphant.Context.MappingContext context)
        {
            if (source is null)
            {
                return default!;
            }

            if (destination is null)
            {
                return MapNewImpl(source, context);
            }

            return destination;
        }

        private global::TestCase.Destination MapNewImpl(
            global::TestCase.Source source,
            global::Morphant.Context.MappingContext context)
        {
            return new global::TestCase.Destination();
        }
    }
}
""";

        var expectedSource =
            (
                "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs",
                expected
            );

        if (assemblyMappingMode is null)
        {
            await TypeMapperGeneratorTest.RunAndAssert(
                LanguageVersion.CSharp9,
                source,
                expectedSource);
            return;
        }

        await TypeMapperGeneratorTest.RunAndAssertWithAnalyzerConfig(
            LanguageVersion.CSharp9,
            source,
            $$"""
is_global = true

build_property.MorphantMappingMode = {{assemblyMappingMode}}
""",
            expectedSource);
    }

    [Test]
    public async Task Resolves_map_then_mapper_then_assembly_precedence()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class AssemblyDestination
    {
    }

    public sealed class RootDestination
    {
    }

    public sealed class MappingDestination
    {
    }

    [MorphantMapper]
    public partial class AssemblyMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.MappingMode(MappingMode.Create);
            builder.Map<Source, AssemblyDestination>();
            builder.MappingMode(MappingMode.Default);
        }
    }

    [MorphantMapper]
    public partial class RootMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, RootDestination>();
            builder.Map<Source, MappingDestination>(
                MappingMode.Update);
            builder.MappingMode(MappingMode.Create);
        }
    }
}
""";

        // lang=c#
        const string assemblyMapperExpected =
"""
