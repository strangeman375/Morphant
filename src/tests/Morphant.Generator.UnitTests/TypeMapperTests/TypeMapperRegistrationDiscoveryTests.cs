    [Test]
    public async Task Does_not_generate_any_registration_from_non_linear_control_flow()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using System;
using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    public static class RuntimeCondition
    {
        public static bool Value => DateTime.UtcNow.Ticks > 0;

        public static string Text =>
            DateTime.UtcNow.Ticks > 0
                ? null
                : string.Empty;
    }

    public static class TestBuilderExtensions
    {
        public static MapperBuilder<TSource, TDestination> When<
            TSource,
            TDestination>(
            this MapperBuilder<TSource, TDestination> builder,
            bool condition) =>
            builder;

        public static MapperBuilder<TSource, TDestination> Value<
            TSource,
            TDestination>(
            this MapperBuilder<TSource, TDestination> builder,
            string value) =>
            builder;
    }

    [MorphantMapper]
    public partial class IfMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            if (RuntimeCondition.Value)
            {
                builder.Map<Source, Destination>();
            }
        }
    }

    [MorphantMapper]
    public partial class ConditionalExpressionMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            _ = RuntimeCondition.Value
                ? builder.Map<Source, Destination>()
                : builder.Map<Source, Destination>();
        }
    }

    [MorphantMapper]
    public partial class ConditionalArgumentMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>(
                RuntimeCondition.Value
                    ? MappingMode.MapNew
                    : MappingMode.MapExisting);
        }
    }

    [MorphantMapper]
    public partial class SwitchExpressionArgumentMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>(
                RuntimeCondition.Value switch
                {
                    true => MappingMode.MapNew,
                    false => MappingMode.MapExisting
                });
        }
    }

    [MorphantMapper]
    public partial class LogicalOperatorArgumentMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>()
                .When(
                    RuntimeCondition.Value &&
                    (RuntimeCondition.Value || RuntimeCondition.Value));
        }
    }

    [MorphantMapper]
    public partial class CoalesceArgumentMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>()
                .Value(RuntimeCondition.Text ?? string.Empty);
        }
    }

    [MorphantMapper]
    public partial class SwitchMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            switch (RuntimeCondition.Value)
            {
                case true:
                    builder.Map<Source, Destination>();
                    break;
                default:
                    break;
            }
        }
    }

    [MorphantMapper]
    public partial class LoopMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            while (RuntimeCondition.Value)
            {
                builder.Map<Source, Destination>();
                break;
            }
        }
    }

    [MorphantMapper]
    public partial class MixedMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>();

            if (RuntimeCondition.Value)
            {
                builder.Map<Source, Destination>();
            }
        }
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source);
    }

    [Test]
    public async Task Does_not_follow_indirect_registration_code()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using System;
using Morphant;

namespace TestCase
{
    public sealed class Source
    {
    }

    public sealed class Destination
    {
    }

    public static class TestTemplateExtensions
    {
        public static MapperBuilder<TSource, TDestination> Template<
            TSource,
            TDestination>(
            this MapperBuilder<TSource, TDestination> builder,
            Func<TSource, int> template) =>
            builder;
    }

    [MorphantMapper]
    public partial class LambdaMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            Action register = () => builder.Map<Source, Destination>();
            register();
        }
    }

    [MorphantMapper]
    public partial class CapturedBuilderMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>()
                .Template(source =>
                {
                    builder.Map<Source, Destination>();

                    return 0;
                });
        }
    }

    [MorphantMapper]
    public partial class BuilderArgumentMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, Destination>(GetMappingMode(builder));
        }

        private static MappingMode GetMappingMode(MapperBuilder builder) =>
            MappingMode.Default;
    }

    [MorphantMapper]
    public partial class LocalFunctionMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            void Register() => builder.Map<Source, Destination>();

            Register();
        }
    }

    [MorphantMapper]
    public partial class HelperMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            Register(builder);
        }

        private static void Register(MapperBuilder builder) =>
            builder.Map<Source, Destination>();
    }

    [MorphantMapper]
    public partial class BuilderAliasMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            var alias = builder;

            alias.Map<Source, Destination>();
        }
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source);
    }

