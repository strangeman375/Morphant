    [Test]
    public async Task Applies_modes_to_expression_and_block_templates()
    {
        // lang=c#
        const string source =
"""
#pragma warning disable CS1591

using System;
using Morphant;

namespace TestCase
{
    public sealed class Source
    {
        public int Value { get; set; }

        public string Text { get; set; } = null!;
    }

    public static class TemplateExtensions
    {
        public static MapperBuilder<TSource, TDestination> Template<
            TSource,
            TDestination>(
            this MapperBuilder<TSource, TDestination> builder,
            Func<TSource, TDestination> template) =>
            builder;
    }

    [MorphantMapper]
    public partial class TestMapper : TypeMapper
    {
        protected override void Configure(MapperBuilder builder)
        {
            builder.Map<Source, int>(MappingMode.MapNew)
                .Template(source =>
                {
                    var value = source.Value;
                    return value + 1;
                });

            builder.Map<Source, string>(MappingMode.MapExisting)
                .Template(source => source.Text);
        }
    }
}
""";

        // lang=c#
        const string expected =
"""
// <auto-generated />
#nullable enable

namespace TestCase
{
    public partial class TestMapper :
        global::Morphant.ITypeMapper<global::TestCase.Source, int>,
        global::Morphant.ITypeMapper<global::TestCase.Source, string>
    {
        /// <inheritdoc/>
        int global::Morphant.ITypeMapper<global::TestCase.Source, int>.Map(
            global::TestCase.Source? source,
            global::Morphant.MappingContext context)
            => MapByTemplate(source!);

        /// <inheritdoc/>
        int global::Morphant.ITypeMapper<global::TestCase.Source, int>.Map(
            global::TestCase.Source? source,
            int destination,
            global::Morphant.MappingContext context)
            => throw new global::System.NotSupportedException(
                "The effective MappingMode does not include MapExisting.");

        private int MapByTemplate(global::TestCase.Source source)
        {
            var value = source.Value;
            return value + 1;
        }

        /// <inheritdoc/>
        string? global::Morphant.ITypeMapper<global::TestCase.Source, string>.Map(
            global::TestCase.Source? source,
            global::Morphant.MappingContext context)
            => throw new global::System.NotSupportedException(
                "The effective MappingMode does not include MapNew.");

        /// <inheritdoc/>
        string? global::Morphant.ITypeMapper<global::TestCase.Source, string>.Map(
            global::TestCase.Source? source,
            string? destination,
            global::Morphant.MappingContext context)
            => source!.Text;
    }
}
""";

        await TypeMapperGeneratorTest.RunAndAssert(
            LanguageVersion.CSharp9,
            source,
            (
                "Morphant.Generated.TypeMapper.TestCase_TestMapper.g.cs",
                expected
            ));
    }

