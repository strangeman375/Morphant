using Microsoft.CodeAnalysis.CSharp;

namespace Morphant.Generator.TemplateSurface.TemplateType;

internal static class TemplateTypeEmitter
{
    private const string TypeAccessibility = "internal";

    public static string Emit(TemplateTypeModel model)
    {
        var writer = new CodeWriter();

        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();

        writer.OpenBlock($"namespace {model.TemplateNamespace}");

        if (!model.ConstructorFields.IsEmpty)
        {
            WriteConstructorParametersType(writer, model);
            writer.Line();
        }

        WriteTemplateType(writer, model);

        writer.CloseBlock();

        return writer.ToString();
    }

    private static void WriteConstructorParametersType(
        CodeWriter writer,
        TemplateTypeModel model)
    {
        var constructorMembersTypeReference = BuildTypeReference(
            Identifier(model.ConstructorParametersTypeName),
            model.TypeParameters);

        var destinationCref = XmlAttribute(
            model.DestinationDocumentation.Cref);

        WriteSummary(
            writer,
            "Contains mappings for constructor arguments of " +
            $"<see cref=\"{destinationCref}\"/>.");

        WriteTypeDeclaration(
            writer,
            $"{TypeAccessibility} sealed class " +
            constructorMembersTypeReference,
            model.TypeParameters);

        for (var i = 0; i < model.ConstructorFields.Length; i++)
        {
            var field = model.ConstructorFields[i];

            if (field.RequiresNullableAnnotationsDisabled &&
                (i == 0 ||
                 !model.ConstructorFields[i - 1]
                     .RequiresNullableAnnotationsDisabled))
            {
                writer.Line("#nullable disable annotations");
            }

            WriteSummary(
                writer,
                "Configures the " +
                $"<c>{XmlText(field.ParameterName)}</c> " +
                "constructor argument.");

            writer.Line(
                $"public global::Morphant.Members.ConstructorParameter<{field.TypeName}>" +
                (field.AcceptsNull ? "?" : string.Empty) +
                $" {Identifier(field.Name)} = null!;");

            var nextFieldRequiresNullableAnnotationsDisabled =
                i + 1 < model.ConstructorFields.Length &&
                model.ConstructorFields[i + 1]
                    .RequiresNullableAnnotationsDisabled;

            if (field.RequiresNullableAnnotationsDisabled &&
                !nextFieldRequiresNullableAnnotationsDisabled)
            {
                writer.Line("#nullable enable annotations");
            }

            if (i < model.ConstructorFields.Length - 1)
            {
                writer.Line();
            }
        }

        writer.CloseBlock();
    }

    private static void WriteTemplateType(
        CodeWriter writer,
        TemplateTypeModel model)
    {
        var templateTypeName = Identifier(model.TemplateTypeName);
        var templateTypeReference = BuildTypeReference(
            templateTypeName,
            model.TypeParameters);

        WriteTemplateTypeDocumentation(writer, model);

        WriteTypeDeclaration(
            writer,
            $"{TypeAccessibility} sealed record {templateTypeReference}",
            model.TypeParameters);

        WriteByConventionConstructor(
            writer,
            model,
            templateTypeName);

        writer.Line();

        WriteByFactoryConstructor(
            writer,
            model,
            templateTypeName);

        writer.Line();

        foreach (var constructor in model.Constructors)
        {
            WriteDestinationConstructorDocumentation(writer, constructor);

            var parameters = new string[constructor.Parameters.Length];
            var nullableAnnotationsDisabled =
                new bool[constructor.Parameters.Length];

            for (var i = 0; i < constructor.Parameters.Length; i++)
            {
                parameters[i] = FormatParameter(
                    constructor.Parameters[i]);
                nullableAnnotationsDisabled[i] =
                    constructor.Parameters[i]
                        .RequiresNullableAnnotationsDisabled;
            }

            WriteConstructor(
                writer,
                templateTypeName,
                parameters,
                nullableAnnotationsDisabled);

            writer.Line();
        }

        WriteTemplateMembers(writer, model.Members);

        writer.Line(
            $"public bool Equals({templateTypeReference}? other) => false;");
        writer.Line();

        writer.Line(
            "public override int GetHashCode() => 0;");
        writer.Line();

        writer.Line(
            "public override string ToString() => string.Empty;");
        writer.Line();

        writer.Line(
            "private bool PrintMembers(global::System.Text.StringBuilder builder) => false;");

        writer.CloseBlock();
    }

    private static void WriteTemplateMembers(
        CodeWriter writer,
        IReadOnlyList<TemplateMemberModel> members)
    {
        for (var i = 0; i < members.Count; i++)
        {
            var member = members[i];

            if (member.RequiresNullableAnnotationsDisabled &&
                (i == 0 ||
                 !members[i - 1].RequiresNullableAnnotationsDisabled))
            {
                writer.Line("#nullable disable annotations");
            }

            WriteTemplateMemberDocumentation(
                writer,
                member);

            if (member.ObsoleteAttributeSource is { } obsoleteAttribute)
            {
                writer.Line($"[{obsoleteAttribute}]");
            }

            writer.OpenBlock(
                $"public global::Morphant.Members.Member<{member.TypeName}>" +
                (member.AcceptsNull ? "? " : " ") +
                Identifier(member.Name));

            writer.Line("get => null!;");
            writer.Line("set { }");

            writer.CloseBlock();

            var nextMemberRequiresNullableAnnotationsDisabled =
                i + 1 < members.Count &&
                members[i + 1].RequiresNullableAnnotationsDisabled;

            if (member.RequiresNullableAnnotationsDisabled &&
                !nextMemberRequiresNullableAnnotationsDisabled)
            {
                writer.Line("#nullable enable annotations");
            }

            writer.Line();
        }
    }

    private static void WriteByConventionConstructor(
        CodeWriter writer,
        TemplateTypeModel model,
        string templateTypeName)
    {
        WriteSummary(
            writer,
            model.CanConstructDestination
                ? "Creates a destination instance using convention-based mapping."
                : "Configures convention-based mapping without selecting a destination constructor.");

        WriteParameterDocumentation(
            writer,
            "marker",
            "Selects convention-based mapping.");

        if (model.ConstructorFields.IsEmpty)
        {
            WriteConstructor(
                writer,
                templateTypeName,
                new[]
                {
                    "global::Morphant.Markers.ByConventionMarker marker"
                });

            return;
        }

        WriteParameterDocumentation(
            writer,
            "members",
            "Specifies optional mappings for constructor arguments.");

        WriteConstructor(
            writer,
            templateTypeName,
            new[]
            {
                "global::Morphant.Markers.ByConventionMarker marker",
                BuildTypeReference(
                    Identifier(model.ConstructorParametersTypeName),
                    model.TypeParameters) +
                "? members = null"
            });
    }

    private static void WriteByFactoryConstructor(
        CodeWriter writer,
        TemplateTypeModel model,
        string templateTypeName)
    {
        WriteSummary(
            writer,
            "Creates a destination instance using factory-based destination construction.");

        WriteParameterDocumentation(
            writer,
            "marker",
            "Selects factory-based construction.");

        WriteConstructor(
            writer,
            templateTypeName,
            new[]
            {
                $"global::Morphant.Markers.IByFactoryMarker<{model.DestinationTypeName}> marker"
            });
    }

    private static void WriteTemplateTypeDocumentation(
        CodeWriter writer,
        TemplateTypeModel model)
    {
        var documentation = model.DestinationDocumentation;
        var cref = XmlAttribute(documentation.Cref);

        if (documentation.HasDocumentation)
        {
            writer.Line(
                $"/// <inheritdoc cref=\"{cref}\"/>");

            return;
        }

        WriteSummary(
            writer,
            "Represents the Morphant mapping template for " +
            $"<see cref=\"{cref}\"/>.");
    }

    private static void WriteTemplateMemberDocumentation(
        CodeWriter writer,
        TemplateMemberModel member)
    {
        var documentation = member.Documentation;
        var cref = XmlAttribute(documentation.Cref);

        if (documentation.HasDocumentation)
        {
            writer.Line(
                $"/// <inheritdoc cref=\"{cref}\"/>");

            return;
        }

        WriteSummary(
            writer,
            $"Configures mapping for <see cref=\"{cref}\"/>.");
    }

    private static void WriteDestinationConstructorDocumentation(
        CodeWriter writer,
        TemplateConstructorModel constructor)
    {
        WriteSummary(
            writer,
            "Creates a destination instance using a corresponding constructor.");

        foreach (var parameter in constructor.Parameters)
        {
            WriteParameterDocumentation(
                writer,
                parameter.Name,
                BuildConstructorParameterDescription(parameter));
        }
    }

    private static string BuildConstructorParameterDescription(
        TemplateConstructorParameterModel parameter)
    {
        var description =
            "Configures the " +
            $"<c>{XmlText(parameter.Name)}</c> " +
            "constructor argument.";

        if (parameter.DefaultValueDisplay is not { } defaultValue)
        {
            return description;
        }

        return description +
               " If omitted, the destination constructor default value " +
               $"<c>{XmlText(defaultValue)}</c> is used.";
    }

    private static void WriteSummary(
        CodeWriter writer,
        string summary)
    {
        writer.Line("/// <summary>");
        writer.Line($"/// {summary}");
        writer.Line("/// </summary>");
    }

    private static void WriteParameterDocumentation(
        CodeWriter writer,
        string parameterName,
        string description)
    {
        writer.Line(
            $"/// <param name=\"{XmlAttribute(parameterName)}\">" +
            $"{description}</param>");
    }

    private static string XmlAttribute(string value)
    {
        return XmlText(value)
            .Replace("\"", "&quot;")
            .Replace("'", "&apos;");
    }

    private static string XmlText(string value)
    {
        return value
            .Replace("&", "&amp;")
            .Replace("<", "&lt;")
            .Replace(">", "&gt;");
    }

    private static string FormatParameter(
        TemplateConstructorParameterModel parameter)
    {
        var wrapperType =
            $"global::Morphant.Members.ConstructorParameter<{parameter.TypeName}>";

        if (parameter.AcceptsNull)
        {
            wrapperType += "?";
        }

        return parameter.IsOptional
            ? $"{wrapperType} {Identifier(parameter.Name)} = " +
              (parameter.AcceptsNull ? "null" : "null!")
            : $"{wrapperType} {Identifier(parameter.Name)}";
    }

    private static void WriteConstructor(
        CodeWriter writer,
        string typeName,
        IReadOnlyList<string> parameters,
        IReadOnlyList<bool>? nullableAnnotationsDisabled = null)
    {
        if (parameters.Count <= 1)
        {
            var parameter = parameters.Count == 0
                ? string.Empty
                : parameters[0];

            var annotationsDisabled =
                nullableAnnotationsDisabled is not null &&
                nullableAnnotationsDisabled.Count == 1 &&
                nullableAnnotationsDisabled[0];

            if (annotationsDisabled)
            {
                writer.Line("#nullable disable annotations");
            }

            writer.Line($"public {typeName}({parameter})");
            writer.EmptyBlock();

            if (annotationsDisabled)
            {
                writer.Line("#nullable enable annotations");
            }

            return;
        }

        writer.Line($"public {typeName}(");
        writer.Indent();

        var annotationsAreDisabled = false;

        for (var i = 0; i < parameters.Count; i++)
        {
            var parameterRequiresNullableAnnotationsDisabled =
                nullableAnnotationsDisabled is not null &&
                nullableAnnotationsDisabled[i];

            if (parameterRequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    parameterRequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");

                annotationsAreDisabled =
                    parameterRequiresNullableAnnotationsDisabled;
            }

            var ending = i == parameters.Count - 1
                ? ")"
                : ",";

            writer.Line(parameters[i] + ending);
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Unindent();
        writer.EmptyBlock();
    }

    private static void WriteTypeDeclaration(
        CodeWriter writer,
        string declaration,
        IReadOnlyList<TemplateTypeParameterModel> typeParameters)
    {
        if (typeParameters.All(
                static typeParameter =>
                    typeParameter.Constraints.IsEmpty))
        {
            writer.OpenBlock(declaration);
            return;
        }

        writer.Line(declaration);
        writer.Indent();

        var annotationsAreDisabled = false;

        foreach (var typeParameter in typeParameters)
        {
            if (typeParameter.Constraints.IsEmpty)
            {
                continue;
            }

            if (typeParameter.RequiresNullableAnnotationsDisabled !=
                annotationsAreDisabled)
            {
                writer.Line(
                    typeParameter.RequiresNullableAnnotationsDisabled
                        ? "#nullable disable annotations"
                        : "#nullable enable annotations");

                annotationsAreDisabled =
                    typeParameter.RequiresNullableAnnotationsDisabled;
            }

            writer.Line(
                $"where {Identifier(typeParameter.Name)} : " +
                string.Join(", ", typeParameter.Constraints));
        }

        if (annotationsAreDisabled)
        {
            writer.Line("#nullable enable annotations");
        }

        writer.Unindent();
        writer.Line("{");
        writer.Indent();
    }

    private static string BuildTypeReference(
        string typeName,
        IReadOnlyList<TemplateTypeParameterModel> typeParameters)
    {
        return typeParameters.Count == 0
            ? typeName
            : typeName +
              "<" +
              string.Join(
                  ", ",
                  typeParameters.Select(static typeParameter =>
                      Identifier(typeParameter.Name))) +
              ">";
    }

    private static string Identifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) != SyntaxKind.None ||
               SyntaxFacts.GetContextualKeywordKind(value) != SyntaxKind.None
            ? "@" + value
            : value;
    }
}
