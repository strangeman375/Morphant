using System.Text;

namespace Morphant.Generator.UnitTests.TestUtils;

internal static class TemplateTypeActualizationExpectedSource
{
    public static string Build(
        string templateNamespace = "TestCase.Morphant.Generated",
        string templateTypeName = "DestinationMorphantTemplate",
        string templateTypeReference = "DestinationMorphantTemplate",
        string destinationTypeName = "global::TestCase.Destination",
        string? destinationCref = null,
        bool destinationHasDocumentation = false,
        string declarationsBeforeTemplate = "",
        string typeParameterConstraints = "",
        string? byConventionConstructor = null,
        string destinationConstructors = "",
        string members = "")
    {
        var builder = new StringBuilder();
        destinationCref ??= destinationTypeName;

        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();
        builder.AppendLine($"namespace {templateNamespace}");
        builder.AppendLine("{");

        if (!string.IsNullOrEmpty(declarationsBeforeTemplate))
        {
            builder.AppendLine(declarationsBeforeTemplate);
            builder.AppendLine();
        }

        if (destinationHasDocumentation)
        {
            builder.AppendLine(
                $"    /// <inheritdoc cref=\"{destinationCref}\"/>");
        }
        else
        {
            builder.AppendLine("    /// <summary>");
            builder.AppendLine(
                "    /// Represents the Morphant mapping template for " +
                $"<see cref=\"{destinationCref}\"/>.");
            builder.AppendLine("    /// </summary>");
        }

        builder.AppendLine(
            $"    internal sealed record {templateTypeReference}");

        if (!string.IsNullOrEmpty(typeParameterConstraints))
        {
            builder.AppendLine(typeParameterConstraints);
        }

        builder.AppendLine("    {");
        builder.AppendLine(
            byConventionConstructor ??
            BuildDefaultByConventionConstructor(templateTypeName));
        builder.AppendLine();
        builder.AppendLine(
            BuildByFactoryConstructor(
                templateTypeName,
                destinationTypeName));

        if (!string.IsNullOrEmpty(destinationConstructors))
        {
            builder.AppendLine();
            builder.AppendLine(destinationConstructors);
        }

        if (!string.IsNullOrEmpty(members))
        {
            builder.AppendLine();
            builder.AppendLine(members);
        }

        builder.AppendLine();
        builder.AppendLine(
            $"        public bool Equals({templateTypeReference}? other) => false;");
        builder.AppendLine();
        builder.AppendLine("        public override int GetHashCode() => 0;");
        builder.AppendLine();
        builder.AppendLine(
            "        public override string ToString() => string.Empty;");
        builder.AppendLine();
        builder.AppendLine(
            "        private bool PrintMembers(global::System.Text.StringBuilder builder) => false;");
        builder.AppendLine("    }");
        builder.AppendLine("}");

        return builder.ToString();
    }

    public static string BuildDefaultByConventionConstructor(
        string templateTypeName)
    {
        return
$$"""
        /// <summary>
        /// Creates a destination instance using convention-based mapping.
        /// </summary>
        /// <param name="marker">Selects convention-based mapping.</param>
        public {{templateTypeName}}(global::Morphant.Markers.ByConventionMarker marker)
        {
        }
""";
    }

    public static string BuildByConventionConstructorWithMembers(
        string templateTypeName,
        string constructorMembersTypeReference)
    {
        return
$$"""
        /// <summary>
        /// Creates a destination instance using convention-based mapping.
        /// </summary>
        /// <param name="marker">Selects convention-based mapping.</param>
        /// <param name="members">Specifies optional mappings for constructor arguments.</param>
        public {{templateTypeName}}(
            global::Morphant.Markers.ByConventionMarker marker,
            {{constructorMembersTypeReference}}? members = null)
        {
        }
""";
    }

    private static string BuildByFactoryConstructor(
        string templateTypeName,
        string destinationTypeName)
    {
        return
$$"""
        /// <summary>
        /// Creates a destination instance using factory-based destination construction.
        /// </summary>
        /// <param name="marker">Selects factory-based construction.</param>
        public {{templateTypeName}}(global::Morphant.Markers.IByFactoryMarker<{{destinationTypeName}}> marker)
        {
        }
""";
    }
}
